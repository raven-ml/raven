(* The recurrence, in float64. *)
let recurrence alpha xs =
  let ys = Array.copy xs in
  for i = 1 to Array.length xs - 1 do
    ys.(i) <- ((1. -. alpha) *. ys.(i - 1)) +. (alpha *. xs.(i))
  done;
  ys

