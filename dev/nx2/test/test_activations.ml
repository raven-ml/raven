(* The distance from [r] to the next float of [dt]'s format away from zero. *)
let ulp (type s) (dt : (float, s) D.t) r =
  let r = Float.abs r in
  match dt with
  | D.Float32 ->
      let r = Int32.float_of_bits (Int32.bits_of_float r) in
      let b = Int32.bits_of_float r in
      if r >= 0x1p-126 then Int32.float_of_bits (Int32.succ b) -. r else 0x1p-149
  | _ -> if r >= 0x1p-1022 then Float.succ r -. r else 0x1p-1074

let representable (type s) (dt : (float, s) D.t) x =
  match dt with
  | D.Float32 -> Int32.float_of_bits (Int32.bits_of_float x) = x
  | _ -> true

(* [f]'s results at the reference points [dt] holds, each within [k] ulps of
   [pick]'s value, or that value's infinity where it overflows [dt]. *)
let within (type s) (dt : (float, s) D.t) k f pick () =
  let pts =
    List.filter (fun (x, _, _) -> representable dt x) (Array.to_list reference)
  in
  let xs = Array.of_list (List.map (fun (x, _, _) -> x) pts) in
  let got = Nx.to_array (f (value dt [| Array.length xs |] xs)) in
  List.iteri
    (fun i p ->
      let r = pick p and v = got.(i) in
      let rd = D.of_float dt r in
      let ok =
        if Float.abs rd = Float.infinity then v = rd
        else Float.abs (v -. r) <= k *. ulp dt r
      in
      if not ok then
        failf "at %h: %h, mpmath's %h, %.2f ulps beyond %g" xs.(i) v r
          (Float.abs (v -. r) /. ulp dt r)
          k)
    pts

