let law_ewma (xs, alpha) =
  let n = Array.length xs in
  let y = Nx.to_array (Nx.ewma ~alpha (Nx.create Nx.float64 [| n |] xs)) in
  let r = recurrence alpha xs in
  let rounds = Float.of_int (n + 4) in
  let big = ref 0. in
  Array.iteri
    (fun i x ->
      big := Float.max !big (Float.abs x);
      if Float.abs (y.(i) -. r.(i)) > rounds *. 0x1p-52 *. !big then
        failf "at %d: %h, the recurrence's %h" i y.(i) r.(i))
    xs

let law_prefix (xs, alpha) =
  let n = Array.length xs in
  let k = n / 2 + 1 in
  assume (n > 0);
  let whole = Nx.to_array (Nx.ewma ~alpha (Nx.create Nx.float64 [| n |] xs)) in
  let k = Stdlib.min k n in
  let prefix =
    Nx.to_array (Nx.ewma ~alpha (Nx.create Nx.float64 [| k |] (Array.sub xs 0 k)))
  in
  equal same_bits prefix (Array.sub whole 0 k)

