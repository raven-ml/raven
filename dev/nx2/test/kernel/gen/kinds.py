"""Fit nx_kinds.h's polynomials and write its f64 accuracy goldens.

    uv run dev/nx2/test/kernel/gen/kinds.py [--check]
    uv run dev/nx2/test/kernel/gen/kinds.py --fits [NAME ...]

The first form writes `dev/nx2/test/kernel/golden/kinds/<fn>.golden`, the
f64 points each transcendental kind is held to; with --check nothing is
written, and the run fails if a file would change.

A golden is a table of hexadecimal doubles, one row per point: the
arguments, then the value correctly rounded to binary64, or `nan`.

The second form prints the minimax fits that nx_kinds.h's polynomials
copy, each with its weighted error, coefficients from the constant term
up. A fit minimises the largest weighted error by Remez exchange over a
monomial basis, then rounds its coefficients all at once; an f32 fit also
rounds them one at a time from the constant term, refitting the rest to
absorb each rounding, and keeps the better. Fitting every polynomial takes
about twenty minutes.
"""

import argparse
