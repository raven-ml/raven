import sys
from pathlib import Path

import mpmath
from mpmath import mp, mpf

E = mpmath
HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "kinds"
HEADER = "# generated by dev/nx2/test/kernel/gen/kinds.py; do not edit\n"

# Rounding


def round_bits(x, p):
    """x rounded to p significant bits, to nearest, ties to even."""
    x = mpf(x)
    if x == 0:
        return mpf(0)
    m, e = E.frexp(x)
    return E.ldexp(E.nint(E.ldexp(m, p)), e - p)


def to_double(v):
    """v correctly rounded to binary64, subnormals and overflow included."""
    if E.isnan(v):
        return math.nan
    if E.isinf(v):
        return float(v)
    if v == 0:
        return 0.0
    m, e = E.frexp(v)
    if e > 1024:
        return math.copysign(math.inf, v)
    p = 53 if e - 1 >= -1022 else 53 - (-1022 - (e - 1))
    if p <= 0:
        return math.copysign(float(E.ldexp(E.nint(E.ldexp(v, 1074)), -1074)), v)
    r = E.ldexp(E.nint(E.ldexp(m, p)), e - p)
    if abs(r) >= E.ldexp(1, 1024):
        return math.copysign(math.inf, v)
    return float(r)


def hexf(x):
    return "nan" if x != x else x.hex()


def c_literal(x, fmt):
    s = float(x).hex()
    if s.startswith("-"):
        sign, s = "-", s[1:]
    else:
        sign = ""
    mant, exp = s.split("p")
    ip, _, frac = mant[2:].partition(".")
    frac = frac.rstrip("0")
    lit = f"{sign}0x{ip}" + (f".{frac}" if frac else "") + f"p{exp}"
    return lit + ("f" if fmt == "f32" else "")


# Remez exchange


def remez(target, exps, a, b, weight, iters=30):
    """Coefficients c of sum c_j t^exps[j] minimising max |w (target - p)|
    on [a, b], and that maximum."""
    a, b = mpf(a), mpf(b)
    n = len(exps)
    grid = max(2000, 60 * n)
    xs = [(a + b) / 2 - (b - a) / 2 * E.cos(E.pi * (i + mpf(1) / 3) / (n + mpf(2) / 3))
          for i in range(n + 1)]
    # a weight that vanishes at a node makes the system singular: move it
    xs = [x if abs(weight(x)) > mpf(10) ** -20 else x + (b - a) / (7 * n) for x in xs]
    ts = [a + (b - a) * i / grid for i in range(grid + 1)]
    tv = [target(t) for t in ts]
    wv = [weight(t) for t in ts]
    best = None
    for _ in range(iters):
        A = E.matrix(n + 1, n + 1)
        rhs = E.matrix(n + 1, 1)
        for i, x in enumerate(xs):
            for j, e in enumerate(exps):
                A[i, j] = x**e
            w = weight(x)
            A[i, n] = (-1) ** i / w if w != 0 else 0
            rhs[i] = target(x)
        try:
            sol = E.lu_solve(A, rhs)
        except ZeroDivisionError:
            break
        c = [sol[j] for j in range(n)]
        level = abs(sol[n])

        def err(t, tgt=None, w=None):
            tgt = target(t) if tgt is None else tgt
            w = weight(t) if w is None else w
            return w * (tgt - sum(cj * t**e for cj, e in zip(c, exps)))

        es = [err(t, tv[i], wv[i]) for i, t in enumerate(ts)]
        # one extremum per run of the error's sign
        runs, start = [], 0
        for i in range(1, grid + 1):
            if E.sign(es[i]) != E.sign(es[start]) and es[i] != 0:
                runs.append((start, i - 1))
                start = i
        runs.append((start, grid))
        ext = []
        for lo_i, hi_i in runs:
            k = max(range(lo_i, hi_i + 1), key=lambda i: abs(es[i]))
            lo, hi = ts[max(k - 1, 0)], ts[min(k + 1, grid)]
            for _ in range(30):
                m1, m2 = lo + (hi - lo) / 3, hi - (hi - lo) / 3
                if abs(err(m1)) < abs(err(m2)):
                    lo = m1
                else:
                    hi = m2
            t = (lo + hi) / 2
            if abs(err(t)) < abs(es[k]):
                t = ts[k]
            ext.append((t, err(t)))
        ext = [e for e in ext if e[1] != 0]
        while len(ext) > n + 1:
            ext.pop(0 if abs(ext[0][1]) < abs(ext[-1][1]) else -1)
        best = (c, max(abs(v) for _, v in ext))
        if len(ext) < n + 1 or best[1] <= level * (1 + mpf(10) ** -4):
            break
        xs = [t for t, _ in ext]
    return best


def max_error(target, exps, c, a, b, weight, grid=20000):
    a, b = mpf(a), mpf(b)
    worst = mpf(0)
    for i in range(grid + 1):
        t = a + (b - a) * i / grid
        e = abs(weight(t) * (target(t) - sum(cj * t**k for cj, k in zip(c, exps))))
        worst = max(worst, e)
    return worst


def fit(target, n, a, b, weight, fmt):
    """The coefficients and their error: rounded all at once, and for f32
    also one at a time from the constant term, refitting the rest to
    absorb each rounding; the better of the two."""
    exps = list(range(n))
    p = 24 if fmt == "f32" else 53
    c, _ = remez(target, exps, a, b, weight)
    best = [round_bits(x, p) for x in c]
    best = (best, max_error(target, exps, best, a, b, weight))
    if fmt == "f64":
        return best
    fixed, rest = [], exps
    while rest:
        def tgt(t, fixed=list(fixed)):
            return target(t) - sum(c * t**e for e, c in fixed)
        c, _ = remez(tgt, rest, a, b, weight)
        fixed.append((rest[0], round_bits(c[0], p)))
        rest = rest[1:]
    cs = [c for _, c in fixed]
    err = max_error(target, exps, cs, a, b, weight)
    return (cs, err) if err < best[1] else best


# The polynomials


def at0(f, v):
    return lambda t: v if t == 0 else f(t)


def log_t(z):
    s = E.sqrt(z)
    return (E.log((1 + s) / (1 - s)) - 2 * s) / (z * s)


def erf_g(a):
    return E.log(E.erfc(a)) + a * a


def fits():
    ln2 = E.log(2)
    r_exp = (-ln2 / 2 - mpf("1e-4"), ln2 / 2 + mpf("1e-4"))
    pio4 = (E.pi / 4) ** 2 * (1 + mpf("1e-3"))
    c0 = 2 / E.sqrt(E.pi)
    common = {
        # expm1 r = r + r^2 Q(r), relative to e^r
        "expQ": (at0(lambda r: (E.exp(r) - 1 - r) / r**2, mpf(1) / 2), r_exp,
                 lambda r: r**2 / E.exp(r)),
        # 2^r = 1 + r P(r), relative
        "exp2P": (at0(lambda r: (E.power(2, r) - 1) / r, ln2), (-mpf(1) / 2, mpf(1) / 2),
                  lambda r: abs(r) / E.power(2, r)),
        # log((1 + s)/(1 - s)) = 2s + s^3 T(s^2)
        "logT": (at0(log_t, mpf(2) / 3), (0, mpf("0.0295")), lambda z: 1),
        # T(z) = 2/3 + z T'(z)
        "logT'": (at0(lambda z: (log_t(z) - mpf(2) / 3) / z, mpf(2) / 5),
                  (0, mpf("0.0295")), lambda z: 1),
        # sin r = r + r^3 S(r^2), relative
        "sinS": (at0(lambda t: (E.sin(E.sqrt(t)) - E.sqrt(t)) / (t * E.sqrt(t)), -mpf(1) / 6),
                 (0, pio4), at0(lambda t: t * E.sqrt(t) / E.sin(E.sqrt(t)), 0)),
        # cos r = 1 - r^2/2 + r^4 C(r^2), relative
        "cosC": (at0(lambda t: (E.cos(E.sqrt(t)) - 1 + t / 2) / t**2, mpf(1) / 24),
                 (0, pio4), lambda t: t**2 / E.cos(E.sqrt(t))),
        # asin s = s + s^3 B(s^2), relative
        "asinB": (at0(lambda z: (E.asin(E.sqrt(z)) - E.sqrt(z)) / (z * E.sqrt(z)), mpf(1) / 6),
                  (0, mpf(1) / 4), at0(lambda z: z * E.sqrt(z) / E.asin(E.sqrt(z)), 0)),
    }
    atan_a = at0(lambda z: (E.atan(E.sqrt(z)) - E.sqrt(z)) / (z * E.sqrt(z)), -mpf(1) / 3)
    atan_w = at0(lambda z: z * E.sqrt(z) / E.atan(E.sqrt(z)), 0)
    # erf a = a (c0 + z E'(z)), relative
    erf_e = at0(lambda z: (E.erf(E.sqrt(z)) / E.sqrt(z) - c0) / z, -2 / (3 * E.sqrt(E.pi)))
    erf_w = at0(lambda z: z / (E.erf(E.sqrt(z)) / E.sqrt(z)), 0)
    out = []
    for name, n in [("expQ", 5), ("exp2P", 6), ("logT", 4), ("logT'", 3), ("sinS", 3),
                    ("cosC", 3), ("asinB", 5)]:
        tgt, (a, b), w = common[name]
        out.append(("f32", name, tgt, n, a, b, w, 0))
    out.append(("f32", "atanA", atan_a, 8, 0, 1, atan_w, 0))
    out.append(("f32", "erfE", erf_e, 6, 0, mpf("0.875") ** 2, erf_w, 0))
    out.append(("f32", "erfG", erf_g, 9, mpf("0.875"), mpf("3.92"), lambda a: 1, 0))
    for name, n in [("expQ", 10), ("exp2P", 12), ("logT", 8), ("logT'", 8), ("sinS", 6),
                    ("cosC", 6), ("asinB", 12)]:
        tgt, (a, b), w = common[name]
        out.append(("f64", name, tgt, n, a, b, w, 0))
    out.append(("f64", "atanA", atan_a, 11, 0, (mpf(7) / 16) ** 2, atan_w, 0))
    out.append(("f64", "erfE", erf_e, 14, 0, 1, erf_w, 0))
    # G on [1, 5.95] in u = a - 3, exact there; erf's error is erfc(a)
    # times G's, so G's is weighted by erfc(a) / erfc(1)
    out.append(("f64", "erfG", lambda u: erf_g(u + 3), 22, mpf(1) - 3, mpf("5.95") - 3,
                lambda u: E.erfc(u + 3) / E.erfc(1), 0))
    return out


def print_fits(names):
    mp.dps = 80
    for fmt, name, tgt, n, a, b, w, mid in fits():
        if names and name not in names and f"{fmt}:{name}" not in names:
            continue
        cs, err = fit(tgt, n, a, b, w, fmt)
        bits = -E.log(err, 2) if err > 0 else mpf("inf")
        centre = f", in u = a - {E.nstr(mid, 6)}" if mid else ""
        print(f"{fmt} {name}: error 2^-{E.nstr(bits, 3)}{centre}")
        print("  " + ", ".join(c_literal(c, fmt) for c in cs))
        sys.stdout.flush()


# Goldens


def f64_of_bits(u):
    return struct.unpack("<d", struct.pack("<Q", u))[0]


SPECIAL = [0.0, -0.0, math.inf, -math.inf, math.nan, 1.0, -1.0, 0.5, -0.5, 2.0, -2.0,
           f64_of_bits(1), -f64_of_bits(1), f64_of_bits(0x000FFFFFFFFFFFFF),
           f64_of_bits(0x0010000000000000), -f64_of_bits(0x0010000000000000),
           sys.float_info.max, -sys.float_info.max]


def neighbours(x, k=4):
    """x and the k doubles on each side of it."""
    if not math.isfinite(x):
        return [x]
    out, lo, hi = [x], x, x
    for _ in range(k):
        lo, hi = math.nextafter(lo, -math.inf), math.nextafter(hi, math.inf)
        out += [lo, hi]
    return out


def log_uniform(rng, n, lo_exp, hi_exp, signed=True):
    out = []
    for _ in range(n):
        x = math.ldexp(1 + rng.random(), rng.randint(lo_exp, hi_exp))
        out.append(-x if signed and rng.random() < 0.5 else x)
    return out


def uniform(rng, n, lo, hi):
    return [lo + (hi - lo) * rng.random() for _ in range(n)]


def unary_points(fn, rng):
    pts = list(SPECIAL)
    # where the function is defined: positive for the logarithms, within 1
    # for asin and acos
    signed = fn not in ("log", "log2", "log1p")
    top = -1 if fn in ("asin", "acos") else 1023
    pts += log_uniform(rng, 500, -1074, top, signed)
    pts += log_uniform(rng, 400, -60, min(top, 10), signed)
    edges = {
        "exp": [709.782712893384, -708.3964185322641, -745.1332191019411, 0.3465735902799726],
        "exp2": [1024.0, -1022.0, -1074.0, 0.5, 3.0, -3.0],
        "expm1": [709.782712893384, -37.42994775023705, float.fromhex("0x1p-54"), 0.3465735902799726],
        "log": [0.7071067811865476, 1.4142135623730951, 1.0],
        "log2": [0.7071067811865476, 1.4142135623730951, 1.0, 1024.0, float.fromhex("0x1p-1074")],
        "log1p": [-1.0, -0.2928932188134524, 0.41421356237309515, float.fromhex("0x1p-53")],
        "sin": [float.fromhex("0x1p28"), float.fromhex("0x1.6ac5b262ca1ffp+849"), math.pi, math.pi / 2],
        "cos": [float.fromhex("0x1p28"), float.fromhex("0x1.6ac5b262ca1ffp+849"), math.pi / 2, math.pi],
        "tan": [float.fromhex("0x1p28"), float.fromhex("0x1.6ac5b262ca1ffp+849"), math.pi / 4, math.pi / 2],
        "asin": [0.5, 1.0, -1.0], "acos": [0.5, -0.5, 1.0, -1.0],
        "atan": [0.4375, 0.6875, 1.1875, 2.4375, float.fromhex("0x1p54")],
        "sinh": [710.4758600739439, 0.3465735902799726, 1.0], "cosh": [710.4758600739439, 1.0],
        "tanh": [19.06154746539849, float.fromhex("0x1p-54")], "erf": [1.0, 1.75, 2.75, 4.0, 5.95, 5.921587195794507],
    }[fn]
    for e in edges:
        pts += neighbours(e) + neighbours(-e)
    core = {
        "exp": (-745, 710), "exp2": (-1075, 1025), "expm1": (-40, 710), "log": (0, 4),
        "log2": (0, 4), "log1p": (-1, 4), "sin": (-100, 100), "cos": (-100, 100),
        "tan": (-100, 100), "asin": (-1, 1), "acos": (-1, 1), "atan": (-4, 4),
        "sinh": (-711, 711), "cosh": (-711, 711), "tanh": (-20, 20), "erf": (-6, 6),
    }[fn]
    pts += uniform(rng, 300, *core)
    if fn in ("sin", "cos", "tan"):
        # near the multiples of pi/2 that reduce worst, and past the switch
        for k in [1, 2, 3, 4, 5, 6, 7, 355, 103993, 1 << 20, 1 << 27]:
            pts += neighbours(k * math.pi / 2, 2)
        pts += log_uniform(rng, 200, 28, 1023)
    return pts


def binary_points(fn, rng):
    pts = [(x, y) for x in SPECIAL for y in SPECIAL]
    if fn == "pow":
        for _ in range(1500):
            x = math.ldexp(1 + rng.random(), rng.randint(-1074, 1023))
            y = rng.choice([
                rng.uniform(-10, 10), float(rng.randint(-100, 100)), rng.randint(-40, 40) + 0.5,
                math.ldexp(1 + rng.random(), rng.randint(-60, 12)) * rng.choice([1, -1])])
            pts.append((-x if rng.random() < 0.2 and y == int(y) else x, y))
        for _ in range(500):
            # near 1 with large exponents, where log x carries the result
            x = 1 + rng.uniform(-1, 1) * math.ldexp(1, rng.randint(-52, -1))
            pts.append((x, rng.uniform(-1, 1) * math.ldexp(1, rng.randint(10, 60))))
        for _ in range(300):
            # results near the overflow and underflow thresholds
            x = rng.uniform(1.0001, 100)
            for t in (1023.99, -1021.9, -1074.5):
                pts.append((x, t / math.log2(x)))
    else:
        for _ in range(1500):
            y = math.ldexp(1 + rng.random(), rng.randint(-1074, 1023)) * rng.choice([1, -1])
            x = math.ldexp(1 + rng.random(), rng.randint(-1074, 1023)) * rng.choice([1, -1])
            pts.append((y, x))
        for _ in range(800):
            pts.append((rng.uniform(-4, 4), rng.uniform(-4, 4)))
    return pts


UNARY = {
    "exp": E.exp, "exp2": lambda x: E.power(2, x), "expm1": E.expm1, "log": E.log,
    "log2": lambda x: E.log(x, 2), "log1p": E.log1p, "sin": E.sin, "cos": E.cos,
    "tan": E.tan, "asin": E.asin, "acos": E.acos, "atan": E.atan, "sinh": E.sinh,
    "cosh": E.cosh, "tanh": E.tanh, "erf": E.erf,
}


def pow_ref(x, y):
    # C99 Annex F where mpmath's power differs
    if y == 0 or x == 1:
        return 1.0
    if math.isnan(x) or math.isnan(y):
        return math.nan
    if math.isinf(y):
        if abs(x) == 1:
            return 1.0
        return (math.inf if y > 0 else 0.0) if abs(x) > 1 else (0.0 if y > 0 else math.inf)
    odd = y == int(y) and int(y) % 2 == 1 if abs(y) < 2**53 else False
    integer = y == int(y)
    if x == 0 or math.isinf(x):
        big = (x == 0) == (y < 0)
        mag = math.inf if big else 0.0
        return math.copysign(mag, x) if odd else mag
    if x < 0 and not integer:
        return math.nan
    v = to_double(E.power(abs(mpf(x)), mpf(y)))
    return -v if x < 0 and odd else v


def atan2_ref(y, x):
    if math.isnan(x) or math.isnan(y):
        return math.nan
    if math.isinf(x) or math.isinf(y) or x == 0 or y == 0:
        return math.atan2(y, x)  # Annex F's exact special values
    return to_double(E.atan2(mpf(y), mpf(x)))


def unary_ref(fn, x):
    if math.isnan(x):
        return math.nan
    domain_nan = (fn in ("log", "log2") and x < 0) or (fn == "log1p" and x < -1) or (
        fn in ("asin", "acos") and abs(x) > 1) or (fn in ("sin", "cos", "tan") and math.isinf(x))
    if domain_nan:
        return math.nan
    if x == 0 and fn in ("log", "log2"):
        return -math.inf
    if x == -1 and fn == "log1p":
        return -math.inf
    if math.isinf(x):
        lim = {"exp": (0.0, math.inf), "exp2": (0.0, math.inf), "expm1": (-1.0, math.inf),
               "log": (math.nan, math.inf), "log2": (math.nan, math.inf),
               "log1p": (math.nan, math.inf), "atan": (-math.pi / 2, math.pi / 2),
               "sinh": (-math.inf, math.inf), "cosh": (math.inf, math.inf),
               "tanh": (-1.0, 1.0), "erf": (-1.0, 1.0)}[fn]
        return lim[1] if x > 0 else lim[0]
    if x == 0 and fn in ("exp", "exp2", "cos", "cosh"):
        return 1.0
    if x == 0:
        return x if fn != "acos" else to_double(E.pi / 2)
    return to_double(UNARY[fn](mpf(x)))


def goldens():
    mp.prec = 320
    files = {}
    for fn in UNARY:
        rng = random.Random(f"nx_kinds:{fn}")
        rows = [f"{hexf(x)}\t{hexf(unary_ref(fn, x))}\n" for x in unary_points(fn, rng)]
        files[fn] = HEADER + "x\tf\n" + "".join(rows)
    for fn, ref in (("pow", pow_ref), ("atan2", atan2_ref)):
        rng = random.Random(f"nx_kinds:{fn}")
        rows = [f"{hexf(a)}\t{hexf(b)}\t{hexf(ref(a, b))}\n" for a, b in binary_points(fn, rng)]
        cols = "x\ty\tf\n" if fn == "pow" else "y\tx\tf\n"
        files[fn] = HEADER + cols + "".join(rows)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--fits", nargs="*")
    args = ap.parse_args()
    if args.fits is not None:
        print_fits(args.fits)
        return
    changed = False
    for fn, text in goldens().items():
        path = GOLDEN / f"{fn}.golden"
        old = path.read_text() if path.exists() else ""
        if old == text:
            continue
        changed = True
        if args.check:
            diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path), "regenerated",
                                        lineterm="", n=0)
            print("\n".join(list(diff)[:20]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path}")
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
