#!/usr/bin/env python3
"""Generate brot's script data from the Unicode 17.0.0 UCD.

Run from anywhere:

    uv run python3 packages/brot/test/gen/gen_scripts.py [--check]

Tokenizer files write patterns over scripts, as Kimi K2's `[\\p{Han}]+`.
`Regex` matches `\\p{..}` over a script with the code points Scripts.txt
gives it, by any of the names PropertyValueAliases.txt gives it. The data is
taken from the Unicode 17.0.0 files rather than from uucp, whose Unicode
version follows its own releases, so that it stays at the version of brot's
grapheme data (`gen_grapheme.py`). `Unknown` is every code point Scripts.txt
leaves out, as the file's header defines it. A script without code points,
`Katakana_Or_Hiragana`, is left out: the engine tokenizer files are written
for has no such property and refuses the pattern.

This writes `lib/script_data.ml`, derived from Unicode's data files and
redistributed under the Unicode License v3 in `packages/brot/LICENSE-unicode`.
With `--check` it writes it to a temporary directory instead and fails if it
differs from the committed one.
"""

from __future__ import annotations

import filecmp
import sys
import tempfile
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
UCD = "https://www.unicode.org/Public/{}/ucd/{}"
LIMIT = 0x110000


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def data_lines(text: str):
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if data:
            yield [f.strip() for f in data.split(";")]


def merge(ranges: list[tuple[int, int]]) -> list[tuple[int, int]]:
    out: list[tuple[int, int]] = []
    for lo, hi in sorted(ranges):
        if out and lo <= out[-1][1] + 1:
            out[-1] = (out[-1][0], max(hi, out[-1][1]))
        else:
            out.append((lo, hi))
    return out


def scripts(version: str) -> list[tuple[list[str], list[tuple[int, int]]]]:
    """Each script's names, short first, and its ranges, by short name."""
    aliases = fetch(UCD.format(version, "PropertyValueAliases.txt"))
    fields = [f[1:] for f in data_lines(aliases) if f[0] == "sc"]
    by_long = {f[1]: list(dict.fromkeys(f)) for f in fields}
    ranges: dict[str, list[tuple[int, int]]] = {long: [] for long in by_long}
    for fields in data_lines(fetch(UCD.format(version, "Scripts.txt"))):
        first, _, last = fields[0].partition("..")
        ranges[fields[1]].append((int(first, 16), int(last or first, 16)))
    listed = merge([r for rs in ranges.values() for r in rs])
    unknown, start = [], 0
    for lo, hi in listed:
        if start < lo:
            unknown.append((start, lo - 1))
        start = hi + 1
    if start < LIMIT:
        unknown.append((start, LIMIT - 1))
    ranges["Unknown"] = unknown
    return [
        (by_long[long], merge(rs))
        for long, rs in sorted(ranges.items(), key=lambda kv: by_long[kv[0]][0])
        if rs
    ]


def ocaml(data) -> str:
    lines = [
        "(* Generated by packages/brot/test/gen/gen_scripts.py from the",
        f"   Unicode {VERSION} UCD (Scripts.txt, PropertyValueAliases.txt);",
        "   do not edit. Run",
        "   [uv run python3 packages/brot/test/gen/gen_scripts.py] to",
        "   regenerate it.",
        "",
        "   The data is derived from Unicode's data files, under the Unicode",
        "   License v3 in packages/brot/LICENSE-unicode. *)",
        "",
        f'let unicode_version = "{VERSION}"',
        "",
        "let scripts =",
        "  [|",
    ]
    for names, ranges in data:
        quoted = "; ".join(f'"{n}"' for n in names)
        bounds = [b for r in ranges for b in r]
        lines.append(f"    ( [ {quoted} ],")
        lines.append("      [|")
        for i in range(0, len(bounds), 8):
            row = "; ".join(f"0x{b:X}" for b in bounds[i : i + 8])
            lines.append(f"        {row};")
        lines.append("      |] );")
    lines.append("  |]")
    return "\n".join(lines) + "\n"


def write(brot: Path) -> list[Path]:
    """Write the generated file under `brot`; return its path."""
    data = brot / "lib" / "script_data.ml"
    data.parent.mkdir(parents=True, exist_ok=True)
    data.write_text(ocaml(scripts(VERSION)), encoding="utf-8", newline="\n")
    return [data.relative_to(brot)]


def main() -> int:
    brot = Path(__file__).resolve().parents[2]
    if "--check" not in sys.argv[1:]:
        for path in write(brot):
            print(f"wrote {path}")
        return 0
    with tempfile.TemporaryDirectory() as scratch:
        stale = [
            path
            for path in write(Path(scratch))
            if not filecmp.cmp(Path(scratch) / path, brot / path, shallow=False)
        ]
    for path in stale:
        print(f"{path} differs from what the generator writes", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
