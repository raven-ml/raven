#!/usr/bin/env python3
"""Generate brot's grapheme cluster data from the Unicode 17.0.0 UCD.

Run from anywhere:

    uv run python3 packages/brot/test/gen/gen_grapheme.py [--check]

`Normalizer.precompiled` reads text by extended grapheme cluster as UAX #29
defines it at Unicode 17.0.0, which is what HuggingFace's tokenizers implements
(unicode-segmentation 1.13). The cluster rules need three properties of every
code point: Grapheme_Cluster_Break, Indic_Conjunct_Break and
Extended_Pictographic. They are taken here from the Unicode 17.0.0 files
rather than from uucp, whose Unicode version follows its own releases, so
that brot's clusters stay those of Unicode 17 whichever uucp is installed.

This writes `lib/grapheme_data.ml`, the three properties as ranges of code
points, and `test/support/unicode/GraphemeBreakTest-17.0.0.txt`, Unicode's
conformance test for the cluster rules, which `test_unicode.ml` runs through
`Normalizer.precompiled`. Both are redistributed under the Unicode License
v3, in `packages/brot/LICENSE-unicode`. With `--check` it writes them to a
temporary directory instead and fails if they differ from the committed
ones.
"""

from __future__ import annotations

import filecmp
import sys
import tempfile
import urllib.request
from pathlib import Path

VERSION = "17.0.0"
UCD = "https://www.unicode.org/Public/{}/ucd/{}"

# Grapheme_Cluster_Break values, in the order grapheme.ml numbers them.
GCB = [
    "Other", "CR", "LF", "Control", "Extend", "ZWJ", "Regional_Indicator",
    "Prepend", "SpacingMark", "L", "V", "T", "LV", "LVT",
]
INCB = ["None", "Consonant", "Extend", "Linker"]
LIMIT = 0x110000


def fetch(url: str) -> str:
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def ranges(text: str, select):
    """(first, last, value) for each data line `select` maps to a value."""
    for line in text.splitlines():
        data = line.split("#", 1)[0].strip()
        if not data:
            continue
        fields = [f.strip() for f in data.split(";")]
        value = select(fields)
        if value is None:
            continue
        first, _, last = fields[0].partition("..")
        yield int(first, 16), int(last or first, 16), value


def properties(version: str) -> list[int]:
    """Every code point's class: GCB | InCB << 4 | Extended_Pictographic << 6."""
    classes = [0] * LIMIT
    gcb = fetch(UCD.format(version, "auxiliary/GraphemeBreakProperty.txt"))
    for first, last, value in ranges(gcb, lambda f: GCB.index(f[1])):
        for cp in range(first, last + 1):
            classes[cp] |= value
    derived = fetch(UCD.format(version, "DerivedCoreProperties.txt"))
    select = lambda f: INCB.index(f[2]) if f[1] == "InCB" else None
    for first, last, value in ranges(derived, select):
        for cp in range(first, last + 1):
            classes[cp] |= value << 4
    emoji = fetch(UCD.format(version, "emoji/emoji-data.txt"))
    select = lambda f: 1 if f[1] == "Extended_Pictographic" else None
    for first, last, value in ranges(emoji, select):
        for cp in range(first, last + 1):
            classes[cp] |= value << 6
    return classes


def ocaml(classes: list[int]) -> str:
    starts, values = [], []
    for cp, value in enumerate(classes):
        if not values or values[-1] != value:
            starts.append(cp)
            values.append(value)
    lines = [
        "(* Generated by packages/brot/test/gen/gen_grapheme.py from the",
        f"   Unicode {VERSION} UCD (auxiliary/GraphemeBreakProperty.txt,",
        "   DerivedCoreProperties.txt, emoji/emoji-data.txt); do not edit. Run",
        "   [uv run python3 packages/brot/test/gen/gen_grapheme.py] to",
        "   regenerate it.",
        "",
        "   The data is derived from Unicode's data files, under the Unicode",
        "   License v3 in packages/brot/LICENSE-unicode. *)",
        "",
        f'let unicode_version = "{VERSION}"',
        "",
        "let starts =",
        "  [|",
    ]
    for i in range(0, len(starts), 8):
        row = "; ".join(f"0x{cp:X}" for cp in starts[i : i + 8])
        lines.append(f"    {row};")
    lines += ["  |]", "", "let classes =", '  "\\']
    body = "".join(f"\\x{v:02X}" for v in values)
    for i in range(0, len(body), 64):
        lines.append(f"   {body[i : i + 64]}\\")
    lines.append('   "')
    return "\n".join(lines) + "\n"


def write(brot: Path) -> list[Path]:
    """Write the generated files under `brot`; return their paths."""
    data = brot / "lib" / "grapheme_data.ml"
    data.parent.mkdir(parents=True, exist_ok=True)
    data.write_text(ocaml(properties(VERSION)), encoding="utf-8", newline="\n")
    unicode = brot / "test" / "support" / "unicode"
    unicode.mkdir(parents=True, exist_ok=True)
    test = unicode / f"GraphemeBreakTest-{VERSION}.txt"
    text = fetch(UCD.format(VERSION, "auxiliary/GraphemeBreakTest.txt"))
    test.write_text(text, encoding="utf-8", newline="\n")
    return [data.relative_to(brot), test.relative_to(brot)]


def main() -> int:
    brot = Path(__file__).resolve().parents[2]
    if "--check" not in sys.argv[1:]:
        for path in write(brot):
            print(f"wrote {path}")
        return 0
    with tempfile.TemporaryDirectory() as scratch:
        stale = [
            path
            for path in write(Path(scratch))
            if not filecmp.cmp(Path(scratch) / path, brot / path, shallow=False)
        ]
    for path in stale:
        print(f"{path} differs from what the generator writes", file=sys.stderr)
    return 1 if stale else 0


if __name__ == "__main__":
    sys.exit(main())
