(* Differential test against HuggingFace [tokenizers]. The expected ids are
   generated by test/scripts/gen_parity_expected.py, which documents both
   fixture formats. *)

open Brot
open Windtrap

let corpora = [ "sample"; "edge_cases" ]
let models = [ "gpt2"; "llama"; "bert_base" ]
let corpus_path corpus = Filename.concat "fixtures/parity" (corpus ^ ".txt")

let ids_path corpus model =
  Filename.concat "fixtures/parity" (corpus ^ "." ^ model ^ ".ids")

let model_path model = Filename.concat "../bench/data" (model ^ ".json")

(* Fixtures *)

(* The last byte of a fixture is a newline that belongs to the file, not to the
   last document or the last line of ids. *)

let drop_final_newline text =
  let n = String.length text in
  if n > 0 && text.[n - 1] = '\n' then String.sub text 0 (n - 1) else text

let lines text = String.split_on_char '\n' (drop_final_newline text)

let documents corpus =
  let text = Fixture.read (corpus_path corpus) in
  let join current = String.concat "\n" (List.rev current) in
  let rec split docs current = function
    | [] -> List.rev (join current :: docs)
    | "====" :: rest -> split (join current :: docs) [] rest
    | line :: rest -> split docs (line :: current) rest
  in
  (drop_final_newline text, Array.of_list (split [] [] (lines text)))

let ids_of_line relative line =
  String.split_on_char ' ' line
  |> List.filter (fun field -> field <> "")
  |> List.map (fun field ->
      match int_of_string_opt field with
      | Some id -> id
      | None -> failf "malformed id %S in %S" field relative)
  |> Array.of_list

(* Expected ids: one line per document, then a final line prefixed [ALL ] for
   the whole corpus file encoded as a single document. *)
let expected corpus model =
  let relative = ids_path corpus model in
  let rows =
    Fixture.read relative |> lines
    |> List.filter (fun line -> not (String.starts_with ~prefix:"#" line))
  in
  match List.rev rows with
  | whole :: rest when String.starts_with ~prefix:"ALL " whole ->
      ( Array.of_list (List.rev_map (ids_of_line relative) rest),
        ids_of_line relative (String.sub whole 4 (String.length whole - 4)) )
  | _ -> failf "%s: last line is not the ALL document" relative

(* Reporting *)

type document = Numbered of int | Whole

let describe = function
  | Numbered index -> Printf.sprintf "document %d" index
  | Whole -> "whole file"

let label = function
  | Numbered index -> string_of_int index
  | Whole -> "whole file"

let id_window ids index =
  let n = Array.length ids in
  if index >= n then "(past end)"
  else
    let first = max 0 (index - 3) and last = min (n - 1) (index + 3) in
    let buffer = Buffer.create 64 in
    if first > 0 then Buffer.add_string buffer "… ";
    for i = first to last do
      if i > first then Buffer.add_char buffer ' ';
      if i = index then Buffer.add_string buffer (Printf.sprintf "[%d]" ids.(i))
      else Buffer.add_string buffer (string_of_int ids.(i))
    done;
    if last < n - 1 then Buffer.add_string buffer " …";
    Buffer.contents buffer

(* Escape what would break the message, and leave the rest of the UTF-8 alone so
   that a mismatch inside non-Latin text stays readable. *)
let escape text =
  let buffer = Buffer.create (String.length text + 8) in
  String.iter
    (fun c ->
      match c with
      | '"' | '\\' ->
          Buffer.add_char buffer '\\';
          Buffer.add_char buffer c
      | '\n' -> Buffer.add_string buffer "\\n"
      | '\r' -> Buffer.add_string buffer "\\r"
      | '\t' -> Buffer.add_string buffer "\\t"
      | c when Char.code c < 0x20 || Char.code c = 0x7f ->
          Buffer.add_string buffer (Printf.sprintf "\\x%02x" (Char.code c))
      | c -> Buffer.add_char buffer c)
    text;
  Buffer.contents buffer

let text_window text (start, stop) =
  let n = String.length text in
  let is_continuation i = Char.code text.[i] land 0xc0 = 0x80 in
  let first = ref (max 0 (min n start - 24)) in
  while !first > 0 && !first < n && is_continuation !first do
    decr first
  done;
  let last = ref (max !first (min n (stop + 24))) in
  while !last > !first && !last < n && is_continuation !last do
    decr last
  done;
  Printf.sprintf "%s\"%s\"%s"
    (if !first > 0 then "… " else "")
    (escape (String.sub text !first (!last - !first)))
    (if !last < n then " …" else "")

let token tokenizer ids index =
  if index >= Array.length ids then "(past end)"
  else
    match id_to_token tokenizer ids.(index) with
    | Some token -> Printf.sprintf "\"%s\"" (escape token)
    | None -> Printf.sprintf "(id %d not in vocabulary)" ids.(index)

let compare_ids tokenizer ~what ~via ~text ~offsets ~expected ~actual =
  let common = min (Array.length expected) (Array.length actual) in
  let rec first_difference i =
    if i = common then
      if Array.length expected = Array.length actual then None else Some i
    else if expected.(i) <> actual.(i) then Some i
    else first_difference (i + 1)
  in
  match first_difference 0 with
  | None -> None
  | Some i ->
      let region =
        if i < Array.length offsets then offsets.(i)
        else (String.length text, String.length text)
      in
      Some
        (Printf.sprintf
           "%s (%s): ids differ at index %d\n\
           \  text:     %s\n\
           \  expected: %s\n\
           \  actual:   %s\n\
           \  token:    expected %s, actual %s\n\
           \  lengths:  expected %d, actual %d"
           what via i (text_window text region) (id_window expected i)
           (id_window actual i)
           (token tokenizer expected i)
           (token tokenizer actual i) (Array.length expected)
           (Array.length actual))

(* Tests *)

let check_corpus model corpus tokenizer =
  let text, docs = documents corpus in
  let expected_docs, expected_whole = expected corpus model in
  equal
    ~msg:(Printf.sprintf "%s: one row per document" (ids_path corpus model))
    int (Array.length docs)
    (Array.length expected_docs);
  (* Every document is checked, so that a fix can be measured by how much of the
     corpus it recovers, not just by which document now fails first. *)
  let differing = ref [] in
  let checked = ref 0 in
  let check document text expected =
    let encoding = encode tokenizer ~add_special_tokens:false text in
    let offsets = Encoding.offsets encoding in
    let what = Printf.sprintf "%s.txt/%s %s" corpus model (describe document) in
    let against = compare_ids tokenizer ~what ~text ~offsets ~expected in
    let record difference =
      incr checked;
      match difference with
      | None -> ()
      | Some message -> differing := (document, message) :: !differing
    in
    record (against ~via:"encode" ~actual:(Encoding.ids encoding));
    record
      (against ~via:"encode_ids"
         ~actual:(encode_ids tokenizer ~add_special_tokens:false text))
  in
  Array.iteri
    (fun index text -> check (Numbered index) text expected_docs.(index))
    docs;
  check Whole text expected_whole;
  match List.rev !differing with
  | [] -> ()
  | (_, first) :: _ as all ->
      let rec distinct = function
        | (a, _) :: ((b, _) :: _ as rest) when a = b -> distinct rest
        | (a, _) :: rest -> label a :: distinct rest
        | [] -> []
      in
      let labels = distinct all in
      let shown = List.filteri (fun i _ -> i < 12) labels in
      failf
        "%d of %d comparisons differ, in documents: %s%s; the first is:\n\n%s"
        (List.length all) !checked (String.concat ", " shown)
        (if List.length labels > List.length shown then
           Printf.sprintf " and %d more" (List.length labels - List.length shown)
         else "")
        first

let with_tokenizer model check () =
  Fixture.with_download (model_path model)
    ~from:"packages/brot/bench/download_data.sh" (fun path ->
      match from_file path with
      | Error msg -> failf "failed to load %s: %s" path msg
      | Ok tokenizer -> check tokenizer)

let () =
  run "HF parity"
    (List.map
       (fun model ->
         group model
           (List.map
              (fun corpus ->
                test corpus (with_tokenizer model (check_corpus model corpus)))
              corpora))
       models)
