def finite32(v):
    return abs(v) < 3.4e38


def located(family, loc, scale, z):
    """The float32 point at z scales from loc, or None past float32."""
    x = loc + scale * z
    return f32(x) if finite32(x) else None


def closed_form(family, args, x):
    """The exact log density of a closed-form family, from mpmath at 200
    bits, -inf outside the open support."""
    mp.prec = 200
    a = [mpf(v) for v in args]
    half_log_2pi = mpmath.log(2 * mpmath.pi) / 2
    if family in ("normal", "cauchy", "laplace", "logistic"):
        loc, scale = a
        z = (mpf(x) - loc) / scale
        if family == "normal":
            return -z * z / 2 - half_log_2pi - mpmath.log(scale)
        if family == "cauchy":
            return -mpmath.log(mpmath.pi) - mpmath.log(scale) - mpmath.log1p(z * z)
        if family == "laplace":
            return -abs(z) - mpmath.log(2 * scale)
        return -z - 2 * mpmath.log1p(mpmath.exp(-z)) - mpmath.log(scale)
    if family in ("half_normal", "half_cauchy", "exponential"):
        (s,) = a
        if not x > 0:
            return -np.inf
        x = mpf(x)
        if family == "half_normal":
            z = x / s
            return mpmath.log(2) - z * z / 2 - half_log_2pi - mpmath.log(s)
        if family == "half_cauchy":
            z = x / s
            return mpmath.log(2) - mpmath.log(mpmath.pi) - mpmath.log(s) - mpmath.log1p(z * z)
        return mpmath.log(s) - s * x
    if family == "lognormal":
        loc, scale = a
        if not x > 0:
            return -np.inf
        lx = mpmath.log(mpf(x))
        z = (lx - loc) / scale
        return -lx - z * z / 2 - half_log_2pi - mpmath.log(scale)
    if family == "uniform":
        low, high = a
        if not low < x < high:
            return -np.inf
        return -mpmath.log(high - low)
    if family == "von_mises":
        loc, k = a
        if abs(mpf(x)) > mpmath.pi:
            return -np.inf
        return (k * (mpmath.cos(mpf(x) - loc) - 1)
                - mpmath.log(2 * mpmath.pi * mpmath.besseli(0, k) * mpmath.exp(-k)))
    raise ValueError(family)


def closed_forms():
    mp.prec = 200
    out = []

    def line(family, args, xs, v):
        out.append(f"density {family} " + " ".join(fmt(u) for u in list(args) + list(xs))
                   + f" {fmt(v)}\n")

    for loc, scale in LOCATION_SCALE:
        for family in ("normal", "cauchy", "laplace", "logistic"):
            for z in Z_POINTS:
                x = located(family, loc, scale, z)
                if x is not None:
                    line(family, (f32(loc), f32(scale)), [x],
                         closed_form(family, (f32(loc), f32(scale)), x))
    for s in map(f32, SCALES):
        for family in ("half_normal", "half_cauchy"):
            for z in [0.0, -1.0] + [abs(z) for z in Z_POINTS if z > 0] + [1e-30]:
                x = located(family, 0.0, s, z)
                if x is not None:
                    line(family, (s,), [x], closed_form(family, (s,), x))
        rate = f32(1 / s)
        for y in [0.0, -0.1, 1e-30, 1e-3, 1.0, 30.0, 1e5, 1e30]:
            x = f32(y / rate)
            if finite32(x):
                line("exponential", (rate,), [x], closed_form("exponential", (rate,), x))
    for loc, scale in [(0.3, 0.8), (-50.0, 1e-3), (60.0, 20.0)]:
        loc, scale = f32(loc), f32(scale)
        for z in [0.0, 1.0, -1.0, 5.0, -5.0, 40.0, -40.0, 1e3, -1e3]:
            lx = loc + scale * z
            if -100 < lx < 88:
                x = f32(np.exp(lx))
                if x > 0:
                    line("lognormal", (loc, scale), [x], closed_form("lognormal", (loc, scale), x))
        for x in [0.0, -1.0]:
            line("lognormal", (loc, scale), [x], closed_form("lognormal", (loc, scale), x))
    for low, high in [(-1.0, 3.0), (0.0, 1e-30), (-1e30, 1e30), (1e7, 1.0000001e7)]:
        low, high = f32(low), f32(high)
        for x in [low, float(np.nextafter(np.float32(low), np.float32(np.inf))),
                  f32((low + high) / 2), float(np.nextafter(np.float32(high), np.float32(-np.inf))),
                  high, f32(high + abs(high) + 1)]:
            line("uniform", (low, high), [x], closed_form("uniform", (low, high), x))
    for loc, k in VON_MISES_CASES:
        loc, k = f32(loc), f32(k)
        for x in map(f32, VON_MISES_POINTS):
            line("von_mises", (loc, k), [x], closed_form("von_mises", (loc, k), x))
    loc = [1.0, -1.0]
    for lower in MVN_LOWERS:
        lower = [f32(v) for v in lower]
        L = mpmath.matrix([[lower[0], 0], [lower[2], lower[3]]])
        for z in MVN_Z:
            x = [f32(loc[0] + lower[0] * z[0]), f32(loc[1] + lower[2] * z[0] + lower[3] * z[1])]
            if not all(finite32(v) for v in x):
                continue
            d = mpmath.matrix([mpf(x[0]) - loc[0], mpf(x[1]) - loc[1]])
            w = mpmath.lu_solve(L, d)
            v = (-(w[0] ** 2 + w[1] ** 2) / 2 - mpmath.log(abs(L[0, 0]))
                 - mpmath.log(abs(L[1, 1])) - mpmath.log(2 * mpmath.pi))
            line("mvn", loc + lower, x, v)
    for logits in CATEGORICAL:
        logits = [f32(v) if np.isfinite(v) else v for v in logits]
        lse = mpmath.log(sum(mpmath.exp(mpf(v)) for v in logits if v > -np.inf))
        for k in range(3):
            v = -np.inf if logits[k] == -np.inf else mpf(logits[k]) - lse
            line("categorical", logits, [float(k)], v)
    for l in BERNOULLI:
        l = f32(l) if np.isfinite(l) else l
        for x in (0.0, 1.0):
            if np.isinf(l):
                v = 0.0 if (l > 0) == (x == 1.0) else -np.inf
            else:
                v = -mpmath.log1p(mpmath.exp(-mpf(l) if x == 1.0 else mpf(l)))
            line("bernoulli", (l,), [x], v)
    return list(dict.fromkeys(out))


def tails(name, x):
    """The CDF and survival of a QUANTILE case at x, from mpmath."""
    x = mpf(x)
    one = mpf(1)

    def located(loc, scale, cdf):
        z = (x - loc) / scale
        return cdf(z), cdf(-z)

    if name == "normal":
        return located(mpf(0.5), mpf(2), mpmath.ncdf)
    if name == "half_normal":
        z = x / mpf(1.5)
        return mpmath.erf(z / mpmath.sqrt(2)), mpmath.erfc(z / mpmath.sqrt(2))
    if name == "lognormal":
        z = (mpmath.log(x) - mpf(0.3)) / mpf(0.8)
        return mpmath.ncdf(z), mpmath.ncdf(-z)
    if name == "cauchy":
        return located(mpf(1), mpf(0.5), lambda z: mpmath.atan2(1, -z) / mpmath.pi)
    if name == "half_cauchy":
        z = x / mpf(2)
        return 2 * mpmath.atan(z) / mpmath.pi, 2 * mpmath.atan2(1, z) / mpmath.pi
    if name == "laplace":
        def cdf(z):
            return mpmath.exp(z) / 2 if z < 0 else one - mpmath.exp(-z) / 2
        return located(mpf(0), mpf(1.3), cdf)
    if name == "logistic":
        return located(mpf(2), mpf(0.4), lambda z: one / (one + mpmath.exp(-z)))
    if name == "exponential":
        return -mpmath.expm1(-mpf(1.7) * x), mpmath.exp(-mpf(1.7) * x)
    if name in ("gamma", "gamma_small", "inverse_gamma"):
        a, r = {"gamma": (2.5, 1.5), "gamma_small": (0.4, 0.8), "inverse_gamma": (3.0, 2.0)}[name]
        a, r = mpf(a), mpf(r)
        y = r * x if name != "inverse_gamma" else r / x
        lo = mpmath.gammainc(a, 0, y, regularized=True)
        hi = mpmath.gammainc(a, y, mpmath.inf, regularized=True)
        return (lo, hi) if name != "inverse_gamma" else (hi, lo)
    if name in BETAS:
        a, b = (mpf(v) for v in BETAS[name])
        lo = mpmath.betainc(a, b, 0, x, regularized=True)
        hi = mpmath.betainc(a, b, x, 1, regularized=True)
        return lo, hi
    if name == "uniform":
        return (x + 1) / 4, (3 - x) / 4
    raise ValueError(name)


BETAS = {"beta": (2.0, 5.0), "beta_u": (0.5, 0.5)}


def solve(tail, side, target, x0, low=None, high=None):
    """The x where tail(x)[side] is target, the lower tail increasing in x
    and the upper decreasing: bisection at 200 bits within [low, high],
    their missing ends found by doubling away from x0."""
    mp.prec = 200
    below = lambda x: (tail(x)[0] < target) if side == 0 else (tail(x)[1] > target)
    x0 = mpf(x0)
    step = abs(x0) + 1
    a = mpf(low) if low is not None else x0 - step
    while low is None and below(a) is False:
        step *= 2
        a = x0 - step
    step = abs(x0) + 1
    b = mpf(high) if high is not None else x0 + step
    while high is None and below(b):
        step *= 2
        b = x0 + step
    for _ in range(400):
        m = (a + b) / 2
        if m == a or m == b:
            break
        if below(m):
            a = m
        else:
            b = m
    return (a + b) / 2


def exact_ppf(name, d, p):
    """The quantile at p, the root of its smaller tail's equation, from
    mpmath, searched from SciPy's."""
    side = 0 if p <= 0.5 else 1
    low = 0.0 if name in POSITIVE or name in BETAS else None
    high = 1.0 if name in BETAS else None
    return solve(lambda x: tails(name, x), side, min(mpf(p), 1 - mpf(p)), d.ppf(p),
                 low=low, high=high)


POSITIVE = {"half_normal", "lognormal", "half_cauchy", "exponential", "gamma",
            "gamma_small", "inverse_gamma"}


def logpdf_mp(name, x):
    """A QUANTILE case's log density at x, from mpmath."""
    x = mpf(x)
    lsqrt2pi = mpmath.log(2 * mpmath.pi) / 2
    if name == "normal":
        z = (x - mpf(0.5)) / 2
        return -z * z / 2 - lsqrt2pi - mpmath.log(2)
    if name == "half_normal":
        z = x / mpf(1.5)
        return -z * z / 2 - lsqrt2pi + mpmath.log(2) - mpmath.log(mpf(1.5))
    if name == "cauchy":
        z = (x - 1) / mpf(0.5)
        return -mpmath.log(mpmath.pi * mpf(0.5) * (1 + z * z))
    if name == "laplace":
        return -abs(x) / mpf(1.3) - mpmath.log(2 * mpf(1.3))
    if name == "exponential":
        return mpmath.log(mpf(1.7)) - mpf(1.7) * x
    if name in ("gamma", "gamma_small"):
        a, r = (2.5, 1.5) if name == "gamma" else (0.4, 0.8)
        return gamma_density(a, r, x)
    if name == "inverse_gamma":
        return gamma_density(3.0, 2.0, 1 / x) - 2 * mpmath.log(x)
    if name in BETAS:
        a, b = (mpf(v) for v in BETAS[name])
        return (a - 1) * mpmath.log(x) + (b - 1) * mpmath.log1p(-x) - mpmath.log(mpmath.beta(a, b))
    if name == "uniform":
        return -mpmath.log(4)
    if name == "lognormal":
        return closed_form("lognormal", (0.3, 0.8), x)
    if name == "half_cauchy":
        return closed_form("half_cauchy", (2.0,), x)
    if name == "logistic":
        return closed_form("logistic", (2.0, 0.4), x)
    raise ValueError(name)


def ppf_line(case, base, p, v):
    """A `ppf` line: the quantile v at p, and the logs of the base's smaller
    tail and density at v, which set the quantile's precision."""
    mp.prec = 200
    tail = min(tails(base, v))
    return (f"ppf {case} {fmt(p)} {fmt(v)} {fmt(mpmath.log(tail))} "
            f"{fmt(logpdf_mp(base, v))}\n")


