"""Generate the goldens of norn's distributions.

    uv run packages/norn/test/gen/dist.py [--check]

Writes `packages/norn/test/golden/dist.golden`: for each family at fixed
parameters, SciPy's log density at chosen points, its quantiles, and the
deciles or probabilities a goodness-of-fit test of `sample` bins draws by.
The parameters are repeated in `packages/norn/test/test_dist.ml` under the
same case names. With --check nothing is written, and the run fails if the
file would change.

Lines are `KIND CASE ARGS... VALUE`, floats hexadecimal or `-inf`:
- `logpdf CASE X... V`: the log density (or mass) at the point X;
- `ppf CASE P V`: the quantile at P;
- `bin CASE LOW HIGH P`: the probability of [LOW, HIGH), the bins of a
  goodness-of-fit test, together of total probability one, each at least
  MIN_BIN;
- `threshold CASE V`: the chi-square statistic of DRAWS draws over the case's
  bins that its test rejects above, at a level that keeps the family-wise
  false-alarm rate of every goodness-of-fit test at 1%;
- `mass FAMILY A B X V`: the exact log mass of poisson (rate A, B unused),
  binomial (trials A, logits B) or neg_binomial (mean A, dispersion B) at the
  count X, from mpmath's log-gamma at 200 bits. The parameters are float32
  values, so float32 and float64 read the same distribution; the counts reach
  far into both tails and up to 2^31 - 1, the logits past where their
  sigmoid underflows, and the means down to subnormal.
"""

import argparse
import sys
from pathlib import Path

import mpmath
import numpy as np
from mpmath import mp, mpf
from scipy import special, stats

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "dist.golden"
HEADER = "# generated by packages/norn/test/gen/dist.py; do not edit\n"


def sigmoid(x):
    return 1 / (1 + np.exp(-x))


SCALAR = {
    "normal": (stats.norm(0.5, 2.0), [-3.0, 0.0, 0.5, 2.0, 40.0]),
    "half_normal": (stats.halfnorm(scale=1.5), [0.0, 0.1, 1.0, 5.0, -1.0]),
    "lognormal": (stats.lognorm(0.8, scale=np.exp(0.3)), [0.01, 0.5, 1.0, 10.0, -1.0, 0.0]),
    "student_t": (stats.t(3.5, -1.0, 0.7), [-50.0, -1.0, 0.0, 3.0]),
    "cauchy": (stats.cauchy(1.0, 0.5), [-1e4, 0.0, 1.0, 7.0]),
    "half_cauchy": (stats.halfcauchy(scale=2.0), [0.0, 1.0, 100.0, -0.5]),
    "laplace": (stats.laplace(0.0, 1.3), [-4.0, 0.0, 0.3, 9.0]),
    "logistic": (stats.logistic(2.0, 0.4), [-10.0, 1.0, 2.0, 30.0]),
    "exponential": (stats.expon(scale=1 / 1.7), [0.0, 0.2, 3.0, -0.1]),
    "gamma": (stats.gamma(2.5, scale=1 / 1.5), [0.001, 0.5, 2.0, 20.0, -1.0, 0.0]),
    "gamma_small": (stats.gamma(0.4, scale=1 / 0.8), [1e-6, 0.3, 5.0]),
    "inverse_gamma": (stats.invgamma(3.0, scale=2.0), [0.05, 0.5, 1.0, 30.0, -1.0]),
    "beta": (stats.beta(2.0, 5.0), [0.01, 0.2, 0.5, 0.99, 0.0, 1.0, 1.5]),
    "beta_u": (stats.beta(0.5, 0.5), [1e-4, 0.5, 0.9999]),
    "uniform": (stats.uniform(-1.0, 4.0), [-1.0, 0.0, 2.5, 3.0, 3.5, -2.0]),
}

QUANTILE = ["normal", "half_normal", "lognormal", "cauchy", "half_cauchy", "laplace",
            "logistic", "exponential", "gamma", "gamma_small", "inverse_gamma",
            "uniform"]

DISCRETE = {
    "poisson": (stats.poisson(3.2), list(range(0, 12)) + [-1], 12),
    "neg_binomial": (stats.nbinom(2.5, 2.5 / (2.5 + 4.0)), list(range(0, 15)) + [-2], 20),
    "bernoulli": (stats.bernoulli(sigmoid(0.4)), [0, 1], 2),
    "binomial": (stats.binom(12, special.expit(0.4)), list(range(0, 14)) + [-1], 12),
    "binomial_rare": (stats.binom(40, special.expit(-2.5)), [0, 1, 3, 10, 40, 41], 40),
    "binomial_many": (stats.binom(200, special.expit(-1.0)), [0, 30, 54, 100, 200], 200),
}


DRAWS = 20000
MIN_BIN = 0.002


INT32_MAX = 2**31 - 1

POISSON_RATES = [1e-40, 2.0**-100, 1e-30, 1e-3, 0.375, 1.0, 3.5, 17.25, 1e3, 1e6,
                 2.0**24, 1.5e9, 1e30]
BINOMIAL_TRIALS = [1, 7, 50, 1000, 10**6, 2**24, INT32_MAX]
BINOMIAL_LOGITS = [0.0, 0.25, -3.5, 12.0, -30.0]
# Logits whose sigmoid underflows at float32 (past 87) and float64 (past 708).
EXTREME_TRIALS = [1, 10, 1000, 10**6]
EXTREME_LOGITS = [-100.0, -110.0, 110.0, -800.0, 800.0]
# Counts 4 to 6 standard deviations from the mean at large trials and drawn
# logits, where the means' rounding weighs most.
TAIL_DRAWS = 120
NB_MEANS = [1e-40, 1e-30, 1e-3, 4.0, 1e3, 1e6]
NB_DISPERSIONS = [1e-6, 0.5, 2.5, 1e3, 1e9]


def f32(v):
    return float(np.float32(v))


def counts(mean, sd, top):
    """Counts at the edges, near the mean and far into both tails."""
    xs = {0, 1, 2, top, top - 1}
    for c in [mean, mean + 1, mean - sd, mean + sd, mean - 4 * sd, mean + 4 * sd,
              mean / 10, 3 * mean + 3, 10 * mean + 10, mean + 30 * sd]:
        xs.add(int(c))
    return sorted(x for x in xs if 0 <= x <= top)


def poisson_mass(x, rate):
    x, rate = mpf(x), mpf(rate)
    return x * mpmath.log(rate) - rate - mpmath.loggamma(x + 1)


def binomial_mass(x, n, logits):
    lp = -mpmath.log1p(mpmath.exp(-mpf(logits)))
    lq = -mpmath.log1p(mpmath.exp(mpf(logits)))
    x, n = mpf(x), mpf(n)
    return (mpmath.loggamma(n + 1) - mpmath.loggamma(x + 1) - mpmath.loggamma(n - x + 1)
            + x * lp + (n - x) * lq)


def neg_binomial_mass(x, mean, r):
    x, mean, r = mpf(x), mpf(mean), mpf(r)
    return (mpmath.loggamma(x + r) - mpmath.loggamma(r) - mpmath.loggamma(x + 1)
            - r * mpmath.log1p(mean / r) + x * mpmath.log(mean / (r + mean)))


def masses():
    mp.prec = 200
    out = []
    for rate in map(f32, POISSON_RATES):
        for x in counts(rate, rate**0.5, INT32_MAX):
            out.append(f"mass poisson {fmt(rate)} {fmt(0.0)} {fmt(x)} {fmt(poisson_mass(x, rate))}\n")
    for n in BINOMIAL_TRIALS:
        for logits in map(f32, BINOMIAL_LOGITS):
            p = 1 / (1 + np.exp(-logits))
            for x in counts(n * p, (n * p * (1 - p)) ** 0.5, n):
                v = binomial_mass(x, n, logits)
                out.append(f"mass binomial {fmt(n)} {fmt(logits)} {fmt(x)} {fmt(v)}\n")
    for n in EXTREME_TRIALS:
        for logits in map(f32, EXTREME_LOGITS):
            for x in sorted({0, 1, n // 2, n - 1, n}):
                v = binomial_mass(x, n, logits)
                out.append(f"mass binomial {fmt(n)} {fmt(logits)} {fmt(x)} {fmt(v)}\n")
    rng = np.random.default_rng(20001)
    for _ in range(TAIL_DRAWS):
        n = int(np.exp(rng.uniform(np.log(1e6), np.log(INT32_MAX))))
        logits = f32(rng.uniform(-6.0, 6.0))
        p = 1 / (1 + np.exp(-logits))
        m, sd = n * p, (n * p * (1 - p)) ** 0.5
        x = int(round(m + rng.choice([-1, 1]) * rng.uniform(4.0, 6.0) * sd))
        if 0 <= x <= n:
            v = binomial_mass(x, n, logits)
            out.append(f"mass binomial {fmt(n)} {fmt(logits)} {fmt(x)} {fmt(v)}\n")
    for mean in map(f32, NB_MEANS):
        for r in map(f32, NB_DISPERSIONS):
            sd = (mean + mean * mean / r) ** 0.5
            for x in counts(mean, sd, INT32_MAX):
                v = neg_binomial_mass(x, mean, r)
                out.append(f"mass neg_binomial {fmt(mean)} {fmt(r)} {fmt(x)} {fmt(v)}\n")
    return out


def merge(bins):
    """Merge each bin below MIN_BIN into its left neighbour."""
    out = []
    for lo, hi, p in bins:
        if out and p < MIN_BIN:
            plo, _, pp = out[-1]
            out[-1] = (plo, hi, pp + p)
        else:
            out.append((lo, hi, p))
    return out


def fmt(v):
    v = float(v)
    if v == -np.inf:
        return "-inf"
    return v.hex()


def bound(v):
    if v == np.inf:
        return "inf"
    return fmt(v)


def render():
    out = [HEADER]
    bins = {}
    for name, (d, xs) in SCALAR.items():
        for x in xs:
            out.append(f"logpdf {name} {fmt(x)} {fmt(d.logpdf(x))}\n")
        edges = [-np.inf] + [d.ppf(j / 10) for j in range(1, 10)] + [np.inf]
        bins[name] = [(lo, hi, 0.1) for lo, hi in zip(edges[:-1], edges[1:])]
    for name in QUANTILE:
        d, _ = SCALAR[name]
        for p in [0.001, 0.1, 0.5, 0.9, 0.999]:
            out.append(f"ppf {name} {fmt(p)} {fmt(d.ppf(p))}\n")
    for name, (d, xs, top) in DISCRETE.items():
        for x in xs:
            out.append(f"logpdf {name} {fmt(x)} {fmt(d.logpmf(x))}\n")
        bins[name] = merge([(k, k + 1, d.pmf(k)) for k in range(top)]
                           + [(top, np.inf, d.sf(top - 1))])
    logits = np.array([0.1, -1.0, 2.0])
    lp = logits - special.logsumexp(logits)
    for k in range(3):
        out.append(f"logpdf categorical {fmt(k)} {fmt(lp[k])}\n")
    bins["categorical"] = [(k, k + 1, np.exp(lp[k])) for k in range(3)]
    alpha = np.array([1.5, 2.0, 0.7])
    for x in [[0.2, 0.3, 0.5], [0.6, 0.39, 0.01], [1 / 3, 1 / 3, 1 / 3]]:
        x = np.array(x)
        out.append("logpdf dirichlet " + " ".join(fmt(v) for v in x)
                   + f" {fmt(stats.dirichlet.logpdf(x, alpha))}\n")
    mean = np.array([1.0, -1.0])
    lower = np.array([[2.0, 0.0], [0.5, 1.0]])
    cov = lower @ lower.T
    for x in [[1.0, -1.0], [0.0, 0.0], [5.0, -3.0]]:
        out.append("logpdf mvn " + " ".join(fmt(v) for v in x)
                   + f" {fmt(stats.multivariate_normal(mean, cov).logpdf(x))}\n")
    alpha = 0.01 / len(bins)
    for name, bs in bins.items():
        for lo, hi, p in bs:
            out.append(f"bin {name} {bound(lo)} {bound(hi)} {fmt(p)}\n")
        out.append(f"threshold {name} {fmt(stats.chi2.ppf(1 - alpha, len(bs) - 1))}\n")
    out.extend(masses())
    return "".join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    text = render()
    if args.check:
        if not GOLDEN.exists() or GOLDEN.read_text() != text:
            sys.exit(f"{GOLDEN} is stale")
        return
    GOLDEN.write_text(text)


if __name__ == "__main__":
    main()
