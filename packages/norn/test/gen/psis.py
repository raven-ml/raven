"""Generate the goldens of norn's Pareto smoothed importance sampling.

    uv run packages/norn/test/gen/psis.py [--check]

Writes `packages/norn/test/golden/psis.golden`: seeded log importance ratios
with their smoothed log weights, normalised, and k-hat as ArviZ computes them
(arviz-stats, after Vehtari et al. 2024), and seeded log likelihoods with their
PSIS-LOO terms. With --check nothing is written, and the run fails if the file
would change.

A `psis NAME S` block has `data`, the S log ratios, `weights` and `khat`. A
`loo NAME CHAINS DRAWS POINTS` block has `data`, the log likelihoods in
[chain; draw; point] order, then per point `reff`, the relative bulk
effective sample size that sets the tail, `elpd_i`, `p_i` and `khat`, then
`elpd`, `se` and `p`. ArviZ's standard error divides the variance by n; the
one written here divides by n - 1, as Vehtari, Gelman and Gabry (2017),
equation 23, defines it. Floats are hexadecimal.
"""

import argparse
import sys
from pathlib import Path

import numpy as np
from arviz_stats.base.diagnostics import _DiagnosticsBase

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "psis.golden"
HEADER = "# generated by packages/norn/test/gen/psis.py; do not edit\n"

D = _DiagnosticsBase()


def norm_logpdf(x, loc, scale):
    return -0.5 * ((x - loc) / scale) ** 2 - np.log(scale) - 0.5 * np.log(2 * np.pi)


def ratio_cases():
    rng = np.random.default_rng(20261031)
    # A proposal narrower than its target: N(0, 1.6^2) from N(0, 1).
    x = rng.standard_normal(500)
    yield "narrow_proposal", norm_logpdf(x, 0, 1.6) - norm_logpdf(x, 0, 1)
    # Ratios with a Pareto tail of shape 0.4, shifted far from 0.
    yield "pareto", -0.4 * np.log(rng.uniform(size=400)) + 50.0
    # A proposal wider than its target: bounded ratios.
    x = 2 * rng.standard_normal(200)
    yield "wide_proposal", norm_logpdf(x, 0, 1) - norm_logpdf(x, 0, 2)
    # The fewest draws with a tail: S = 25, M = 5.
    yield "fewest", rng.standard_normal(25)
    # A tail heavier than any mean: shape 1.3.
    yield "heavy", -1.3 * np.log(rng.uniform(size=400))


def loo_cases():
    rng = np.random.default_rng(20261101)
    # y_i ~ N(mu, 1), mu ~ N(0, 10^2); exact posterior draws, one outlier.
    y = np.concatenate([rng.normal(0.5, 1.0, size=7), [6.0]])
    n = len(y)
    prec = 1 / 100 + n
    mean = y.sum() / prec
    mu = mean + rng.standard_normal((2, 200)) / np.sqrt(prec)
    yield "normal_outlier", norm_logpdf(y[None, None, :], mu[:, :, None], 1.0)
    # The same posterior drawn by 4 AR(1) chains of correlation 0.97: the
    # ratios' small relative efficiency widens the tail.
    z = np.empty((4, 100))
    z[:, 0] = rng.standard_normal(4)
    for t in range(1, 100):
        z[:, t] = 0.97 * z[:, t - 1] + np.sqrt(1 - 0.97**2) * rng.standard_normal(4)
    mu = mean + z / np.sqrt(prec)
    yield "correlated_chains", norm_logpdf(y[None, None, :], mu[:, :, None], 1.0)


def fmt(v):
    v = float(v)
    return "nan" if np.isnan(v) else v.hex()


def line(key, xs):
    return key + " " + " ".join(fmt(v) for v in np.ravel(xs)) + "\n"


def render():
    out = [HEADER]
    for name, lr in ratio_cases():
        out.append(f"psis {name} {len(lr)}\n")
        out.append(line("data", lr))
        # ArviZ smooths the negated log likelihood: it takes -lr.
        lw, k = D._psislw(-lr.copy(), 1.0)
        out.append(line("weights", lw))
        out.append(line("khat", [k]))
    for name, ll in loo_cases():
        c, s, n = ll.shape
        out.append(f"loo {name} {c} {s} {n}\n")
        out.append(line("data", ll))
        # Appendix H: each point's tail from its ratios' relative bulk ESS.
        reff = [D._ess_bulk(ll[:, :, i].copy()) / (c * s) for i in range(n)]
        out.append(line("reff", reff))
        each = [D._loo(ll[:, :, i].copy(), r_eff=reff[i]) for i in range(n)]
        elpd_i = np.array([e[0] for e in each])
        khat = np.array([e[1] for e in each])
        p_i = np.array([e[2] for e in each])
        out.append(line("elpd_i", elpd_i))
        out.append(line("p_i", p_i))
        out.append(line("khat", khat))
        out.append(line("elpd", [elpd_i.sum()]))
        out.append(line("se", [np.sqrt(n * np.var(elpd_i, ddof=1))]))
        out.append(line("p", [p_i.sum()]))
    return "".join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    text = render()
    if args.check:
        if not GOLDEN.exists() or GOLDEN.read_text() != text:
            sys.exit(f"{GOLDEN} is stale")
        return
    GOLDEN.write_text(text)


if __name__ == "__main__":
    main()
