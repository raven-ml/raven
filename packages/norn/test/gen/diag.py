"""Generate the goldens of norn's chain diagnostics.

    uv run packages/norn/test/gen/diag.py [--check]

Writes `packages/norn/test/golden/diag.golden`: seeded draws of chains and
their diagnostics as ArviZ computes them (arviz-stats, after Vehtari et al.
2021 and Margossian et al. 2024). With --check nothing is written, and the
run fails if the file would change.

Each case is a block of lines: `case NAME CHAINS DRAWS SUPERCHAINS`, then
`data` and the draws in chain-major order, then one line per diagnostic.
Floats are hexadecimal; `nan` is written as such.
"""

import argparse
import sys
from pathlib import Path

import numpy as np
from arviz_stats.base.diagnostics import _DiagnosticsBase

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "diag.golden"
HEADER = "# generated by packages/norn/test/gen/diag.py; do not edit\n"

D = _DiagnosticsBase()


def ar1(rng, chains, draws, phi, shift=0.0):
    x = np.empty((chains, draws))
    x[:, 0] = rng.standard_normal(chains)
    for t in range(1, draws):
        x[:, t] = phi * x[:, t - 1] + np.sqrt(1 - phi**2) * rng.standard_normal(chains)
    return x + shift * np.arange(chains)[:, None]


def cases():
    rng = np.random.default_rng(20261006)
    yield "iid", ar1(rng, 4, 100, 0.0), 2
    yield "correlated", ar1(rng, 4, 200, 0.9), 2
    yield "odd_draws", ar1(rng, 3, 101, 0.5), 0
    yield "shifted_chains", ar1(rng, 4, 80, 0.3, shift=1.0), 2
    yield "one_chain", ar1(rng, 1, 60, 0.6), 0
    yield "ties", np.round(ar1(rng, 4, 50, 0.2) * 2) / 2, 2
    yield "heavy_tails", rng.standard_cauchy((4, 120)), 2
    yield "many_short", ar1(rng, 16, 8, 0.2), 4


def fmt(v):
    v = float(v)
    return "nan" if np.isnan(v) else v.hex()


def nested(x, k):
    if k == 0:
        return float("nan")
    per = x.shape[0] // k
    ids = np.repeat(np.arange(k), per)
    return D._rhat_nested_rank(x, ids)


def render():
    out = [HEADER]
    for name, x, k in cases():
        c, n = x.shape
        out.append(f"case {name} {c} {n} {k}\n")
        out.append("data " + " ".join(fmt(v) for v in x.ravel()) + "\n")
        split = D._split_chains(x)
        rhat = max(D._rhat(D._z_scale(split)), D._rhat(D._z_scale(abs(split - np.median(split)))))
        out.append(f"rhat {fmt(rhat)}\n")
        out.append(f"ess_bulk {fmt(D._ess_bulk(x))}\n")
        out.append(f"ess_tail {fmt(D._ess_tail(x, 0.05))}\n")
        out.append(f"mcse_mean {fmt(D._mcse_mean(x))}\n")
        out.append(f"nested_rhat {fmt(nested(x, k))}\n")
        out.append("ebfmi " + " ".join(fmt(v) for v in D._bfmi(x)) + "\n")
    return "".join(out)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    text = render()
    if args.check:
        if not GOLDEN.exists() or GOLDEN.read_text() != text:
            sys.exit(f"{GOLDEN} is stale")
        return
    GOLDEN.write_text(text)


if __name__ == "__main__":
    main()
