import argparse
import io
import json
import re
import sys
import urllib.request
import zipfile
from pathlib import Path

import numpy as np
from arviz_stats.base.diagnostics import _DiagnosticsBase

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "posteriordb.golden"

COMMIT = "91027f9cdd13b7e76283fec3f2898f59d4b83ec4"
ROOT = f"https://raw.githubusercontent.com/stan-dev/posteriordb/{COMMIT}/posterior_database"

NOTICE = __doc__[__doc__.index("BSD 3-Clause") :].strip()
HEADER = (
    "# generated by packages/norn/test/gen/posteriordb.py; do not edit\n"
    f"# Data and reference draws from posteriordb at {COMMIT}.\n"
    + "".join(f"# {l}".rstrip() + "\n" for l in NOTICE.splitlines())
)

# Each posterior with the data arrays its model reads.
POSTERIORS = [
    ("eight_schools-eight_schools_noncentered", ["y", "sigma"]),
    ("arK-arK", ["y"]),
    ("dogs-dogs", ["y"]),
    ("low_dim_gauss_mix-low_dim_gauss_mix", ["y"]),
    ("sblrc-blr", ["X", "y"]),
    ("gp_pois_regr-gp_pois_regr", ["x", "k"]),
]

D = _DiagnosticsBase()


def fetch_json(path):
    with urllib.request.urlopen(f"{ROOT}/{path}") as r:
        raw = r.read()
    if path.endswith(".zip"):
        with zipfile.ZipFile(io.BytesIO(raw)) as z:
            raw = z.read(z.namelist()[0])
    return json.loads(raw)


def fmt(v):
    return float(v).hex()


# "theta[3]" is element 2 of theta; "mu" is element 0 of mu.
def element(name):
    m = re.fullmatch(r"(\w+)\[(\d+)\]", name)
    if m is None:
        return name, 0
    return m.group(1), int(m.group(2)) - 1


def render():
    out = [HEADER]
    for name, arrays in POSTERIORS:
        info = fetch_json(f"posteriors/{name}.json")
        data = fetch_json(f"data/data/{info['data_name']}.json.zip")
        draws = fetch_json(f"reference_posteriors/draws/draws/{name}.json.zip")
        out.append(f"posterior {name}\n")
        for a in arrays:
            x = np.asarray(data[a], dtype=np.float64)
            dims = " ".join(str(d) for d in x.shape)
            values = " ".join(fmt(v) for v in x.ravel())
            out.append(f"data {a} {x.ndim} {dims} {values}\n")
        for e in draws[0]:
            x = np.array([chain[e] for chain in draws], dtype=np.float64)
            base, index = element(e)
            row = [x.mean(), x.std(ddof=1), D._mcse_mean(x), D._mcse_sd(x)]
            out.append(f"ref {base} {index} " + " ".join(fmt(v) for v in row) + "\n")
    return "".join(out)


def main():
    p = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    text = render()
    if args.check:
        if not GOLDEN.exists() or GOLDEN.read_text() != text:
            sys.exit(f"{GOLDEN} is stale; run without --check")
        return
    GOLDEN.write_text(text)


if __name__ == "__main__":
    main()
