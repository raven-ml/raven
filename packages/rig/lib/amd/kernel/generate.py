#!/usr/bin/env python3
"""Regenerate the private OCaml code objects with Clang and AMDGPU LLD 22."""

import argparse
from pathlib import Path
import struct
import subprocess
import tempfile

# Each generic target and the processors that run it, as LLVM lists them.
TARGETS = {
    "gfx9-4-generic": ("gfx940", "gfx941", "gfx942", "gfx950"),
    "gfx11-generic": ("gfx1100", "gfx1101", "gfx1102", "gfx1103", "gfx1150",
                      "gfx1151", "gfx1152", "gfx1153"),
    "gfx12-generic": ("gfx1200", "gfx1201"),
}
ROOT = Path(__file__).resolve().parent

# What the driver's dispatch of copy_bytes gives it: no private or group
# memory, 24 bytes of arguments and groups of 256 work-items.
ARGUMENT_BYTES = 24
GROUP_ITEMS = 256
NT_AMDGPU_METADATA = 32


# MessagePack's fixed-size numbers, and the strings, arrays and maps whose
# length follows their type byte.
NUMBERS = {0xcc: ">B", 0xcd: ">H", 0xce: ">I", 0xcf: ">Q",
           0xd0: ">b", 0xd1: ">h", 0xd2: ">i", 0xd3: ">q"}
SIZED = {0xd9: ("str", ">B"), 0xda: ("str", ">H"), 0xdb: ("str", ">I"),
         0xdc: ("array", ">H"), 0xdd: ("array", ">I"),
         0xde: ("map", ">H"), 0xdf: ("map", ">I")}


def unpack(b, i):
    """The MessagePack value at b[i] and the offset after it."""
    t = b[i]
    i += 1
    if t <= 0x7f or t >= 0xe0:
        return (t if t <= 0x7f else t - 256), i
    if t in (0xc2, 0xc3):
        return t == 0xc3, i
    if t in NUMBERS:
        f = NUMBERS[t]
        return struct.unpack_from(f, b, i)[0], i + struct.calcsize(f)
    if t in SIZED:
        kind, f = SIZED[t]
        n, = struct.unpack_from(f, b, i)
        i += struct.calcsize(f)
    elif 0xa0 <= t <= 0xbf:
        kind, n = "str", t & 0x1f
    elif 0x80 <= t <= 0x9f:
        kind, n = ("map" if t < 0x90 else "array"), t & 0x0f
    else:
        raise SystemExit(f"MessagePack type 0x{t:02x} in the metadata")
    if kind == "str":
        return b[i:i + n].decode(), i + n
    items = []
    for _ in range(2 * n if kind == "map" else n):
        v, i = unpack(b, i)
        items.append(v)
    return (dict(zip(items[::2], items[1::2])) if kind == "map" else items), i


def metadata(image):
    """The AMDGPU metadata note of the ELF64 image."""
    shoff, = struct.unpack_from("<Q", image, 0x28)
    shentsize, shnum = struct.unpack_from("<HH", image, 0x3a)
    for s in range(shnum):
        at = shoff + s * shentsize
        kind, = struct.unpack_from("<I", image, at + 4)
        offset, size = struct.unpack_from("<QQ", image, at + 0x18)
        if kind != 7:  # SHT_NOTE
            continue
        i = offset
        while i < offset + size:
            namesz, descsz, ntype = struct.unpack_from("<III", image, i)
            name = image[i + 12:i + 12 + namesz].rstrip(b"\0")
            desc = i + 12 + (namesz + 3) // 4 * 4
            if name == b"AMDGPU" and ntype == NT_AMDGPU_METADATA:
                return unpack(image[desc:desc + descsz], 0)[0]
            i = desc + (descsz + 3) // 4 * 4
    raise SystemExit("no AMDGPU metadata note")


def check(target, image):
    """Refuses an image whose copy_bytes is not what the driver dispatches."""
    meta = metadata(image)
    if meta["amdhsa.target"] != "amdgcn-amd-amdhsa--" + target:
        raise SystemExit(f"{target}: built for {meta['amdhsa.target']}")
    k = next((k for k in meta["amdhsa.kernels"] if k[".name"] == "copy_bytes"),
             None)
    if k is None:
        raise SystemExit(f"{target}: no kernel copy_bytes")
    explicit = max((a[".offset"] + a[".size"] for a in k[".args"]
                    if not a[".value_kind"].startswith("hidden_")), default=0)
    facts = [
        ("private segment", k[".private_segment_fixed_size"], 0),
        ("group segment", k[".group_segment_fixed_size"], 0),
        ("explicit arguments", explicit, ARGUMENT_BYTES),
    ]
    for what, got, want in facts:
        if got != want:
            raise SystemExit(f"{target}: {what} {got}, expected {want}")
    if k[".max_flat_workgroup_size"] < GROUP_ITEMS:
        raise SystemExit(f"{target}: groups of at most "
                         f"{k['.max_flat_workgroup_size']} work-items")


def emit(objects):
    lines = [
        "(* Generated by kernel/generate.py from kernel/copy.cl.",
        "   Copyright (c) Advanced Micro Devices, Inc., or its affiliates.",
        "   Copyright (c) 2026 The Raven authors.",
        "   SPDX-License-Identifier: MIT *)",
        "",
    ]
    cases = []
    for target, data in objects:
        name = target.replace("-", "_")
        members = " | ".join(f'"{p}"' for p in TARGETS[target])
        cases.append(f"  | {members} -> Some {name}")
        chunks = [data[i:i + 24] for i in range(0, len(data), 24)]
        lines.append(f"let {name} =")
        for i, chunk in enumerate(chunks):
            prefix = '  "' if i == 0 else "   "
            suffix = '"' if i == len(chunks) - 1 else "\\"
            lines.append(prefix + "".join(f"\\x{b:02x}" for b in chunk) + suffix)
        lines.append("")
    lines += ["let find = function", *cases, "  | _ -> None"]
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--clang", default="clang")
    parser.add_argument("--lld", default="ld.lld")
    args = parser.parse_args()
    objects = []
    with tempfile.TemporaryDirectory(prefix="rig-amd-copy-") as tmp:
        for target in TARGETS:
            obj = Path(tmp) / (target + ".o")
            image = Path(tmp) / (target + ".hsaco")
            subprocess.run([
                args.clang, "-c", "-x", "cl", "-cl-std=CL2.0",
                "-target", "amdgcn-amd-amdhsa", "-mcpu=" + target,
                "-mcode-object-version=6", "-nogpulib", "-O3",
                str(ROOT / "copy.cl"), "-o", str(obj),
            ], check=True)
            subprocess.run([args.lld, "-shared", str(obj), "-o", str(image)],
                           check=True)
            check(target, image.read_bytes())
            objects.append((target, image.read_bytes()))
    (ROOT.parent / "copy_kernel.ml").write_text(emit(objects))


if __name__ == "__main__":
    main()
