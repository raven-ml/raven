#!/usr/bin/env python3
"""Compile the private copy kernel and embed its ELF object."""

import argparse
import hashlib
from pathlib import Path
import re
import struct
import subprocess
import tempfile

# The attribute of .nv.info that holds a function's stack bytes, and the
# format of attributes that carry data.
EIATTR_MIN_STACK_SIZE = 0x12
EIFMT_SVAL = 4


def sections(blob):
    """The ELF64 object's sections, by name, as (offset, size)."""
    shoff, = struct.unpack_from("<Q", blob, 0x28)
    shentsize, shnum, shstrndx = struct.unpack_from("<HHH", blob, 0x3a)
    heads = [struct.unpack_from("<I4xQ8xQQ", blob, shoff + i * shentsize)
             for i in range(shnum)]
    names = heads[shstrndx][2]

    def name(at):
        return blob[names + at:blob.index(b"\0", names + at)].decode()

    return {name(n): (offset, size) for n, _, offset, size in heads}


def check(blob):
    """Refuses an object whose copy_bytes takes stack or shared memory: the
    driver launches it with no local memory."""
    s = sections(blob)
    shared = s.get(".nv.shared.copy_bytes", (0, 0))[1]
    if shared:
        raise SystemExit(f"copy_bytes takes {shared} shared bytes")
    offset, size = s[".symtab"]
    strtab = s[".strtab"][0]
    entries = struct.iter_unpack("<I20x", blob[offset:offset + size])
    symbols = [blob[strtab + n:blob.index(b"\0", strtab + n)]
               for n, in entries]
    copy = symbols.index(b"copy_bytes")
    at, size = s[".nv.info"]
    end = at + size
    while at < end:
        fmt, attribute, n = struct.unpack_from("<BBH", blob, at)
        data = n if fmt == EIFMT_SVAL else 0
        if fmt == EIFMT_SVAL and attribute == EIATTR_MIN_STACK_SIZE:
            symbol, stack = struct.unpack_from("<II", blob, at + 4)
            if symbol == copy and stack:
                raise SystemExit(f"copy_bytes takes {stack} stack bytes")
        at += 4 + data


here = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument("--nvcc", default="nvcc")
parser.add_argument("--object", type=Path, help="embed an already compiled sm80 object")
parser.add_argument("--check", action="store_true", help="check the embedded object")
args = parser.parse_args()
source = here / "copy.cu"
output = here.parent / "copy_kernel.ml"
if args.check:
    text = output.read_text()
    source_digest = hashlib.sha256(source.read_bytes()).hexdigest()
    if "Source SHA256: " + source_digest not in text:
        raise SystemExit("copy.cu changed: regenerate copy_kernel.ml")
    blob = bytes.fromhex("".join(re.findall(r"\\x([0-9a-f]{2})", text)))
    if "Object SHA256: " + hashlib.sha256(blob).hexdigest() not in text:
        raise SystemExit("copy_kernel.ml object changed: regenerate it")
    check(blob)
    raise SystemExit(0)
with tempfile.TemporaryDirectory() as directory:
    obj = args.object
    if obj is None:
        obj = Path(directory) / "copy_sm80.cubin"
        subprocess.run([args.nvcc, "-O3", "-arch=sm_80", "-cubin", str(source),
                        "-o", str(obj)], check=True)
    blob = obj.read_bytes()
    if blob[:4] != b"\x7fELF":
        raise SystemExit("expected a cubin ELF object")
    check(blob)
    lines = ["(* Generated by kernel/gen.py from copy.cu. *)",
             "(* Source SHA256: " + hashlib.sha256(source.read_bytes()).hexdigest() + " *)",
             "(* Object SHA256: " + hashlib.sha256(blob).hexdigest() + " *)",
             "let sm80 ="]
    for at in range(0, len(blob), 24):
        chunk = "".join("\\x%02x" % byte for byte in blob[at:at + 24])
        lines.append(('  "' if at == 0 else "   ") + chunk
                     + ('"' if at + 24 >= len(blob) else "\\"))
    lines += ["", "let find = function",
              '  | "sm_80" | "sm_86" | "sm_87" | "sm_89" -> Some sm80',
              "  | _ -> None", ""]
    output.write_text("\n".join(lines))
