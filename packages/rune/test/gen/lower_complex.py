"""Generate the exact values the compiled complex kinds are held to.

    uv run packages/rune/test/gen/lower_complex.py [--check]

Writes `packages/rune/test/golden/lower_complex/<kind>.golden`: one row per
point, its dtype (`c64` or `c128`), both parts of each operand, then each
part of the kind's exact value correctly rounded to binary64 and the
remainder past it rounded to binary64, as hexadecimal doubles. Values and
the side a zero part takes of a branch cut come from nx's generator,
packages/nx/test/kernel/gen/kinds.py, which this imports. A dtype's points are
nx's draws for the kind, pairs of the switch points test_lower_complex.ml
lists, the bands where a kind's value nears the greatest float or the least
normal one, and for the arithmetic kinds products and quotients at those
edges. A row is kept where every operand part is finite and the value's
modulus lies between the dtype's least normal and greatest float, where
the bounds hold. With --check nothing is written, and the run fails if a
golden would change.
"""

import argparse
import difflib
import math
import random
import sys
from pathlib import Path

import mpmath
from mpmath import mp, mpf

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parents[2] / "nx" / "test" / "kernel" / "gen"))
import kinds as nx  # noqa: E402

GOLDEN = HERE.parent / "golden" / "lower_complex"
HEADER = "# generated by packages/rune/test/gen/lower_complex.py; do not edit\n"

# A dtype's least normal and greatest float, and the exponents its values
# span.
RANGE = {
    "c64": (mpf(2) ** -126, (2 - mpf(2) ** -23) * mpf(2) ** 127, -149, 127),
    "c128": (mpf(2) ** -1022, (2 - mpf(2) ** -52) * mpf(2) ** 1023, -1074, 1023),
}

ARITH = {
    "mul": lambda z, w: z * w,
    "fdiv": lambda z, w: z / w,
    "recip": lambda z: 1 / z,
}

# Points


def single(fmt):
    return fmt == "c64"


def rounded_pt(fmt, pt):
    """pt with its parts rounded to fmt's, or None past its range."""
    if not single(fmt):
        return pt
    parts = [nx.f32(v) for v in pt]
    return None if any(v is None for v in parts) else tuple(parts)


def grid(fmt):
    """The switch points test_lower_complex.ml lists, of both signs."""
    common = [0.0, 1.0, 0.5, 2.0, 0.6, 0.8, 3.0, 1.5707963267948966, 3.141592653589793,
              19.9, 20.0, 20.1, 30.0, 1e-30, 1e5]
    if single(fmt):
        edges = [88.7, 89.4, 90.0, 194.0, 280.0, 1e30, 1e-38, 1e-45]
        edges += [float.fromhex(h) for h in ("0x1.fffffep127", "0x1.fffffep-1", "0x1.000002p0")]
    else:
        edges = [709.78, 710.4, 711.0, 1456.0, 2101.0, 1e300, 1e-300, 5e-324,
                 sys.float_info.max, float.fromhex("0x1.fffffffffffffp-1"),
                 1.0 + sys.float_info.epsilon]
    return [s * v for v in common + edges for s in (1, -1)]


def grid_pairs(fmt, rng, n):
    """n pairs of a switch point and a small part, either way round."""
    small = [0.0, -0.0, 0.5, 1.0, -2.0, 1.5707963267948966, 3.0, 1e-30]
    pairs = [(g, s) for g in grid(fmt) for s in small] + [(s, g) for g in grid(fmt) for s in small]
    return rng.sample(pairs, n)


def bands(fn, fmt, rng):
    """Operands where fn's value nears its dtype's greatest float or least
    normal one: e^x, 2^x, cosh and sinh past their overflow and near their
    underflow, the trigonometric kinds along the imaginary axis."""
    lo, hi, _, _ = RANGE[fmt]
    ln_hi, ln_lo = float(mpmath.log(hi)), float(mpmath.log(lo))
    out = []

    def u(a, b):
        return rng.uniform(a, b)

    if fn in ("exp", "exp2"):
        k = 1 / math.log(2) if fn == "exp2" else 1.0
        for _ in range(30):
            out.append((u(ln_hi - 6, ln_hi) * k, u(-3, 3)))
            out.append((u(ln_lo, ln_lo + 6) * k, u(-3, 3)))
    if fn in ("sinh", "cosh", "sin", "cos"):
        for _ in range(30):
            x = u(ln_hi - 3, ln_hi + math.log(2)) * rng.choice([1, -1])
            y = u(-3, 3)
            out.append((x, y) if fn in ("sinh", "cosh") else (y, x))
    return out


def arith_points(fn, fmt, rng):
    """Operands of mul, fdiv and recip: nx's draws for the kind's shape, and
    results near the greatest float and the least normal one, products
    whose parts cancel, and subnormal dividends over divisors whose larger
    part is between the least normal and 8 times it."""
    lo, hi, _, _ = RANGE[fmt]
    base = nx.complex_points("sqrt", rng, single(fmt))

    def polar(r, diagonal=False):
        """A number of modulus r, its angle away from the axes if diagonal,
        so that neither part is far below r."""
        t = rng.uniform(math.pi / 8, 3 * math.pi / 8) + rng.randint(0, 3) * math.pi / 2 \
            if diagonal else rng.uniform(-math.pi, math.pi)
        return (float(r) * math.cos(t), float(r) * math.sin(t))

    if fn == "recip":
        out = rng.sample(base, 200)
        for _ in range(30):
            out.append(polar(lo * rng.uniform(1, 8)))
            out.append(polar(1 / (lo * rng.uniform(4, 32)), diagonal=True))
        return [(z,) for z in out]
    out = [tuple(rng.sample(base, 2)) for _ in range(200)]
    for _ in range(20):
        r = mpf(2) ** rng.randint(-60, 60)
        a = polar(r)
        if fn == "mul":
            out.append((a, polar(hi * rng.uniform(0.25, 1) / r)))
            out.append((polar(r, diagonal=True),
                        polar(lo * rng.uniform(4, 32) / r, diagonal=True)))
            x, y = rng.uniform(1, 2), rng.uniform(1, 2)
            out.append(((x, y), (y * (1 + rng.uniform(-1e-6, 1e-6)), x)))
        else:
            out.append((a, polar(r / (hi * rng.uniform(0.25, 1)))))
            out.append((a, polar(r / (lo * rng.uniform(1, 8)))))
            sub = lo * rng.random()
            out.append(((sub * rng.choice([1, -1]), lo * rng.random()),
                        (float(lo) * rng.uniform(1, 8), float(8 * lo) * rng.uniform(-1, 1))))
    return out


def points(fn, fmt):
    rng = random.Random(f"rune2:lower_complex:{fn}:{fmt}")
    if fn in ARITH:
        pts = arith_points(fn, fmt, rng)
    elif fn == "pow":
        pws = nx.complex_powers(rng, single(fmt))
        pts = rng.sample(pws, min(400, len(pws)))
    else:
        nxs = nx.complex_points(fn, rng, single(fmt))
        pts = [(z,) for z in rng.sample(nxs, min(400, len(nxs)))]
        pts += [(z,) for z in grid_pairs(fmt, rng, 160) + bands(fn, fmt, rng)]
    out = []
    for args in pts:
        args = tuple(rounded_pt(fmt, tuple(float(v) for v in z)) for z in args)
        if all(z is not None and all(math.isfinite(v) for v in z) for z in args):
            out.append(args)
    return out


# Rows


def sided(f, flat):
    """f's value where a zero part stands for its side's limit, or None
    where that limit is no value, as at a pole: the value with the side
    2^-2000 in place of nx's 2^-3000 moves past 2^-100 of it."""
    v = nx.settled(f, flat)
    if all(o != 0 for o in flat):
        return v
    side, nx.SIDE = nx.SIDE, mpf(2) ** -2000
    try:
        w = nx.settled(f, flat)
    finally:
        nx.SIDE = side
    return v if abs(v - w) <= abs(v) * mpf(2) ** -100 else None


def value(fn, args):
    flat = tuple(v for z in args for v in z)
    if fn in ARITH:
        zs = [mpmath.mpc(mpf(x), mpf(y)) for x, y in args]
        if fn != "mul" and zs[-1] == 0:
            return None
        return nx.settled(lambda: ARITH[fn](*zs), flat)
    if fn == "pow":
        (x, y), (u, v) = args
        if x == 0 and y == 0:
            return None
        return sided(lambda: mpmath.power(nx.limit(x, y), nx.limit(u, v)), flat)
    (x, y), = args
    if fn == "sign" and x == 0 and y == 0:
        return None
    return sided(lambda: nx.COMPLEX[fn](nx.limit(x, y)), flat)


def row(fn, fmt, args):
    """The row of fn at args, or None where its value's modulus lies outside
    fmt's normal range."""
    v = value(fn, args)
    if v is None:
        return None
    lo, hi, _, _ = RANGE[fmt]
    if not lo <= abs(v) <= hi:
        return None
    cols = [fmt] + [nx.hexf(p) for z in args for p in z]
    return "\t".join(cols + [nx.rounded(v.real), nx.rounded(v.imag)]) + "\n"


def goldens():
    mp.prec = 320
    files = {}
    for fn in list(ARITH) + list(nx.COMPLEX):
        binary = fn in ("mul", "fdiv", "pow")
        cols = "dtype\tx\ty\tu\tv\tre\tlo\tim\tlo\n" if binary else "dtype\tx\ty\tre\tlo\tim\tlo\n"
        rows = []
        for fmt in RANGE:
            for args in points(fn, fmt):
                r = row(fn, fmt, args)
                if r is not None:
                    rows.append(r)
        files[fn] = HEADER + cols + "".join(rows)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    changed = False
    for fn, text in goldens().items():
        path = GOLDEN / f"{fn}.golden"
        old = path.read_text() if path.exists() else ""
        if old == text:
            continue
        changed = True
        if args.check:
            diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path),
                                        "regenerated", lineterm="", n=0)
            print("\n".join(list(diff)[:20]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path}")
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
