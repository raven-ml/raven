"""Generate the derivative goldens of nx's special functions.

    uv run packages/rune/test/gen/special_grad.py [--check]

Writes `packages/rune/test/golden/special_grad/<fn>.golden`: at the points of
nx's goldens (nx's test/gen/special.py) where the function and its
derivative are finite, the derivative in each argument, correctly rounded at
float32 and float64, in nx's golden format. `lgamma_2`, `lbeta_aa`,
`lbeta_bb` and `lbeta_ab` hold second derivatives; an incomplete gamma's
`<fn>_a`, `<fn>_x` and `<fn>_p` its derivative in each argument. A row whose
bound is scaled holds the scale: a reflection's terms, 1 + |log f| or an
inverse's condition number. With --check nothing is
written, and the run fails if a golden would change.
"""

import argparse
import difflib
import math
import sys
from pathlib import Path

import mpmath
from mpmath import mp, mpf

HERE = Path(__file__).resolve().parent
TEST = HERE.parent
GOLDEN = TEST / "golden" / "special_grad"
sys.path.insert(0, str(HERE.parents[2] / "nx" / "test" / "gen"))
import special as nx  # noqa: E402

HEADER = "# generated by packages/rune/test/gen/special_grad.py; do not edit\n"


def finite(fmt, f, *args):
    """Whether nx's reference of `f` at `args` is a finite number."""
    v = f.reference(fmt, *args)
    return not (math.isnan(v) or math.isinf(v))


def log_ndtr_slope(x):
    """phi / Phi; far below 0, -x over Phi's asymptotic series."""
    if x < -100:
        series = 1 + sum((-1) ** k * mpmath.fac2(2 * k - 1) / x ** (2 * k) for k in range(1, 41))
        return -x / series
    return mpmath.npdf(x) / mpmath.ncdf(x)


def vanishing(f, beyond):
    """`f`, zero beyond `beyond` in magnitude, where it underflows every
    dtype and mpmath would work at an exponent of the argument's square."""
    return lambda x: mpf(0) if abs(x) > beyond else f(x)


def reflection_scale(parts):
    """A row's scale below 0: one plus the magnitudes of the reflection's
    parts."""
    def extra(fmt, value, x):
        if x >= 0:
            return "1"
        with mp.workprec(fmt.p + 40):
            return nx.scale(1 + sum(abs(p(mpf(x))) for p in parts))
    return extra


def trigamma(x):
    """psi'; below 0 by its reflection, which mpmath's polygamma takes slowly
    far from 0."""
    if x < 0:
        return -mpmath.polygamma(1, 1 - x) + pi2_csc2(x)
    return mpmath.polygamma(1, x)


def pi_cot(x):
    return mpmath.pi * mpmath.cot(mpmath.pi * x)


def pi2_csc2(x):
    return (mpmath.pi / mpmath.sin(mpmath.pi * x)) ** 2


class Derivative:
    def __init__(self, name, of, d, extra=None, points=None, normal=None):
        self.name, self.of, self.d, self.extra = name, of, d, extra
        self.normal = normal
        self.points = points or of.points

    def golden(self):
        args = self.of.args
        columns = ["dtype"] + list(args) + ["f"] + (["scale"] if self.extra else [])
        lines = ["\t".join(columns)]
        for fmt in nx.FORMATS:
            seen = set()
            for p in self.points(fmt):
                p = p if isinstance(p, tuple) else (p,)
                if any(math.isnan(x) or math.isinf(x) for x in p) or p in seen:
                    continue
                seen.add(p)
                if not finite(fmt, self.of, *p):
                    continue
                if self.normal and not self.normal(fmt, *p):
                    continue
                value = nx.correctly_rounded(fmt, self.d, *p)
                if math.isinf(value):
                    continue
                row = [fmt.short] + [nx.hexf(x) for x in p] + [nx.hexf(value)]
                if self.extra:
                    row.append(self.extra(fmt, value, *p))
                lines.append("\t".join(row))
        return HEADER + "\n".join(lines) + "\n"


F = {f.name: f for f in nx.FUNCTIONS}


def lbeta_points(fmt):
    return [p for p in F["lbeta"].points(fmt) if max(p) <= 2.0 ** 40]


def lbeta_points_2(fmt):
    """lbeta's points where each argument is at least the largest float's
    reciprocal's cube root, below which 1/x^3, which a second derivative
    forms, overflows."""
    with mp.workprec(nx.POINT_PREC):
        least = mpf(fmt.max) ** (mpf(-1) / 3)
    return [p for p in lbeta_points(fmt) if min(p) >= least]


def exact_difference(f):
    """`f a b`, a difference of nearly equal terms when one argument is far
    below the other, at a precision past that ratio."""
    def g(a, b):
        extra = int(abs(mpmath.log(abs(a), 2)) + abs(mpmath.log(abs(b), 2))) + 64
        with mp.workprec(mp.prec + extra):
            return f(a, b)
    return g


def inside(lo, hi):
    """The points of nx's golden strictly inside (lo, hi)."""
    def points(f):
        return lambda fmt: [x for x in f.points(fmt) if lo < x < hi]
    return points


def hankel(nu, n=40):
    """The coefficients a_k of e^-x I_nu x ~ (2 pi x)^-1/2 sum_k a_k x^-k."""
    mu, a, cs = 4 * nu * nu, mpf(1), [mpf(1)]
    for k in range(1, n + 1):
        a *= -(mu - (2 * k - 1) ** 2) / mpf(8 * k)
        cs.append(a)
    return cs


def hankel_sum(cs, x):
    return sum(c / x ** k for k, c in enumerate(cs)) / mpmath.sqrt(2 * mpmath.pi * x)


def i0e_slope(x):
    """i1e x - sign x i0e x, its right-hand value -1 at 0. Far out, the
    difference of the two expansions, term by term, which mpmath would
    otherwise cancel to 0 at any precision Ziv's test tries."""
    a = abs(x)
    if a > nx.BESSEL_ASYMPTOTIC:
        r = hankel_sum([c1 - c0 for c0, c1 in zip(hankel(0), hankel(1))], a)
        return r if x >= 0 else -r
    return nx.i1e_exact(x) - (1 if x >= 0 else -1) * nx.i0e_exact(x)


def i1e_slope(x):
    """i0e a - i1e a / a - i1e a at a = |x|, even, 1/2 at 0; far out, as
    i0e_slope, one expansion."""
    a = abs(x)
    if a == 0:
        return mpf(1) / 2
    if a > nx.BESSEL_ASYMPTOTIC:
        c0, c1 = hankel(0), hankel(1)
        return hankel_sum([c0[k] - c1[k] - (c1[k - 1] if k else 0) for k in range(len(c0))], a)
    i1 = nx.i1e_exact(a)
    return nx.i0e_exact(a) - i1 / a - i1


def i1e_points(fmt):
    """i1e's points and the zero of its derivative near 1.545, with eight
    neighbours on each side, both signs."""
    with mp.workprec(120):
        zero = mpmath.findroot(lambda x: i1e_slope(x), mpf("1.545"))
    near = nx.neighbours(fmt, zero)
    return F["i1e"].points(fmt) + near + [-x for x in near]


# The incomplete gamma family. In x, the density x^(a - 1) e^-x / Gamma(a)
# with the tail's sign, over the tail for a logarithm; in a, mpmath's diff of
# the exact logarithm of the tail, times the tail for a linear function. An
# inverse's derivative is the reciprocal density in its probability and
# -(dP/da) / density in a, at the exact quantile. Each row's scale is 1 +
# |log f| for f the smaller tail, or the inverse's condition number.

def in_a(f, a, size=1):
    """f'(a) for a > 0, as the derivative in log a over a, so that no step
    leaves a > 0, with guard bits for a function of magnitude `size`."""
    with mp.workprec(mp.prec + int(mpmath.log(size + 1, 2)) + 20):
        return mpmath.diff(lambda t: f(mpmath.exp(t)), mpmath.log(a)) / a


def igamma_log_density(a, x):
    return a * mpmath.log(x) - x - mpmath.loggamma(a) - mpmath.log(x)


def igamma_d(tail, log, wrt):
    def d(a, x):
        if a == 0:
            # P = 1 - a E1(x) + O(a^2) for x > 0: in a, -E1(x) for P and its
            # logarithm, E1(x) for Q; in x, 0.
            if wrt == 1:
                return mpf(0)
            return mpmath.e1(x) if tail == 1 else -mpmath.e1(x)
        if x == 0:
            if log or wrt == 0:
                return mpf(0)
            slope = mpf(0) if a > 1 else mpf(1) if a == 1 else mpmath.inf
            return slope if tail == 0 else -slope
        sign = 1 if tail == 0 else -1
        if wrt == 1:
            # The density's and the tail's logarithms cancel where x is large:
            # guard bits for their size.
            size = abs(a * mpmath.log(x)) + x + abs(mpmath.loggamma(a)) + 1
            with mp.workprec(mp.prec + int(mpmath.log(size, 2)) + 20):
                lt = nx.igamma_exact(a, x)[tail]
                ld = igamma_log_density(a, x)
                return sign * mpmath.exp(ld - lt) if log else sign * mpmath.exp(ld)
        lt = nx.igamma_exact(a, x)[tail]
        dl = in_a(lambda s: nx.igamma_exact(s, x)[tail], a, abs(lt))
        return dl if log else dl * mpmath.exp(lt)
    return d


def igamma_log_scale(fmt, value, a, x):
    """1 + |log f|, f the smaller tail at the row's point: P's derivative is
    Q's negated, and carries the smaller tail's relative error."""
    if x == 0 or a == 0:
        return "1"
    with mp.workprec(fmt.p + 40):
        return nx.scale(1 + max(abs(t) for t in nx.igamma_exact(a, x)))


def igamma_quantile_d(upper, wrt):
    def d(a, p):
        if a == 0:
            # x = 0 for p < 1 at a = 0, and near it x is about (p Gamma(a +
            # 1))^(1/a), flat to every order in both arguments.
            return mpf(0)
        x = nx.igamma_quantile(a, p, upper)
        ld = igamma_log_density(a, x)
        if wrt == 1:
            return (-1 if upper else 1) * mpmath.exp(-ld)
        dlp = in_a(lambda s: nx.igamma_exact(s, x)[0], a)
        lp = nx.igamma_exact(a, x)[0]
        return -dlp * mpmath.exp(lp - ld)
    return d


# A derivative through the exponential of a logarithm underflows with the
# smaller tail: the linear functions' derivatives are held where it is
# normal, and at the domain's end x = 0, an inverse's where its result is.

def tails_normal(fmt, a, x):
    if x == 0 or a == 0:
        return True
    with mp.workprec(fmt.p + 40):
        return min(mpmath.exp(t) for t in nx.igamma_exact(a, x)) >= fmt.min_normal


def result_normal(f):
    return lambda fmt, a, p: a == 0 or abs(f.reference(fmt, a, p)) >= fmt.min_normal


def thinned(f, every=3):
    """Every third of nx's points where the derivative's arguments are in the
    domain of its bound, and the edge x = 0."""
    def points(fmt):
        pts = [p for p in f.points(fmt)
               if all(math.isfinite(v) for v in p) and 0 < p[0] <= nx.IGAMMA_A_MAX and p[1] >= 0]
        edges = ([(0.5, 0.0), (1.0, 0.0), (2.5, 0.0)]
                 + [(0.0, nx.round_to(fmt, mpf(x))) for x in ("1e-10", "0.5", "1.1", "3", "30")]
                 if f.args[1] == "x" else [])
        return pts[::every] + edges
    return points


def quantile_points(f):
    def points(fmt):
        return [p for p in thinned(f)(fmt) if 0 < p[1] < 1] + [(0.0, 0.125), (0.0, 0.5), (0.0, 0.875)]
    return points


DERIVATIVES = [
    Derivative("erfc", F["erfc"],
               vanishing(lambda x: -2 / mpmath.sqrt(mpmath.pi) * mpmath.exp(-x * x), 100)),
    Derivative("ndtr", F["ndtr"], vanishing(mpmath.npdf, 100)),
    Derivative("log_ndtr", F["log_ndtr"], log_ndtr_slope),
    Derivative("erfinv", F["erfinv"],
               lambda p: mpmath.sqrt(mpmath.pi) / 2 * mpmath.exp(mpmath.erfinv(p) ** 2),
               points=inside(-1, 1)(F["erfinv"])),
    Derivative("ndtri", F["ndtri"], lambda p: 1 / mpmath.npdf(nx.ndtri_exact(p)),
               points=inside(0, 1)(F["ndtri"])),
    Derivative("lgamma", F["lgamma"], mpmath.digamma,
               extra=reflection_scale([lambda x: mpmath.digamma(1 - x), pi_cot])),
    Derivative("digamma", F["digamma"], trigamma,
               extra=reflection_scale([lambda x: mpmath.polygamma(1, 1 - x), pi2_csc2])),
    Derivative("lbeta_a", F["lbeta"],
               exact_difference(lambda a, b: mpmath.digamma(a) - mpmath.digamma(a + b)),
               points=lbeta_points),
    Derivative("lbeta_b", F["lbeta"],
               exact_difference(lambda a, b: mpmath.digamma(b) - mpmath.digamma(a + b)),
               points=lbeta_points),
    Derivative("lgamma_2", F["lgamma"], trigamma,
               extra=reflection_scale([lambda x: mpmath.polygamma(1, 1 - x), pi2_csc2])),
    Derivative("lbeta_aa", F["lbeta"], exact_difference(lambda a, b: trigamma(a) - trigamma(a + b)),
               points=lbeta_points_2),
    Derivative("lbeta_bb", F["lbeta"], exact_difference(lambda a, b: trigamma(b) - trigamma(a + b)),
               points=lbeta_points_2),
    Derivative("lbeta_ab", F["lbeta"], lambda a, b: -trigamma(a + b), points=lbeta_points_2),
    Derivative("i0e", F["i0e"], i0e_slope),
    Derivative("i1e", F["i1e"], i1e_slope, points=i1e_points),
] + [
    Derivative(f"{name}_{arg}", F[name], igamma_d(tail, log, wrt), extra=igamma_log_scale,
               points=thinned(F[name]), normal=None if log else tails_normal)
    for name, tail, log in [("gammainc", 0, False), ("gammaincc", 1, False),
                            ("log_gammainc", 0, True), ("log_gammaincc", 1, True)]
    for arg, wrt in [("a", 0), ("x", 1)]
] + [
    Derivative(f"{name}_{arg}", F[name], igamma_quantile_d(upper, wrt),
               extra=nx.igamma_kappa(upper) if wrt == 1 else None, points=quantile_points(F[name]),
               normal=result_normal(F[name]))
    for name, upper in [("gammaincinv", False), ("gammainccinv", True)]
    for arg, wrt in [("a", 0), ("p", 1)]
]


def read(path):
    return path.read_text() if path.exists() else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a golden would change")
    args = parser.parse_args()
    files = {GOLDEN / f"{d.name}.golden": d.golden() for d in DERIVATIVES}
    changed = {path: body for path, body in files.items() if read(path) != body}
    if args.check:
        for path, body in changed.items():
            rel = path.relative_to(TEST)
            sys.stdout.writelines(difflib.unified_diff(
                (read(path) or "").splitlines(keepends=True), body.splitlines(keepends=True),
                fromfile=f"committed/{rel}", tofile=f"generated/{rel}"))
        if changed:
            sys.exit(1)
        print(f"{len(files)} goldens match")
        return
    GOLDEN.mkdir(parents=True, exist_ok=True)
    for path, body in changed.items():
        path.write_text(body)
        print(f"wrote {path.relative_to(TEST)}")


if __name__ == "__main__":
    main()
