HEADER = "# generated by packages/rune/test/gen/lower_real.py; do not edit\n"

# A dtype's precision, least normal exponent and the exponent its values stay
# below.
FORMATS = {"f32": (24, -126, 128), "f64": (53, -1022, 1024)}

# Stand-ins for values past the magnitudes where a kind's value rounds to its
# limit at both dtypes: each rounds as that value does.
HUGE = mpf(2) ** 1200
TINY = mpf(2) ** -1200

# Rounding


def round_to(v, fmt):
    """v correctly rounded to fmt, to nearest, ties to even, subnormals and
    overflow included."""
    p, emin, emax = FORMATS[fmt]
    if v == 0:
        return 0.0
    _, e = mpmath.frexp(v)
    q = max(e - 1, emin) - (p - 1)
    r = mpmath.ldexp(mpmath.nint(mpmath.ldexp(v, -q)), q)
    if abs(r) >= mpmath.ldexp(1, emax):
        return math.copysign(math.inf, v)
    return math.copysign(float(r), v)


def exact(x, fmt):
    """The float x, a Python float or an exact rational, rounded to fmt."""
    return round_to(mpf(float.fromhex(x) if isinstance(x, str) else x), fmt)


def bits(x, fmt):
    if fmt == "f32":
        return struct.unpack("<I", struct.pack("<f", x))[0]
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def of_bits(u, fmt):
    if fmt == "f32":
        return struct.unpack("<f", struct.pack("<I", u))[0]
    return struct.unpack("<d", struct.pack("<Q", u))[0]


def step(x, d, fmt):
    """The float d ranks of bits from x, or 0 past x's sign."""
    sign = 1 << (31 if fmt == "f32" else 63)
    u = bits(x, fmt)
    mag = (u & (sign - 1)) + d
    return 0.0 if mag <= 0 else of_bits((u & sign) | mag, fmt)


def usable(x):
    return math.isfinite(x) and x != 0


def hexf(x):
    return "nan" if x != x else x.hex()


# Points


def edges(fmt):
    """The least subnormal, the greatest subnormal, the least normal and the
    greatest float."""
    p, _, _ = FORMATS[fmt]
    least_normal = 1 << (p - 1)
    greatest = (((1 << (8 if fmt == "f32" else 11)) - 2) << (p - 1)) | (least_normal - 1)
    return [of_bits(u, fmt) for u in (1, least_normal - 1, least_normal, greatest)]


def specials(fmt):
    vs = [1.0, 0.5, 2.0] + edges(fmt)
    return vs + [-v for v in vs]


def near(xs, fmt, k=2, signed=True):
    """xs rounded to fmt, each with the k floats on each side of it, and
    their negations where signed."""
    out = []
    for x in xs:
        x = exact(x, fmt)
        if not usable(x):
            continue
        for v in ([x, -x] if signed else [x]):
            out += [step(v, d, fmt) for d in range(-k, k + 1)]
    return out


def uniform(rng, n, lo, hi, fmt):
    return [exact(mpf(lo) + (mpf(hi) - mpf(lo)) * mpf(rng.random()), fmt) for _ in range(n)]


def any_bits(rng, n, fmt, top_exp=None, low_exp=None, signed=True):
    """n floats of fmt log-uniform over the exponents [low_exp, top_exp],
    every exponent by default."""
    p, emin, emax = FORMATS[fmt]
    low = emin - p + 1 if low_exp is None else low_exp
    high = emax - 1 if top_exp is None else top_exp
    out = []
    for _ in range(n):
        m = mpf(1) + mpf(rng.getrandbits(p - 1)) / mpf(2) ** (p - 1)
        x = exact(mpmath.ldexp(m, rng.randint(low, high)), fmt)
        out.append(-x if signed and rng.random() < 0.5 else x)
    return out


def half_pis(fmt):
    """Multiples of pi/2 that reduce worst, and some past each dtype's switch
    to the big reduction."""
    with mp.workprec(400):
        return [k * mp.pi / 2 for k in (1, 2, 3, 4, 5, 6, 7, 355, 103993, 1 << 20, 1 << 27)]


