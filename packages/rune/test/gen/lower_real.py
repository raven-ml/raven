"""Generate the correctly rounded values the compiled float kinds are held to.

    uv run packages/rune/test/gen/lower_real.py [--check]

Writes `packages/rune/test/golden/lower_real/<kind>.golden`: one row per point,
its dtype (`f32` or `f64`), its operands and the kind's exact value correctly
rounded to that dtype, or `nan`, as hexadecimal doubles. Operands are finite
and not zero; test_lower_real.ml states the values C99 Annex F gives at
zeros, infinities and NaNs. A dtype's points are its edges, each kind's
switch points and their neighbours, and values drawn uniformly in a range
or over every exponent, all exact binary values. With --check nothing is
written, and the run fails if a golden would change.
"""

import argparse
