"""Generate the correctly rounded values the compiled float kinds are held to.

    uv run packages/rune/test/gen/lower_real.py [--check]

Writes `packages/rune/test/golden/lower_real/<kind>.golden`: one row per point,
its dtype (`f32` or `f64`), its operands and the kind's exact value correctly
rounded to that dtype, or `nan`, as hexadecimal doubles. Operands are finite
and not zero; test_lower_real.ml states the values C99 Annex F gives at
zeros, infinities and NaNs. A dtype's points are its edges, each kind's
switch points and their neighbours, and values drawn uniformly in a range
or over every exponent, all exact binary values. With --check nothing is
written, and the run fails if a golden would change.
"""

import argparse
import difflib
import math
import random
import struct
import sys
from pathlib import Path

import mpmath
from mpmath import mp, mpf

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "lower_real"
HEADER = "# generated by packages/rune/test/gen/lower_real.py; do not edit\n"

# A dtype's precision, least normal exponent and the exponent its values stay
# below.
FORMATS = {"f32": (24, -126, 128), "f64": (53, -1022, 1024)}

# Stand-ins for values past the magnitudes where a kind's value rounds to its
# limit at both dtypes: each rounds as that value does.
HUGE = mpf(2) ** 1200
TINY = mpf(2) ** -1200

# Rounding


def round_to(v, fmt):
    """v correctly rounded to fmt, to nearest, ties to even, subnormals and
    overflow included."""
    p, emin, emax = FORMATS[fmt]
    if v == 0:
        return 0.0
    _, e = mpmath.frexp(v)
    q = max(e - 1, emin) - (p - 1)
    r = mpmath.ldexp(mpmath.nint(mpmath.ldexp(v, -q)), q)
    if abs(r) >= mpmath.ldexp(1, emax):
        return math.copysign(math.inf, v)
    return math.copysign(float(r), v)


def exact(x, fmt):
    """The float x, a Python float or an exact rational, rounded to fmt."""
    return round_to(mpf(float.fromhex(x) if isinstance(x, str) else x), fmt)


def bits(x, fmt):
    if fmt == "f32":
        return struct.unpack("<I", struct.pack("<f", x))[0]
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def of_bits(u, fmt):
    if fmt == "f32":
        return struct.unpack("<f", struct.pack("<I", u))[0]
    return struct.unpack("<d", struct.pack("<Q", u))[0]


def step(x, d, fmt):
    """The float d ranks of bits from x, or 0 past x's sign."""
    sign = 1 << (31 if fmt == "f32" else 63)
    u = bits(x, fmt)
    mag = (u & (sign - 1)) + d
    return 0.0 if mag <= 0 else of_bits((u & sign) | mag, fmt)


def usable(x):
    return math.isfinite(x) and x != 0


def hexf(x):
    return "nan" if x != x else x.hex()


# Points


def edges(fmt):
    """The least subnormal, the greatest subnormal, the least normal and the
    greatest float."""
    p, _, _ = FORMATS[fmt]
    least_normal = 1 << (p - 1)
    greatest = (((1 << (8 if fmt == "f32" else 11)) - 2) << (p - 1)) | (least_normal - 1)
    return [of_bits(u, fmt) for u in (1, least_normal - 1, least_normal, greatest)]


def specials(fmt):
    vs = [1.0, 0.5, 2.0] + edges(fmt)
    return vs + [-v for v in vs]


def near(xs, fmt, k=2, signed=True):
    """xs rounded to fmt, each with the k floats on each side of it, and
    their negations where signed."""
    out = []
    for x in xs:
        x = exact(x, fmt)
        if not usable(x):
            continue
        for v in ([x, -x] if signed else [x]):
            out += [step(v, d, fmt) for d in range(-k, k + 1)]
    return out


def uniform(rng, n, lo, hi, fmt):
    return [exact(mpf(lo) + (mpf(hi) - mpf(lo)) * mpf(rng.random()), fmt) for _ in range(n)]


def any_bits(rng, n, fmt, top_exp=None, low_exp=None, signed=True):
    """n floats of fmt log-uniform over the exponents [low_exp, top_exp],
    every exponent by default."""
    p, emin, emax = FORMATS[fmt]
    low = emin - p + 1 if low_exp is None else low_exp
    high = emax - 1 if top_exp is None else top_exp
    out = []
    for _ in range(n):
        m = mpf(1) + mpf(rng.getrandbits(p - 1)) / mpf(2) ** (p - 1)
        x = exact(mpmath.ldexp(m, rng.randint(low, high)), fmt)
        out.append(-x if signed and rng.random() < 0.5 else x)
    return out


def pow_points(fmt):
    rng = random.Random(f"lower_real:pow:{fmt}")
    p, emin, emax = FORMATS[fmt]
    pairs = [(-2, 0.5), (-2, 3), (-2, 2), (-8, mpf(1) / 3), (-3, 2**53), (-3, 2**53 - 1),
             (-1, 2**24 - 1), (2, 1024), (2, -1075), (10, 308), (10, -320), (1.0000001, 1e9),
             (-1.5, 1e9 + 1), (2, 128), (2, -150), (10, 38), (10, -45), (-1, 3), (-1, 0.5)]
    # subnormal bases and results, and exponents y log2 |x| past 64
    far = {
        "f32": [("0x1.cp-147", "0x1p-1"), ("0x1.0bb15p+0", "-0x1.e30ecp+9"),
                ("0x1.000002p+1", "0x1.ead958p+6"), ("0x1.e5b66p-130", "-0x1.745282p-1"),
                ("0x1.67b4ccp-127", "0x1p+0"), ("0x1.cd360ep-1", "0x1.a67a5ap+9"),
                ("0x1p-149", "-0x1.555556p-2")],
        "f64": [("0x1.0000005a98fdcp+0", "0x1.c8cf46d10f26bp+34"),
                ("0x0.0000000000025p-1022", "-0x1.900084bf4d66p-1"),
                ("0x1.d961271d0722bp-342", "0x1.8p+1"),
                ("0x0.000000000000cp-1022", "-0x1.9e7b4d3dba0e7p-5"),
                ("0x1.fd3c200443b9bp-1023", "0x1.0061afdc4d90cp+0"),
                ("0x0.0000000000001p-1022", "0x1p-1")],
    }[fmt]
    pairs += [(float.fromhex(x), float.fromhex(y)) for x, y in far]
    ys = [1, -1, 0.5, -0.5, 2, -2, 3, -3]
    pairs += [(x, y) for x in specials(fmt) for y in ys]
    pairs += [(1, y) for y in any_bits(rng, 20, fmt)]
    for _ in range(250):
        x = any_bits(rng, 1, fmt, signed=False)[0]
        y = rng.choice([
            uniform(rng, 1, -10, 10, fmt)[0], float(rng.randint(-100, 100)),
            rng.randint(-40, 40) + 0.5, any_bits(rng, 1, fmt, low_exp=-60, top_exp=12)[0]])
        pairs.append((-x if rng.random() < 0.2 and y == int(y) else x, y))
    for _ in range(100):
        # near 1 with large exponents, where log x carries the result
        x = 1 + mpf(rng.uniform(-1, 1)) * mpf(2) ** rng.randint(-p + 1, -1)
        y = mpf(rng.uniform(-1, 1)) * mpf(2) ** rng.randint(10, 60)
        pairs.append((x, y))
    for _ in range(40):
        # results near the overflow and underflow thresholds
        x = exact(mpf(1.0001) + mpf(rng.random()) * 99, fmt)
        for t in (emax - 0.01, emin + 0.1, emin - p + 0.5):
            pairs.append((x, mpf(t) / mpmath.log(mpf(x), 2)))
    out = []
    for x, y in pairs:
        x, y = exact(x, fmt), exact(y, fmt)
        if usable(x) and usable(y):
            out.append((x, y))
    return out


# Exact values of finite, non-zero operands


def pow_ref(x, y):
    x, y = mpf(x), mpf(y)
    integer = y == mpmath.floor(y)
    if x < 0 and not integer:
        return None
    odd = integer and abs(y) < 2**53 and int(y) % 2 == 1
    if x == 1 or x == -1 and integer:
        return mpf(-1) if x == -1 and odd else mpf(1)
    t = y * mpmath.log(abs(x), 2)
    if t > 1200:
        v = HUGE
    elif t < -1200:
        v = TINY
    else:
        v = mpmath.power(abs(x), y)
    return -v if x < 0 and odd else v


def golden(rows):
    return HEADER + "".join("\t".join(r) + "\n" for r in rows)


def rounded(v, fmt):
    return "nan" if v is None else hexf(round_to(v, fmt))


def goldens():
    mp.prec = 320
    files = {}
    rows = [("dtype", "x", "y", "f")]
    for fmt in FORMATS:
        rows += [(fmt, hexf(x), hexf(y), rounded(pow_ref(x, y), fmt)) for x, y in pow_points(fmt)]
    files["pow"] = golden(rows)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    changed = False
    for fn, text in goldens().items():
        path = GOLDEN / f"{fn}.golden"
        old = path.read_text() if path.exists() else ""
        if old == text:
            continue
        changed = True
        if args.check:
            diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path),
                                        "regenerated", lineterm="", n=0)
            print("\n".join(list(diff)[:20]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path}")
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
