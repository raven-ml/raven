def unary_points(fn, fmt):
    rng = random.Random(f"lower_real:{fn}:{fmt}")
    pts, lo_hi = UNARY[fn]
    if fn in ("sin", "cos", "tan"):
        pts = TRIG + half_pis(fmt)
    xs = specials(fmt) + near(pts, fmt)
    xs += uniform(rng, 150, *lo_hi[fmt], fmt)
    xs += any_bits(rng, 100, fmt)
    if fn == "tanh":
        # past the split at 0.625, where 1 - 2 / (e^2a + 1) errs most
        xs += uniform(rng, 60, -2, 2, fmt)
    if fn in ("sin", "cos", "tan"):
        # past the switch to the big reduction, to the greatest float
        xs += any_bits(rng, 60, fmt, low_exp=15 if fmt == "f32" else 28)
    return [x for x in xs if usable(x)]


def pow_points(fmt):
    rng = random.Random(f"lower_real:pow:{fmt}")
    p, emin, emax = FORMATS[fmt]
    pairs = [(-2, 0.5), (-2, 3), (-2, 2), (-8, mpf(1) / 3), (-3, 2**53), (-3, 2**53 - 1),
             (-1, 2**24 - 1), (2, 1024), (2, -1075), (10, 308), (10, -320), (1.0000001, 1e9),
             (-1.5, 1e9 + 1), (2, 128), (2, -150), (10, 38), (10, -45), (-1, 3), (-1, 0.5)]
    # subnormal bases and results, and exponents y log2 |x| past 64
    far = {
        "f32": [("0x1.cp-147", "0x1p-1"), ("0x1.0bb15p+0", "-0x1.e30ecp+9"),
                ("0x1.000002p+1", "0x1.ead958p+6"), ("0x1.e5b66p-130", "-0x1.745282p-1"),
                ("0x1.67b4ccp-127", "0x1p+0"), ("0x1.cd360ep-1", "0x1.a67a5ap+9"),
                ("0x1p-149", "-0x1.555556p-2")],
        "f64": [("0x1.0000005a98fdcp+0", "0x1.c8cf46d10f26bp+34"),
                ("0x0.0000000000025p-1022", "-0x1.900084bf4d66p-1"),
                ("0x1.d961271d0722bp-342", "0x1.8p+1"),
                ("0x0.000000000000cp-1022", "-0x1.9e7b4d3dba0e7p-5"),
                ("0x1.fd3c200443b9bp-1023", "0x1.0061afdc4d90cp+0"),
                ("0x0.0000000000001p-1022", "0x1p-1")],
    }[fmt]
    pairs += [(float.fromhex(x), float.fromhex(y)) for x, y in far]
    ys = [1, -1, 0.5, -0.5, 2, -2, 3, -3]
    pairs += [(x, y) for x in specials(fmt) for y in ys]
    pairs += [(1, y) for y in any_bits(rng, 20, fmt)]
    for _ in range(250):
        x = any_bits(rng, 1, fmt, signed=False)[0]
        y = rng.choice([
            uniform(rng, 1, -10, 10, fmt)[0], float(rng.randint(-100, 100)),
            rng.randint(-40, 40) + 0.5, any_bits(rng, 1, fmt, low_exp=-60, top_exp=12)[0]])
        pairs.append((-x if rng.random() < 0.2 and y == int(y) else x, y))
    for _ in range(100):
        # near 1 with large exponents, where log x carries the result
        x = 1 + mpf(rng.uniform(-1, 1)) * mpf(2) ** rng.randint(-p + 1, -1)
        y = mpf(rng.uniform(-1, 1)) * mpf(2) ** rng.randint(10, 60)
        pairs.append((x, y))
    for _ in range(40):
        # results near the overflow and underflow thresholds
        x = exact(mpf(1.0001) + mpf(rng.random()) * 99, fmt)
        for t in (emax - 0.01, emin + 0.1, emin - p + 0.5):
            pairs.append((x, mpf(t) / mpmath.log(mpf(x), 2)))
    out = []
    for x, y in pairs:
        x, y = exact(x, fmt), exact(y, fmt)
        if usable(x) and usable(y):
            out.append((x, y))
    return out


def atan2_points(fmt):
    rng = random.Random(f"lower_real:atan2:{fmt}")
    pts = [1, 0.4375, 0.6875, 1.1875, 2.4375, 1e10, 1e300, "0x1p-960"]
    vs = specials(fmt) + near(pts, fmt, k=0)
    pairs = [(y, x) for y in vs for x in vs]
    # the ratios y / x at atan's switch points and their neighbours
    pairs += [(v, 1.0) for v in near(pts, fmt)] + [(1.0, v) for v in near(pts, fmt)]
    pairs += list(zip(any_bits(rng, 300, fmt), any_bits(rng, 300, fmt)))
    pairs += list(zip(uniform(rng, 150, -4, 4, fmt), uniform(rng, 150, -4, 4, fmt)))
    return [(exact(y, fmt), exact(x, fmt)) for y, x in pairs
            if usable(exact(y, fmt)) and usable(exact(x, fmt))]


# Exact values of finite, non-zero operands


def limit(x, beyond, below, above):
    """A stand-in past the point where the value rounds to its limit."""
    if x > beyond:
        return above
    if x < -beyond:
        return below
    return None


def unary_ref(fn, x):
    x = mpf(x)
    if fn in ("log", "log2") and x < 0 or fn == "log1p" and x < -1:
        return None
    if fn in ("asin", "acos") and abs(x) > 1:
        return None
    if fn == "log1p" and x == -1:
        return -HUGE
    far = {
        "exp": (1200, TINY, HUGE), "exp2": (1200, TINY, HUGE), "expm1": (1200, -1 + TINY, HUGE),
        "sinh": (1200, -HUGE, HUGE), "cosh": (1200, HUGE, HUGE),
        "tanh": (1000, -1 + TINY, 1 - TINY), "erf": (30, -1 + TINY, 1 - TINY),
    }.get(fn)
    if far is not None:
        v = limit(x, *far)
        if v is not None:
            return v
    f = {
        "exp": mpmath.exp, "exp2": lambda v: mpmath.power(2, v), "expm1": mpmath.expm1,
        "log": mpmath.log, "log2": lambda v: mpmath.log(v, 2), "log1p": mpmath.log1p,
        "sin": mpmath.sin, "cos": mpmath.cos, "tan": mpmath.tan, "asin": mpmath.asin,
        "acos": mpmath.acos, "atan": mpmath.atan, "sinh": mpmath.sinh, "cosh": mpmath.cosh,
        "tanh": mpmath.tanh, "erf": mpmath.erf,
    }[fn]
    return f(x)


def pow_ref(x, y):
    x, y = mpf(x), mpf(y)
    integer = y == mpmath.floor(y)
    if x < 0 and not integer:
        return None
    odd = integer and abs(y) < 2**53 and int(y) % 2 == 1
    if x == 1 or x == -1 and integer:
        return mpf(-1) if x == -1 and odd else mpf(1)
    t = y * mpmath.log(abs(x), 2)
    if t > 1200:
        v = HUGE
    elif t < -1200:
        v = TINY
    else:
        v = mpmath.power(abs(x), y)
    return -v if x < 0 and odd else v


def golden(rows):
    return HEADER + "".join("\t".join(r) + "\n" for r in rows)


def rounded(v, fmt):
    return "nan" if v is None else hexf(round_to(v, fmt))


def goldens():
    mp.prec = 320
    files = {}
    for fn in UNARY:
        rows = [("dtype", "x", "f")]
        for fmt in FORMATS:
            rows += [(fmt, hexf(x), rounded(unary_ref(fn, x), fmt))
                     for x in unary_points(fn, fmt)]
        files[fn] = golden(rows)
    rows = [("dtype", "x", "y", "f")]
    for fmt in FORMATS:
        rows += [(fmt, hexf(x), hexf(y), rounded(pow_ref(x, y), fmt)) for x, y in pow_points(fmt)]
    files["pow"] = golden(rows)
    rows = [("dtype", "y", "x", "f")]
    for fmt in FORMATS:
        rows += [(fmt, hexf(y), hexf(x), rounded(mpmath.atan2(mpf(y), mpf(x)), fmt))
                 for y, x in atan2_points(fmt)]
    files["atan2"] = golden(rows)
    return files


def main():
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    changed = False
    for fn, text in goldens().items():
        path = GOLDEN / f"{fn}.golden"
        old = path.read_text() if path.exists() else ""
        if old == text:
            continue
        changed = True
        if args.check:
            diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path),
                                        "regenerated", lineterm="", n=0)
            print("\n".join(list(diff)[:20]))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
            print(f"wrote {path}")
    if args.check and changed:
        sys.exit(1)


if __name__ == "__main__":
    main()
