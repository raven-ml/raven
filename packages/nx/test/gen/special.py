    below = [(a, max(a, IGAMMA_CORNER) * (1 - 2.0 ** -40)) for a in (1, 1.05, 1.5, 2, 3, 5, 8, 12, 16, 19.99)]
    above = [(a, (1 - IGAMMA_TEMME_WIDTH) * a) for a in (20, 50, 200, 1e3, 1e4, 2.0 ** 20)]
