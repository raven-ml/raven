# Formats


class Format:
    def __init__(self, name, short, p, emin, emax):
        self.name, self.short = name, short
        self.p, self.emin, self.emax = p, emin, emax
        self.u = 2.0 ** -p
        self.eps = 2.0 ** (1 - p)
        self.tiny = 2.0 ** (emin - p + 1)
        self.min_normal = 2.0 ** emin
        self.max = (2.0 - 2.0 ** (1 - p)) * 2.0 ** emax


F32 = Format("float32", "f32", 24, -126, 127)
F64 = Format("float64", "f64", 53, -1022, 1023)
FORMATS = [F32, F64]


class Overflow(float):
    """An infinity a finite value rounds to past the format's range, which a
    golden writes as `overflow`: the largest finite float is one ulp from it,
    where an exact infinity is held exactly."""


def round_to(fmt, v):
    """`v`, an mpf, rounded to nearest even in `fmt`, as a Python float."""
    if mpmath.isnan(v):
        return math.nan
    if mpmath.isinf(v):
        return math.inf if v > 0 else -math.inf
    if v == 0:
        return 0.0
    sign = -1.0 if v < 0 else 1.0
    a = abs(v)
    _, exp = mpmath.frexp(a)
    e = int(exp) - 1
    if e > fmt.emax:
        return Overflow(sign * math.inf)
    q = max(e, fmt.emin) - (fmt.p - 1)
    scaled = mpmath.ldexp(a, -q)
    n = int(mpmath.floor(scaled))
    frac = scaled - n
    if frac > 0.5 or (frac == 0.5 and n % 2 == 1):
        n += 1
    r = math.ldexp(n, q) if q > -1100 else float(mpmath.ldexp(n, q))
    if r > fmt.max:
        return Overflow(sign * math.inf)
    return sign * r


def bits(fmt, x):
    if fmt is F32:
        return struct.unpack("<I", struct.pack("<f", x))[0]
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def of_bits(fmt, b):
    if fmt is F32:
        return struct.unpack("<f", struct.pack("<I", b))[0]
    return struct.unpack("<d", struct.pack("<Q", b))[0]


def next_up(fmt, x):
    """The least float of `fmt` above `x`, a float of `fmt`."""
    if math.isnan(x) or x == math.inf:
        return x
    if x == 0:
        return fmt.tiny
    b = bits(fmt, x)
    return of_bits(fmt, b + 1 if x > 0 else b - 1)


def next_down(fmt, x):
    return -next_up(fmt, -x)


def representable(fmt, x):
    return math.isnan(x) or round_to(fmt, mpf(x)) == x


def neighbours(fmt, c, k=8):
    """`c` rounded to `fmt` and the `k` floats on each side."""
    x = round_to(fmt, mpf(c))
    ups, downs, u, d = [], [], x, x
    for _ in range(k):
        u, d = next_up(fmt, u), next_down(fmt, d)
        ups.append(u)
        downs.append(d)
    return downs[::-1] + [x] + ups


# The precision points are computed at, by mpmath, so that no platform's libm
# moves a point.
POINT_PREC = 100


def log_sweep(fmt, lo, hi, n):
    """`n` floats of `fmt` log-spaced over `[lo, hi]`, both positive."""
    with mp.workprec(POINT_PREC):
        a, b = mpmath.log(mpf(lo)), mpmath.log(mpf(hi))
        return [round_to(fmt, mpmath.exp(a + (b - a) * i / (n - 1))) for i in range(n)]


def uniform(fmt, rng, lo, hi, n):
    return [round_to(fmt, mpf(rng.uniform(lo, hi))) for _ in range(n)]


def specials(fmt):
    """Zeros, subnormals, the extremes and the infinities."""
    sub = [fmt.tiny, 2 * fmt.tiny, round_to(fmt, mpf(fmt.min_normal) / 3), next_down(fmt, fmt.min_normal)]
    return [0.0, -0.0, fmt.min_normal, fmt.max, math.inf, -math.inf] + sub + [-s for s in sub]


# Correctly rounded references

def correctly_rounded(fmt, f, *args):
    """`f args` rounded to `fmt`, at precisions that agree on the rounding."""
    prec = fmt.p + 40
    while True:
        with mp.workprec(prec):
            r1 = round_to(fmt, f(*[mpf(a) for a in args]))
        with mp.workprec(2 * prec):
            r2 = round_to(fmt, f(*[mpf(a) for a in args]))
        if r1 == r2 or (math.isnan(r1) and math.isnan(r2)):
            return r2
        prec *= 2
        if prec > 20000:
            raise RuntimeError(f"no stable rounding for {f.__name__}{args}")


def hexf(x):
    if isinstance(x, Overflow):
        return "overflow" if x > 0 else "-overflow"
    if math.isnan(x):
        return "nan"
    if math.isinf(x):
        return "infinity" if x > 0 else "-infinity"
    return x.hex()


def scale(v):
    """A positive scale, rounded up to 4 significant digits."""
    if mpmath.isinf(v) or v > 1e300:
        return "infinity"
    s = float(v)
    if s == 0:
        return "0"
    e = int(mpmath.floor(mpmath.log10(abs(mpf(s)))))
    m = math.ceil(abs(s) / 10 ** (e - 3))
    return f"{m}e{e - 3}"


# Functions
#
# A function is its reference, the points it is held to per format, and the
# extra column of each row, if it has one.


class Function:
    def __init__(self, name, args, reference, points, extra=None):
        self.name, self.args = name, args
        self.reference, self.points, self.extra = reference, points, extra

    def rows(self, fmt):
        seen, rows = set(), []
        for p in self.points(fmt):
            p = p if isinstance(p, tuple) else (p,)
            key = tuple(bits(fmt, x) if not math.isnan(x) else -1 for x in p)
            if key in seen:
                continue
            assert all(representable(fmt, x) for x in p), (self.name, p)
            seen.add(key)
            value = self.reference(fmt, *p)
            row = [fmt.short] + [hexf(x) for x in p] + [hexf(value)]
            if self.extra:
                row.append(self.extra(fmt, value, *p))
            rows.append(row)
        return rows

    def golden(self):
        columns = ["dtype"] + list(self.args) + ["f"] + (["kappa" if "kappa" in self.extra.__name__ else "scale"] if self.extra else [])
        lines = ["\t".join(columns)]
        for fmt in FORMATS:
            lines += ["\t".join(r) for r in self.rows(fmt)]
        return HEADER + "\n".join(lines) + "\n"


def odd(f):
    """A reference odd in its argument: the sign of a zero result follows the
    argument's."""
    def g(fmt, x):
        if math.isnan(x):
            return math.nan
        r = correctly_rounded(fmt, f, x)
        return math.copysign(r, x) if r == 0 else r
    return g


def standard(fmt, rng, lo, hi, n_sweep=48, n_random=96):
    """Signed log-spaced sweeps of [lo, hi], uniform points in [-hi, hi], NaN
    and the special values."""
    sweep = log_sweep(fmt, lo, hi, n_sweep)
    return ([math.nan] + specials(fmt) + sweep + [-x for x in sweep]
            + uniform(fmt, rng, -hi, hi, n_random))


# erf: the backend's. Its points are the boundaries of fdlibm's regions, where
# the compiled erf changes formula, and the points where it rounds to 1.

def erf_reference(fmt, x):
    if math.isinf(x):
        return math.copysign(1.0, x)
    return odd(mpmath.erf)(fmt, x)


def saturation(fmt, f, lo, hi, target):
    """The least float of `fmt` in [lo, hi] where `f` rounds to `target`."""
    while next_up(fmt, lo) < hi:
        mid = round_to(fmt, mpf((lo + hi) / 2))
        if mid in (lo, hi):
            break
        if correctly_rounded(fmt, f, mid) == target:
            hi = mid
        else:
            lo = mid
    return hi


def erf_points(fmt):
    rng = random.Random(f"erf {fmt.name}")
    edges = [2.0 ** -28, 0.84375, 1.25, 1 / 0.35, 6.0, saturation(fmt, mpmath.erf, 1.0, 7.0, 1.0)]
    points = [x for c in edges for x in neighbours(fmt, c)]
    return standard(fmt, rng, fmt.tiny, 30.0) + points + [-x for x in points]


# erfinv: an inverse of erf on (-1, 1). Its points are where its guess changes
# polynomial (in w = -log ((1 - p)(1 + p))), where its Newton step changes
# residual (|p| = erf 1.25), the ends, and floats crowded against them.

def erfinv_reference(fmt, x):
    if math.isnan(x) or abs(x) > 1:
        return math.nan
    if abs(x) == 1:
        return math.copysign(math.inf, x)
    return odd(mpmath.erfinv)(fmt, x)


def kappa(fmt, value, x):
    """|p / (x F'(x))| at x = erfinv p, F = erf."""
    p = mpf(x)
    if math.isnan(value) or math.isinf(value) or p == 0:
        return "1" if p == 0 else "infinity"
    with mp.workprec(fmt.p + 40):
        y = mpmath.erfinv(p)
        return scale(abs(p / (y * 2 / mpmath.sqrt(mpmath.pi) * mpmath.exp(-y * y))))


