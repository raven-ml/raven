def tables():
    shared = shared_tables()
    rows = {F32: per_dtype(F32), F64: per_dtype(F64)}
    out = [comment(HEADER[2:]), ""]
    for name, value in shared:
        text = comment(COMMENTS[name]) + "\n" if name in COMMENTS else ""
        out.append(f"{text}let {name} = {value}\n" if not value.startswith("[|")
                   else f"{text}let {name} =\n  {value}\n")
    fields = [name for name, _ in rows[F64]]
    decl = ["(* The tables whose values differ between dtypes. *)", "type t = {"]
    for name in fields:
        kind = ocaml_kind(rows[F64][fields.index(name)][1])
        if name in PER_DTYPE:
            decl.append("  " + comment(PER_DTYPE[name]).replace("\n", "\n  "))
        decl.append(f"  {name} : {kind};")
    decl.append("}\n")
    out.append("\n".join(decl))
    for fmt, label in [(F32, "float32"), (F64, "float64")]:
        body = [f"let {label} =", "  {"]
        for name, value in rows[fmt]:
            value = value.replace("\n", "\n    ")
            body.append(f"    {name} = {value};")
        body.append("  }\n")
        out.append("\n".join(body))
    return "\n".join(out)


# Driver


def outputs():
    files = {TABLES: tables()}
    for f in FUNCTIONS:
        files[GOLDEN / f"{f.name}.golden"] = f.golden()
    return files


def read(path):
    return path.read_text() if path.exists() else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a file would change")
    args = parser.parse_args()
    files = outputs()
    changed = {path: body for path, body in files.items() if read(path) != body}
    if args.check:
        for path, body in changed.items():
            rel = path.relative_to(NX)
            sys.stdout.writelines(difflib.unified_diff(
                (read(path) or "").splitlines(keepends=True), body.splitlines(keepends=True),
                fromfile=f"committed/{rel}", tofile=f"generated/{rel}"))
        if changed:
            sys.exit(1)
        print(f"{len(files)} files match")
        return
    GOLDEN.mkdir(parents=True, exist_ok=True)
    for path, body in changed.items():
        path.write_text(body)
        print(f"wrote {path.relative_to(NX)}")


if __name__ == "__main__":
    main()
