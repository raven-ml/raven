def cached():
    """The committed goldens' rows by key. A golden is the oracle's table of
    each point's correctly rounded value, so a run reuses the rows whose
    function, dtype and arguments it already holds."""
    rows = {}
    for f in FUNCTIONS:
        path = GOLDEN / f"{f.name}.golden"
        if not path.exists():
            continue
        lines = [line for line in path.read_text().splitlines() if not line.startswith("#")]
        for line in lines[1:]:
            cells = line.split("\t")
            rows[(f.name,) + tuple(cells[:1 + len(f.args)])] = line
    return rows


def outputs(jobs, fresh):
    """Every golden: rows the committed goldens hold, unless `fresh`, and the
    rest computed by `jobs` processes, as a reference far past mpmath's
    series takes seconds."""
    oracle.check()
    tasks = [(f.name, fmt.short, p) for f in FUNCTIONS for fmt in FORMATS for p in f.unique(fmt)]
    rows = {} if fresh else cached()
    todo = [t for t in tasks if key(*t) not in rows]
    print(f"computing {len(todo)} of {len(tasks)} rows", file=sys.stderr)
    with multiprocessing.get_context("fork").Pool(jobs) as pool:
        for t, r in zip(todo, pool.map(row, todo, chunksize=1)):
            rows[key(*t)] = r
    by_function = {f.name: [] for f in FUNCTIONS}
    for t in tasks:
        by_function[t[0]].append(rows[key(*t)])
    return {GOLDEN / f"{f.name}.golden": f.golden(by_function[f.name]) for f in FUNCTIONS}


def read(path):
    return path.read_text() if path.exists() else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a golden would change")
    parser.add_argument("--scipy", action="store_true", help="hold the committed goldens to scipy.special")
    parser.add_argument("--jobs", type=int, default=4, help="processes computing rows (default 4)")
    parser.add_argument("--fresh", action="store_true", help="compute every row, reusing none of the goldens'")
    args = parser.parse_args()
    if args.scipy:
        scipy_datapoint()
        return
    files = outputs(args.jobs, args.fresh)
    changed = {path: body for path, body in files.items() if read(path) != body}
    if args.check:
        for path, body in changed.items():
            rel = path.relative_to(ROOT)
            sys.stdout.writelines(difflib.unified_diff(
                (read(path) or "").splitlines(keepends=True), body.splitlines(keepends=True),
                fromfile=f"committed/{rel}", tofile=f"generated/{rel}"))
        if changed:
            sys.exit(1)
        print(f"{len(files)} goldens match")
        return
    GOLDEN.mkdir(parents=True, exist_ok=True)
    for path, body in changed.items():
        path.write_text(body)
        print(f"wrote {path.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
