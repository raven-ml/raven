"""Generate nx's special-function accuracy goldens.

    uv run packages/nx/test/gen/special.py [--check] [--fresh] [--jobs N]

Writes `packages/nx/test/golden/special/<fn>.golden`, the points each
function is held to. With --check nothing is written, and the run fails if
a golden would change.

The goldens are the cache: a run reuses each committed row whose function,
dtype and arguments it computes again, and computes the rest, so a change of
points costs only the new ones. --fresh computes every row from oracle.py
again, as a change to oracle.py or to a reference needs; the incomplete
gamma and beta families take hours. `--check --fresh` proves the goldens.

A golden is a table of hexadecimal floats, one row per point and dtype:
the arguments, exactly representable in the dtype, and the value correctly
rounded to it. An inverse's row also holds `kappa`, its condition number
|p / (x F'(x))| at the result; a row whose bound is absolute and scaled by
the function holds that scale.

Values come from oracle.py, mpmath's functions; nothing here or there
follows nx's algorithms. The points surround the boundaries of nx's
regions, which special_tables.py, the generator of nx's tables, defines.

    uv run --with scipy==1.16.3 --with numpy==2.3.4 packages/nx/test/gen/special.py --scipy

reads the committed goldens and reports how far their float64 rows of the
incomplete gamma and beta families and their inverses are from
scipy.special's, Boost's float64 implementations: a second, independent
and coarser datapoint.
"""

