# scipy's datapoint

SCIPY = "1.16.3"
SCIPY_TOLERANCE = 2.0 ** -30


def scipy_datapoint():
    """Prints how many of each golden's float64 rows, normal and with normal
    arguments, disagree with scipy.special's past SCIPY_TOLERANCE, and the
    worst. Boost's inverses lose accuracy at extreme probabilities, so this
    reports and does not fail."""
    import scipy
    import scipy.special as sc
    if scipy.__version__ != SCIPY:
        sys.exit(f"scipy {scipy.__version__}, not {SCIPY}")
    functions = {
        "gammainc": sc.gammainc, "gammaincc": sc.gammaincc,
        "gammaincinv": sc.gammaincinv, "gammainccinv": sc.gammainccinv,
        "betainc": sc.betainc, "betaincc": sc.betaincc,
        "betaincinv": sc.betaincinv, "betainccinv": sc.betainccinv,
    }
    for name, f in functions.items():
        header, *lines = (GOLDEN / f"{name}.golden").read_text().splitlines()[1:]
        columns = header.split("\t")
        args = slice(1, columns.index("f"))
        worst, at, n, past = 0.0, None, 0, 0
        for line in lines:
            cells = line.split("\t")
            if cells[0] != "f64" or not all("x" in c for c in cells[1:columns.index("f") + 1]):
                continue
            x = [float.fromhex(c) for c in cells[args]]
            want = float.fromhex(cells[columns.index("f")])
            got = float(f(*x))
            if any(0 < abs(v) < F64.min_normal for v in x):
                continue
            if min(abs(want), abs(got)) < F64.min_normal or not math.isfinite(got):
                continue
            n += 1
            d = abs(got - want) / abs(want)
            past += d > SCIPY_TOLERANCE
            if d > worst:
                worst, at = d, (x, want, got)
        print(f"{name}: {n} rows, {past} past {SCIPY_TOLERANCE:.3g}, worst {worst:.3g} at {at}")


