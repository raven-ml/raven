"""Generate nx's special-function tables and accuracy goldens.

    uv run packages/nx/test/gen/special.py [--check]

Writes `packages/nx/lib/special_tables.ml`, the coefficients, region
boundaries and counts of nx's special functions per compute dtype, and
`packages/nx/test/golden/special/<fn>.golden`, the points each function is
held to. With --check nothing is written, and the run fails if a file would
change: the tables and the proofs they carry disagree.

A golden is a table of hexadecimal floats, one row per point and dtype:
the arguments, exactly representable in the dtype, and the value correctly
rounded to it. An inverse's row also holds `kappa`, its condition number
|p / (x F'(x))| at the result; a row whose bound is absolute and scaled by
the function holds that scale.
"""

import argparse
import difflib
import math
import random
import struct
import sys
from pathlib import Path

import mpmath
from mpmath import mp, mpf

HERE = Path(__file__).resolve().parent
NX = HERE.parents[1]
TABLES = NX / "lib" / "special_tables.ml"
GOLDEN = NX / "test" / "golden" / "special"
HEADER = "# generated by packages/nx/test/gen/special.py; do not edit\n"


# Formats


class Format:
    def __init__(self, name, short, p, emin, emax):
        self.name, self.short = name, short
        self.p, self.emin, self.emax = p, emin, emax
        self.u = 2.0 ** -p
        self.eps = 2.0 ** (1 - p)
        self.tiny = 2.0 ** (emin - p + 1)
        self.min_normal = 2.0 ** emin
        self.max = (2.0 - 2.0 ** (1 - p)) * 2.0 ** emax


F32 = Format("float32", "f32", 24, -126, 127)
F64 = Format("float64", "f64", 53, -1022, 1023)
FORMATS = [F32, F64]


def round_to(fmt, v):
    """`v`, an mpf, rounded to nearest even in `fmt`, as a Python float."""
    if mpmath.isnan(v):
        return math.nan
    if mpmath.isinf(v):
        return math.inf if v > 0 else -math.inf
    if v == 0:
        return 0.0
    sign = -1.0 if v < 0 else 1.0
    a = abs(v)
    _, exp = mpmath.frexp(a)
    e = int(exp) - 1
    if e > fmt.emax:
        return sign * math.inf
    q = max(e, fmt.emin) - (fmt.p - 1)
    scaled = mpmath.ldexp(a, -q)
    n = int(mpmath.floor(scaled))
    frac = scaled - n
    if frac > 0.5 or (frac == 0.5 and n % 2 == 1):
        n += 1
    r = math.ldexp(n, q) if q > -1100 else float(mpmath.ldexp(n, q))
    if r > fmt.max:
        return sign * math.inf
    return sign * r


def bits(fmt, x):
    if fmt is F32:
        return struct.unpack("<I", struct.pack("<f", x))[0]
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def of_bits(fmt, b):
    if fmt is F32:
        return struct.unpack("<f", struct.pack("<I", b))[0]
    return struct.unpack("<d", struct.pack("<Q", b))[0]


def next_up(fmt, x):
    """The least float of `fmt` above `x`, a float of `fmt`."""
    if math.isnan(x) or x == math.inf:
        return x
    if x == 0:
        return fmt.tiny
    b = bits(fmt, x)
    return of_bits(fmt, b + 1 if x > 0 else b - 1)


def next_down(fmt, x):
    return -next_up(fmt, -x)


def representable(fmt, x):
    return math.isnan(x) or round_to(fmt, mpf(x)) == x


def neighbours(fmt, c, k=8):
    """`c` rounded to `fmt` and the `k` floats on each side."""
    x = round_to(fmt, mpf(c))
    ups, downs, u, d = [], [], x, x
    for _ in range(k):
        u, d = next_up(fmt, u), next_down(fmt, d)
        ups.append(u)
        downs.append(d)
    return downs[::-1] + [x] + ups


def log_sweep(fmt, lo, hi, n):
    """`n` floats of `fmt` log-spaced over `[lo, hi]`, both positive, computed
    by mpmath so that no platform's libm moves a point."""
    with mp.workprec(100):
        a, b = mpmath.log(mpf(lo)), mpmath.log(mpf(hi))
        return [round_to(fmt, mpmath.exp(a + (b - a) * i / (n - 1))) for i in range(n)]


def uniform(fmt, rng, lo, hi, n):
    return [round_to(fmt, mpf(rng.uniform(lo, hi))) for _ in range(n)]


def specials(fmt):
    """Zeros, subnormals, the extremes and the infinities."""
    sub = [fmt.tiny, 2 * fmt.tiny, round_to(fmt, mpf(fmt.min_normal) / 3), next_down(fmt, fmt.min_normal)]
    return [0.0, -0.0, fmt.min_normal, fmt.max, math.inf, -math.inf] + sub + [-s for s in sub]


# Correctly rounded references

def correctly_rounded(fmt, f, *args):
    """`f args` rounded to `fmt`, at precisions that agree on the rounding."""
    prec = fmt.p + 40
    while True:
        with mp.workprec(prec):
            r1 = round_to(fmt, f(*[mpf(a) for a in args]))
        with mp.workprec(2 * prec):
            r2 = round_to(fmt, f(*[mpf(a) for a in args]))
        if r1 == r2 or (math.isnan(r1) and math.isnan(r2)):
            return r2
        prec *= 2
        if prec > 20000:
            raise RuntimeError(f"no stable rounding for {f.__name__}{args}")


def hexf(x):
    if math.isnan(x):
        return "nan"
    if math.isinf(x):
        return "infinity" if x > 0 else "-infinity"
    return x.hex()


def scale(v):
    """A positive scale, rounded up to 4 significant digits."""
    if mpmath.isinf(v) or v > 1e300:
        return "infinity"
    s = float(v)
    if s == 0:
        return "0"
    e = int(mpmath.floor(mpmath.log10(abs(mpf(s)))))
    m = math.ceil(abs(s) / 10 ** (e - 3))
    return f"{m}e{e - 3}"


# Functions
#
# A function is its reference, the points it is held to per format, and the
# extra column of each row, if it has one.


class Function:
    def __init__(self, name, args, reference, points, extra=None):
        self.name, self.args = name, args
        self.reference, self.points, self.extra = reference, points, extra

    def rows(self, fmt):
        seen, rows = set(), []
        for p in self.points(fmt):
            p = p if isinstance(p, tuple) else (p,)
            key = tuple(bits(fmt, x) if not math.isnan(x) else -1 for x in p)
            if key in seen:
                continue
            assert all(representable(fmt, x) for x in p), (self.name, p)
            seen.add(key)
            value = self.reference(fmt, *p)
            row = [fmt.short] + [hexf(x) for x in p] + [hexf(value)]
            if self.extra:
                row.append(self.extra(fmt, value, *p))
            rows.append(row)
        return rows

    def golden(self):
        columns = ["dtype"] + list(self.args) + ["f"] + ([self.extra.__name__] if self.extra else [])
        lines = ["\t".join(columns)]
        for fmt in FORMATS:
            lines += ["\t".join(r) for r in self.rows(fmt)]
        return HEADER + "\n".join(lines) + "\n"


def odd(f):
    """A reference odd in its argument: the sign of a zero result follows the
    argument's."""
    def g(fmt, x):
        if math.isnan(x):
            return math.nan
        r = correctly_rounded(fmt, f, x)
        return math.copysign(r, x) if r == 0 else r
    return g


def standard(fmt, rng, lo, hi, n_sweep=48, n_random=96):
    """Signed log-spaced sweeps of [lo, hi], uniform points in [-hi, hi], NaN
    and the special values."""
    sweep = log_sweep(fmt, lo, hi, n_sweep)
    return ([math.nan] + specials(fmt) + sweep + [-x for x in sweep]
            + uniform(fmt, rng, -hi, hi, n_random))


# erf: the backend's. Its points are the boundaries of fdlibm's regions, where
# the compiled erf changes formula, and the points where it rounds to 1.

def erf_reference(fmt, x):
    if math.isinf(x):
        return math.copysign(1.0, x)
    return odd(mpmath.erf)(fmt, x)


def saturation(fmt, f, lo, hi, target):
    """The least float of `fmt` in [lo, hi] where `f` rounds to `target`."""
    while next_up(fmt, lo) < hi:
        mid = round_to(fmt, mpf((lo + hi) / 2))
        if mid in (lo, hi):
            break
        if correctly_rounded(fmt, f, mid) == target:
            hi = mid
        else:
            lo = mid
    return hi


def erf_points(fmt):
    rng = random.Random(f"erf {fmt.name}")
    edges = [2.0 ** -28, 0.84375, 1.25, 1 / 0.35, 6.0, saturation(fmt, mpmath.erf, 1.0, 7.0, 1.0)]
    points = [x for c in edges for x in neighbours(fmt, c)]
    return standard(fmt, rng, fmt.tiny, 30.0) + points + [-x for x in points]


# erfinv: an inverse of erf on (-1, 1). Its points are where its guess changes
# polynomial (w = 5, w = -log ((1 - x)(1 + x))), where the float64 refinement
# changes residual (|y| = 2), the ends, and floats crowded against them.

def erfinv_reference(fmt, x):
    if math.isnan(x) or abs(x) > 1:
        return math.nan
    if abs(x) == 1:
        return math.copysign(math.inf, x)
    return odd(mpmath.erfinv)(fmt, x)


def kappa(fmt, value, x):
    """|p / (x F'(x))| at x = erfinv p, F = erf."""
    p = mpf(x)
    if math.isnan(value) or math.isinf(value) or p == 0:
        return "1" if p == 0 else "infinity"
    with mp.workprec(fmt.p + 40):
        y = mpmath.erfinv(p)
        return scale(abs(p / (y * 2 / mpmath.sqrt(mpmath.pi) * mpmath.exp(-y * y))))


# erfinv's regions: its guess switches polynomial at w = 5, w = -log ((1 -
# p)(1 + p)), and its float64 refinement switches residual at |p| = erf 2.

ERFINV_W_SPLIT = 5.0
ERFINV_CENTRAL_SHIFT = 2.5
ERFINV_TAIL_SHIFT = 3.0
ERFINV_REFINE_SPLIT = 2.0
ERF_SERIES_TERMS = 80
ERFC_FRACTION_TERMS = 64


def erfinv_split():
    """|p| where w = 5, and erf 2, at 100 bits."""
    with mp.workprec(100):
        return (mpmath.sqrt(1 - mpmath.exp(-ERFINV_W_SPLIT)), mpmath.erf(ERFINV_REFINE_SPLIT))


def erfinv_points(fmt):
    rng = random.Random(f"erfinv {fmt.name}")
    edges = list(erfinv_split()) + [1.0]
    near_one = [1 - 2.0 ** -k for k in range(2, fmt.p + 1)]
    points = [x for c in edges for x in neighbours(fmt, c)] + [round_to(fmt, mpf(x)) for x in near_one]
    sweep = log_sweep(fmt, fmt.tiny, 0.5, 48)
    return ([math.nan, 0.0, -0.0, math.inf, -math.inf, 2.0, -2.0] + sweep + [-x for x in sweep]
            + uniform(fmt, rng, -1, 1, 96) + points + [-x for x in points])


FUNCTIONS = [
    Function("erf", ["x"], erf_reference, erf_points),
    Function("erfinv", ["x"], erfinv_reference, erfinv_points, extra=kappa),
]


# Tables
#
# Each table is an OCaml binding with the comment that names its source.
# Coefficients are written as hexadecimal floats, exact.


def ocaml_float(x):
    if x == 0:
        return "0."
    mantissa, exponent = x.hex().split("p")
    mantissa = mantissa.rstrip("0").rstrip(".")
    return f"{mantissa}p{exponent}"


def ocaml_array(xs):
    return "[|\n" + "".join(f"    {ocaml_float(x)};\n" for x in xs) + "  |]"


def comment(text):
    """`text` as an OCaml comment wrapped at 80 columns, as ocamlformat
    wraps it."""
    words, lines, line = text.split(), [], "(*"
    for w in words:
        if len(line) + 1 + len(w) > 80:
            lines.append(line)
            line = "  "
        line += " " + w
    lines.append(line + " *)" if len(line) + 3 <= 80 else line + "\n   *)")
    return "\n".join(lines)


def binding(text, name, value):
    return f"{comment(text)}\nlet {name} =\n  {value}\n"


# erfinv's first guess: Giles, "Approximating the erfinv function", GPU
# Computing Gems Jade (2011), its single-precision polynomials
# (erfinv_SP_1.cu), each coefficient the float32 its source writes, highest
# degree first.

GILES_SP_CENTRAL = ["2.81022636e-08", "3.43273939e-07", "-3.5233877e-06", "-4.39150654e-06",
                    "0.00021858087", "-0.00125372503", "-0.00417768164", "0.246640727", "1.50140941"]
GILES_SP_TAIL = ["-0.000200214257", "0.000100950558", "0.00134934322", "-0.00367342844",
                 "0.00573950773", "-0.0076224613", "0.00943887047", "1.00167406", "2.83297682"]


def single(decimals):
    with mp.workprec(200):
        return [round_to(F32, mpf(d)) for d in decimals]


def tables():
    giles = "Giles, Approximating the erfinv function, GPU Computing Gems Jade (2011), single precision"
    parts = [
        binding(f"erfinv's guess below [w = erfinv_w_split], [w = -log ((1 - p)(1 + p))], a "
                f"polynomial in [w - erfinv_central_shift]: {giles}.",
                "erfinv_central", ocaml_array(single(GILES_SP_CENTRAL))),
        binding("Its guess from [w = erfinv_w_split], a polynomial in [sqrt w - erfinv_tail_shift].",
                "erfinv_tail", ocaml_array(single(GILES_SP_TAIL))),
        binding("Where the guess changes polynomial.", "erfinv_w_split", ocaml_float(ERFINV_W_SPLIT)),
        binding("The central polynomial's origin in [w].", "erfinv_central_shift",
                ocaml_float(ERFINV_CENTRAL_SHIFT)),
        binding("The tail polynomial's origin in [sqrt w].", "erfinv_tail_shift",
                ocaml_float(ERFINV_TAIL_SHIFT)),
        binding("erf 2, below which in [|p|] the float64 refinement runs Newton on erf's series, "
                "and from which on erfc's continued fraction.",
                "erfinv_erf2", ocaml_float(round_to(F64, erfinv_split()[1]))),
        binding("The series' terms.", "erf_series_terms", str(ERF_SERIES_TERMS)),
        binding("The continued fraction's terms.", "erfc_fraction_terms", str(ERFC_FRACTION_TERMS)),
    ]
    return comment(HEADER[2:]) + "\n\n" + "\n".join(parts)


# Driver


def outputs():
    files = {TABLES: tables()}
    for f in FUNCTIONS:
        files[GOLDEN / f"{f.name}.golden"] = f.golden()
    return files


def read(path):
    return path.read_text() if path.exists() else None


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a file would change")
    args = parser.parse_args()
    files = outputs()
    changed = {path: body for path, body in files.items() if read(path) != body}
    if args.check:
        for path, body in changed.items():
            rel = path.relative_to(NX)
            sys.stdout.writelines(difflib.unified_diff(
                (read(path) or "").splitlines(keepends=True), body.splitlines(keepends=True),
                fromfile=f"committed/{rel}", tofile=f"generated/{rel}"))
        if changed:
            sys.exit(1)
        print(f"{len(files)} files match")
        return
    GOLDEN.mkdir(parents=True, exist_ok=True)
    for path, body in changed.items():
        path.write_text(body)
        print(f"wrote {path.relative_to(NX)}")


if __name__ == "__main__":
    main()
