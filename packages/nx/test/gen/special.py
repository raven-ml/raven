def ocaml_float(x):
    if x == 0:
        return "0."
    mantissa, exponent = x.hex().split("p")
    mantissa = mantissa.rstrip("0").rstrip(".")
    return f"{mantissa}p{exponent}"


def ocaml_array(xs):
    return "[|\n" + "".join(f"    {ocaml_float(x)};\n" for x in xs) + "  |]"


def ocaml_matrix(rows):
    return "[|\n" + "".join(
        "    [|\n" + "".join(f"      {ocaml_float(x)};\n" for x in row) + "    |];\n" for row in rows) + "  |]"


def ocaml_kind(value):
    if value.startswith("[|\n    [|"):
        return "float array array"
    if value.startswith("[|"):
        return "float array"
    return "int" if value.isdigit() else "float"


def comment(text):
    """`text` as an OCaml comment wrapped at 80 columns, as ocamlformat
    wraps it."""
    words, lines, line = text.split(), [], "(*"
    for w in words:
        if len(line) + 1 + len(w) > 80:
            lines.append(line)
            line = "  "
        line += " " + w
    lines.append(line + " *)" if len(line) + 3 <= 80 else line + "\n   *)")
    return "\n".join(lines)


def binding(text, name, value):
    return f"{comment(text)}\nlet {name} =\n  {value}\n"


