def fdlibm(table, names):
    """The doubles of `names` in `table`, each checked against its words."""
    out = []
    for n in names:
        decimal, word = table[n]
        x = float(decimal)
        if bits(F64, x) != word:
            sys.exit(f"fdlibm {n}: {decimal} is not 0x{word:016X}")
        out.append(x)
    return out


