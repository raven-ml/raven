# A function is its reference, the points it is held to per format, and the
# extra column of each row, if it has one.


class Function:
    def __init__(self, name, args, reference, points, extra=None):
        self.name, self.args = name, args
        self.reference, self.points, self.extra = reference, points, extra

    def unique(self, fmt):
        """The points of `fmt`, each once, as tuples."""
        seen, points = set(), []
        for p in self.points(fmt):
            p = p if isinstance(p, tuple) else (p,)
            key = tuple(bits(fmt, x) if not math.isnan(x) else -1 for x in p)
            if key in seen:
                continue
            assert all(representable(fmt, x) for x in p), (self.name, p)
            seen.add(key)
            points.append(p)
        return points

    def row(self, fmt, p):
        value = self.reference(fmt, *p)
        row = [fmt.short] + [hexf(x) for x in p] + [hexf(value)]
        if self.extra:
            row.append(self.extra(fmt, value, *p))
        return "\t".join(row)

    def golden(self, rows):
        columns = ["dtype"] + list(self.args) + ["f"] + (["kappa" if "kappa" in self.extra.__name__ else "scale"] if self.extra else [])
        return HEADER + "\n".join(["\t".join(columns)] + rows) + "\n"


def odd(f):
    """A reference odd in its argument: the sign of a zero result follows the
    argument's."""
    def g(fmt, x):
        if math.isnan(x):
            return math.nan
        r = correctly_rounded(fmt, f, x)
        return math.copysign(r, x) if r == 0 else r
    return g


def standard(fmt, rng, lo, hi, n_sweep=48, n_random=96):
    """Signed log-spaced sweeps of [lo, hi], uniform points in [-hi, hi], NaN
    and the special values."""
    sweep = log_sweep(fmt, lo, hi, n_sweep)
    return ([math.nan] + specials(fmt) + sweep + [-x for x in sweep]
            + uniform(fmt, rng, -hi, hi, n_random))


# erf: the backend's. Its points are the boundaries of fdlibm's regions, where
# the compiled erf changes formula, and the points where it rounds to 1.

def erf_reference(fmt, x):
    if math.isinf(x):
        return math.copysign(1.0, x)
    return odd(mpmath.erf)(fmt, x)


def saturation(fmt, f, lo, hi, target):
    """The least float of `fmt` in [lo, hi] where `f` rounds to `target`."""
    while next_up(fmt, lo) < hi:
        mid = round_to(fmt, mpf((lo + hi) / 2))
        if mid in (lo, hi):
            break
        if correctly_rounded(fmt, f, mid) == target:
            hi = mid
        else:
            lo = mid
    return hi


def erf_points(fmt):
    rng = random.Random(f"erf {fmt.name}")
    edges = [2.0 ** -28, 0.84375, 1.25, 1 / 0.35, 6.0, saturation(fmt, mpmath.erf, 1.0, 7.0, 1.0)]
    points = [x for c in edges for x in neighbours(fmt, c)]
    return standard(fmt, rng, fmt.tiny, 30.0) + points + [-x for x in points]


# erfinv: an inverse of erf on (-1, 1). Its points are where its guess changes
# polynomial (in w = -log ((1 - p)(1 + p))), where its Newton step changes
# residual (|p| = erf 1.25), the ends, and floats crowded against them.

def erfinv_reference(fmt, x):
    if math.isnan(x) or abs(x) > 1:
        return math.nan
    if abs(x) == 1:
        return math.copysign(math.inf, x)
    return odd(mpmath.erfinv)(fmt, x)


def kappa(fmt, value, x):
    """|p / (x F'(x))| at x = erfinv p, F = erf."""
    p = mpf(x)
    if math.isnan(value) or math.isinf(value) or p == 0:
        return "1" if p == 0 else "infinity"
    with mp.workprec(fmt.p + 40):
        y = mpmath.erfinv(p)
        return scale(abs(p / (y * 2 / mpmath.sqrt(mpmath.pi) * mpmath.exp(-y * y))))


def erfinv_points(fmt):
    rng = random.Random(f"erfinv {fmt.name}")
    edges = [float(e) for e in erfinv_split(fmt)] + [1.0]
    near_one = [1 - 2.0 ** -k for k in range(2, fmt.p + 1)]
    points = [x for c in edges for x in neighbours(fmt, c)] + [round_to(fmt, mpf(x)) for x in near_one]
    sweep = log_sweep(fmt, fmt.tiny, 0.5, 48)
    return ([math.nan, 0.0, -0.0, math.inf, -math.inf, 2.0, -2.0] + sweep + [-x for x in sweep]
            + uniform(fmt, rng, -1, 1, 96) + points + [-x for x in points])


# erfc, ndtr and log_ndtr: their points are the boundaries of erfc's regions,
# mapped through -x/sqrt 2 for ndtr, log_ndtr's own, and where each
# underflows or saturates.

ERFC_EDGES = [ERFC_SMALL_SPLIT, ERF_SMALL_BELOW, ERF_NEAR_BELOW, ERFC_MID_BELOW, ERFC_FAR_FROM]


def plain(f, lo_limit, hi_limit):
    """A reference of one argument that rounds to its limits beyond 100 in
    magnitude."""
    def g(fmt, x):
        if math.isnan(x):
            return math.nan
        if x < -100:
            return lo_limit
        if x > 100:
            return hi_limit
        return correctly_rounded(fmt, f, x)
    return g


def thresholds(fmt, f, lo, hi):
    """Where `f`, decreasing on [lo, hi], first rounds to a subnormal and to
    zero."""
    def first(target):
        a, b = lo, hi
        while True:
            mid = round_to(fmt, (mpf(a) + mpf(b)) / 2)
            if mid in (a, b):
                return b
            if target(abs(correctly_rounded(fmt, f, mid))):
                b = mid
            else:
                a = mid
    return [first(lambda v: v < fmt.min_normal), first(lambda v: v == 0)]


def sqrt2_times(fmt, e):
    """`e sqrt 2` rounded to `fmt`: an erfc boundary in ndtr's argument."""
    with mp.workprec(POINT_PREC):
        return round_to(fmt, mpf(e) * mpmath.sqrt(2))


def erfc_points(fmt):
    rng = random.Random(f"erfc {fmt.name}")
    edges = ERFC_EDGES + thresholds(fmt, mpmath.erfc, 1.0, 30.0)
    points = [x for c in edges for x in neighbours(fmt, c)]
    two = saturation(fmt, lambda x: mpmath.erfc(-x), 1.0, 30.0, 2.0)
    return (standard(fmt, rng, fmt.tiny, 30.0) + points + [-x for x in points]
            + [-x for x in neighbours(fmt, two)])


def ndtr_points(fmt):
    rng = random.Random(f"ndtr {fmt.name}")
    edges = [sqrt2_times(fmt, e) for e in ERFC_EDGES] + [-t for t in thresholds(fmt, lambda x: mpmath.ncdf(-x), 1.0, 45.0)]
    points = [x for c in edges for x in neighbours(fmt, c)]
    one = saturation(fmt, mpmath.ncdf, 1.0, 45.0, 1.0)
    return (standard(fmt, rng, fmt.tiny, 45.0) + points + [-x for x in points]
            + neighbours(fmt, one))


def log_ndtr_reference(fmt, x):
    if math.isnan(x):
        return math.nan
    if x == math.inf:
        return -0.0
    if x == -math.inf:
        return -math.inf
    if x > 100:
        return -0.0
    return correctly_rounded(fmt, oracle.log_ndtr, x)


def log_ndtr_points(fmt):
    rng = random.Random(f"log_ndtr {fmt.name}")
    edges = [0.0, LOG_NDTR_BELOW[fmt]] + [-sqrt2_times(fmt, e) for e in ERFC_EDGES]
    points = [x for c in edges for x in neighbours(fmt, c)]
    far = log_sweep(fmt, 10.0, fmt.max, 64)
    with mp.workprec(POINT_PREC):
        overflow = round_to(fmt, mpmath.sqrt(2 * mpf(fmt.max)))
    return (standard(fmt, rng, fmt.tiny, 45.0) + points + [-x for x in far]
            + [-x for x in neighbours(fmt, overflow)]
            + [x for x in neighbours(fmt, 8.0)] + [37.5, 40.0])


# ndtri: its regions are |p - 1/2| <= 0.425 and sqrt (-log q) = 5, q the
# nearer tail.

def ndtri_reference(fmt, p):
    if math.isnan(p) or p < 0 or p > 1:
        return math.nan
    if p == 0:
        return -math.inf
    if p == 1:
        return math.inf
    return correctly_rounded(fmt, oracle.ndtri, p)


def ndtri_kappa(fmt, value, p):
    """|p / (x Phi'(x))| at x = ndtri p."""
    if math.isnan(value) or math.isinf(value):
        return "infinity"
    if p == 0.5:
        return "1"
    with mp.workprec(fmt.p + 40):
        x = oracle.ndtri(p)
        return scale(abs(mpf(p) / (x * mpmath.npdf(x))))


def ndtri_points(fmt):
    rng = random.Random(f"ndtri {fmt.name}")
    with mp.workprec(POINT_PREC):
        tail = round_to(fmt, mpmath.exp(-mpf(NDTRI_NEAR_BELOW) ** 2))
    edges = [round_to(fmt, mpf(1) / 2 - mpf(NDTRI_CENTRAL_BELOW)),
             round_to(fmt, mpf(1) / 2 + mpf(NDTRI_CENTRAL_BELOW)), tail, 0.5]
    points = [x for c in edges for x in neighbours(fmt, c)]
    near = [round_to(fmt, mpf(1) - mpf(2) ** -k) for k in range(2, fmt.p + 1)]
    sweep = log_sweep(fmt, fmt.tiny, 0.5, 64)
    return ([math.nan, 0.0, -0.0, 1.0, -1.0, 2.0, math.inf, -math.inf] + sweep + near
            + uniform(fmt, rng, 0, 1, 96) + [p for p in points if 0 <= p <= 1]
            + [next_up(fmt, 0.0), next_down(fmt, 1.0)])


# lgamma: log |Gamma x|. Its points are fdlibm's region boundaries, the
# zeros at 1 and 2 and the negative ones, the poles, and where it overflows.

def lgamma_exact(x):
    if x > 0:
        return mpmath.loggamma(x)
    return mpmath.re(mpmath.loggamma(x))


def lgamma_reference(fmt, x):
    if math.isnan(x) or x == -math.inf:
        return math.nan
    if x == math.inf or (x <= 0 and x == math.floor(x)):
        return math.inf
    return correctly_rounded(fmt, lgamma_exact, x)


def lgamma_scale(fmt, value, x):
    """1 + lgamma (1 - x), the scale of the absolute bound below 0."""
    if math.isnan(x) or x >= 0 or math.isinf(x) or x == math.floor(x):
        return "1"
    with mp.workprec(fmt.p + 40):
        return scale(1 + abs(lgamma_exact(1 - mpf(x))))


def negative_zeros(f, n):
    """The roots of `f` on (-k - 1, -k) for k < n, where it has one."""
    roots = []
    with mp.workprec(120):
        for k in range(n):
            for lo, hi in [(-k - 1 + mpf(1) / 1000, -k - mpf(1) / 2), (-k - mpf(1) / 2, -k - mpf(1) / 1000)]:
                if f(lo) * f(hi) < 0:
                    roots.append(float(mpmath.findroot(f, (lo, hi), solver="anderson")))
    return roots


def lgamma_points(fmt):
    rng = random.Random(f"lgamma {fmt.name}")
    edges = [LGAMMA_SMALL, LGAMMA_C, LGAMMA_B, LGAMMA_F, LGAMMA_E, 1.0, LGAMMA_SHIFT_FROM, 3.0, 4.0,
             7.0, LGAMMA_STIRLING_FROM]
    overflow = saturation(fmt, lgamma_exact, 1e30, fmt.max, math.inf)
    zeros = negative_zeros(lambda x: lgamma_exact(x), 4)
    poles = [-1.0, -2.0, -3.0, -10.0, -100.0, -2.0 ** (fmt.p - 1)]
    points = [x for c in edges + [overflow] + zeros + poles for x in neighbours(fmt, c)]
    sweep = log_sweep(fmt, fmt.tiny, fmt.max, 96)
    return ([math.nan] + specials(fmt) + sweep + [-x for x in log_sweep(fmt, 1e-3, 1e6, 48)]
            + uniform(fmt, rng, -20, 20, 96) + uniform(fmt, rng, 0, 10, 64) + points)


# digamma: its points are its root, the regions' ends, the poles and the
# negative roots.

def digamma_reference(fmt, x):
    if math.isnan(x) or x == -math.inf:
        return math.nan
    if x == math.inf:
        return math.inf
    if x == 0:
        return -math.inf if math.copysign(1, x) > 0 else math.inf
    if x < 0 and x == math.floor(x):
        return math.nan
    return correctly_rounded(fmt, mpmath.digamma, x)


def digamma_scale(fmt, value, x):
    """1 + |pi cot (pi x)|, the scale of the absolute bound below 0."""
    if math.isnan(x) or x >= 0 or math.isinf(x) or x == math.floor(x):
        return "1"
    with mp.workprec(fmt.p + 40):
        return scale(1 + abs(mpmath.pi * mpmath.cot(mpmath.pi * mpf(x))))


def digamma_points(fmt):
    rng = random.Random(f"digamma {fmt.name}")
    edges = [float(digamma_root()), 1.0, 2.0, 3.0, DIGAMMA_FROM[fmt]]
    zeros = negative_zeros(mpmath.digamma, 4)
    poles = [-1.0, -2.0, -3.0, -10.0, -100.0]
    points = [x for c in edges + zeros + poles for x in neighbours(fmt, c)]
    sweep = log_sweep(fmt, fmt.tiny, fmt.max, 96)
    return ([math.nan] + specials(fmt) + sweep + [-x for x in log_sweep(fmt, 1e-3, 1e6, 48)]
            + uniform(fmt, rng, -20, 20, 96) + uniform(fmt, rng, 0, 10, 64) + points)


# lbeta: its points are a grid of both arguments, both orders, the boundary
# where the larger reaches 8, and the edges.

def lbeta_exact(a, b):
    extra = int(max(0, math.log2(max(abs(float(a)), abs(float(b)), 1.0)))) + 20
    with mp.workprec(mp.prec + extra):
        return lgamma_exact(a) + lgamma_exact(b) - lgamma_exact(a + b)


def lbeta_reference(fmt, a, b):
    if math.isnan(a) or math.isnan(b) or a < 0 or b < 0:
        return math.nan
    if a == 0 or b == 0:
        return math.nan if math.inf in (a, b) else math.inf
    if math.inf in (a, b):
        return -math.inf
    return correctly_rounded(fmt, lbeta_exact, a, b)


def lbeta_points(fmt):
    rng = random.Random(f"lbeta {fmt.name}")
    axis = [round_to(fmt, mpf(10) ** (e / 2)) for e in range(-60, 61, 5)]
    grid_points = [(a, b) for a in axis for b in axis if max(a, b) <= 2.0 ** 10 or a == b or min(a, b) < 10]
    near_eight = [(a, b) for b in neighbours(fmt, LGAMMA_STIRLING_FROM) for a in (0.5, 1.0, 3.0, 7.5, 8.0)]
    near_eight += [(b, a) for a, b in near_eight]
    named = [(1.0, 1.0), (1.0, 7.0), (0.3, 7.9), (2.0, 0.5), (1e-10, 1e-10), (1e10, 1.0), (5e5, 0.5)]
    named = [(round_to(fmt, mpf(a)), round_to(fmt, mpf(b))) for a, b in named]
    edges = [(0.0, 1.0), (1.0, 0.0), (math.inf, 1.0), (1.0, math.inf), (math.inf, math.inf),
             (0.0, math.inf), (-1.0, 1.0), (1.0, -1.0), (math.nan, 1.0), (1.0, math.nan),
             (fmt.tiny, 1.0), (fmt.tiny, fmt.tiny), (fmt.max, 1.0), (fmt.max, fmt.max)]
    with mp.workprec(POINT_PREC):
        randoms = [(round_to(fmt, mpmath.exp(mpf(rng.uniform(-10, 10)))),
                    round_to(fmt, mpmath.exp(mpf(rng.uniform(-10, 10))))) for _ in range(96)]
    return grid_points + near_eight + named + edges + randoms


# i0e and i1e: their points are where nx's near series hands over to the far
# one, a point far out on the far one, sweeps to the largest float, both
# signs.

BESSEL_FAR = 1e4


def bessel_reference(exact, sign):
    def g(fmt, x):
        if math.isnan(x):
            return math.nan
        if math.isinf(x):
            return math.copysign(0.0, x) if sign else 0.0
        r = correctly_rounded(fmt, exact, x)
        return math.copysign(r, x) if sign and r == 0 else r
    return g


def bessel_points(fmt):
    rng = random.Random(f"bessel {fmt.name}")
    points = neighbours(fmt, BESSEL_SPLIT) + neighbours(fmt, BESSEL_FAR)
    return standard(fmt, rng, fmt.tiny, fmt.max, n_sweep=96) + uniform(fmt, rng, -20, 20, 96) + points + [-x for x in points]


# The incomplete gamma family: its points are the regions' boundaries with
# their neighbours, P along x = a for a log-spaced to 2^20, the small-a
# corner, sweeps of x/a at log-spaced a, the edges and NaN, subnormals and
# seeded random points. Points above a = 2^10 are thinned to the regions'
# boundaries and the sweeps' ratios.


def igamma_edge(a, x):
    """P and Q at an edge of the domain, None inside it. At a = 0 they are
    their limits, P = 1 for x > 0, which disagree with P(a, 0) = 0 at x = 0."""
    if math.isnan(a) or math.isnan(x) or a < 0 or x < 0:
        return math.nan, math.nan
    if a == math.inf:
        return (math.nan, math.nan) if x == math.inf else (0.0, 1.0)
    if x == math.inf:
        return 1.0, 0.0
    if x == 0:
        return (math.nan, math.nan) if a == 0 else (0.0, 1.0)
    if a == 0:
        return 1.0, 0.0
    return None


def igamma_reference(tail, log):
    """The reference of P (tail 0) or Q (tail 1), or of its logarithm."""
    def f(fmt, a, x):
        edge = igamma_edge(a, x)
        if edge is not None:
            v = edge[tail]
            if not log or math.isnan(v):
                return v
            if v == 0:
                return -math.inf
            # A tail that tends to 1 from below has a logarithm of -0: P as a
            # goes to 0, Q as a goes to +inf, each for finite x > 0.
            towards_one = (a == 0 and tail == 0) or (a == math.inf and tail == 1 and x > 0)
            return -0.0 if towards_one and x < math.inf else math.log(v)
        if log:
            return correctly_rounded(fmt, lambda a, x: oracle.igamma(a, x)[tail], a, x)
        return correctly_rounded(fmt, lambda a, x: mpmath.exp(oracle.igamma(a, x)[tail]), a, x)
    return f


def igamma_points(fmt):
    rng = random.Random(f"igamma {fmt.name}")
    r = lambda v: round_to(fmt, mpf(v))
    points = []
    # The corner's edge at x = 1.1 and a = 1, and the series' x = max(a, 1.1).
    for x in neighbours(fmt, IGAMMA_CORNER):
        points += [(r(a), x) for a in (1e-10, 1e-3, 0.3, 0.999, 1.0, 1.05)]
    for a in neighbours(fmt, 1.0):
        points += [(a, r(x)) for x in (1e-3, 0.5, 1.05, 2.0, 30.0)]
    # The series and the continued fraction meet at x = a.
    for a in (1.5, 3.0, 7.9, 19.0, 19.99):
        points += [(r(a), x) for x in neighbours(fmt, a)]
    # Stirling's shift changes count at the integers below 8.
    for a in range(2, 10):
        points += [(b, r(a + 0.25)) for b in neighbours(fmt, a, 2)]
    # bd0's series ends at |v| = 1/2, x = 3a and a/3.
    for a in (1.5, 10.0, 1000.0):
        points += [(r(a), x) for c in (3 * a, a / 3) for x in neighbours(fmt, c, 4)]
    # Temme's window: a = 20 and x/a = 0.6 and 1.4.
    for a in neighbours(fmt, IGAMMA_TEMME_FROM):
        points += [(a, r(x)) for x in (11.0, 12.0, 15.0, 20.0, 25.0, 28.0, 29.0)]
    for a in (20.0, 100.0, 1e4, IGAMMA_A_MAX):
        for c in ((1 - IGAMMA_TEMME_WIDTH) * a, (1 + IGAMMA_TEMME_WIDTH) * a):
            points += [(r(a), x) for x in neighbours(fmt, c, 4)]
    # P along x = a.
    points += [(a, a) for a in log_sweep(fmt, 1e-3, IGAMMA_A_MAX, 48)]
    # The small-a corner.
    points += [(r(1e-10), r(1e-10)), (r(1e-3), r(1e-2)), (fmt.tiny, fmt.tiny), (fmt.tiny, r(1.0)),
               (r(1e-30), r(0.5)), (r(0.5), fmt.tiny)]
    # Sweeps of x/a, and of x at small and large a.
    ratios = [1e-30, 1e-6, 1e-3, 0.1, 0.5, 0.8, 0.95, 0.99, 1.01, 1.05, 1.2, 1.5, 2.0, 3.0, 5.0, 10.0, 30.0, 100.0]
    for a in log_sweep(fmt, 1e-6, IGAMMA_A_MAX, 24):
        points += [(a, r(a * q)) for q in ratios if a * q <= fmt.max and (a <= 2.0 ** 10 or 0.5 <= q <= 2)]
    for a in (1e-6, 0.3, 2.5, 50.0):
        points += [(r(a), x) for x in log_sweep(fmt, fmt.tiny, fmt.max, 24)]
    # Edges and NaN.
    edges = [0.0, 1.0, math.inf, math.nan, -1.0, fmt.tiny]
    points += [(a, x) for a in (0.0, 0.5, 1.0, 30.0, math.inf, math.nan, -1.0, -math.inf) for x in edges + [-math.inf]]
    points += [(0.0, r(x)) for x in (1e-300, 1e-10, 0.5, 1.1, 3.0, 30.0, 1e300)] + [(-0.0, r(1.0))]
    points += [(fmt.max, r(1.0)), (fmt.max, fmt.max), (r(1.0), fmt.max)]
    # Random points, x near a and far from it; z is a standard normal by
    # Box-Muller, in mpmath as POINT_PREC says.
    with mp.workprec(POINT_PREC):
        lo, hi = mpmath.log(mpf("1e-4")), mpmath.log(mpf(2) ** 10)
        for _ in range(96):
            a = r(mpmath.exp(lo + (hi - lo) * mpf(rng.random())))
            u, v = mpf(rng.random()), mpf(rng.random())
            z = mpmath.sqrt(-2 * mpmath.log(1 - v)) * mpmath.cos(2 * mpmath.pi * u)
            points.append((a, r(mpf(a) * mpmath.exp(z))))
        for _ in range(48):
            points.append((r(mpmath.exp(mpf(rng.uniform(-10, 14)))), r(mpmath.exp(mpf(rng.uniform(-30, 10))))))
    return points


# gammaincinv and gammainccinv: the gamma's quantiles from either tail, at
# a grid of a against probabilities from the least subnormal to 1, the ends,
# the edges and seeded random points.

def igamma_quantile_edge(a, p, upper):
    """The quantile at an edge, None inside the domain. At a = 0, the
    limit: 0 but at the probability that P = 1 gives, where it is inf."""
    if math.isnan(a) or math.isnan(p) or a < 0 or p < 0 or p > 1:
        return math.nan
    low, high = (1.0, 0.0) if upper else (0.0, 1.0)
    if p == low:
        return 0.0
    if p == high or a == math.inf:
        return math.inf
    if a == 0:
        return 0.0
    return None


def igamma_quantile_reference(upper):
    def f(fmt, a, p):
        edge = igamma_quantile_edge(a, p, upper)
        if edge is not None:
            return edge
        return correctly_rounded(fmt, lambda a, p: oracle.igamma_quantile(a, p, upper), a, p)
    return f


def igamma_kappa(upper):
    """|m / (x F'(x))| at the exact quantile x, F the tail and m the smaller
    tail, min(p, 1 - p)."""
    def extra(fmt, value, a, p):
        if math.isnan(value) or math.isinf(value):
            return "1"
        if igamma_quantile_edge(a, p, upper) is not None:
            return "0"
        with mp.workprec(fmt.p + 40):
            x = oracle.igamma_quantile(a, p, upper)
            m = min(mpf(p), 1 - mpf(p))
            return scale(mpmath.exp(mpmath.log(m) - (mpf(a) * mpmath.log(x) - x - mpmath.loggamma(mpf(a)))))
    extra.__name__ = "kappa"
    return extra


