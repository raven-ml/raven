"""Generate nx's special-function tables and accuracy goldens.

    uv run packages/nx/test/gen/special.py [--check]

Writes `packages/nx/lib/special_tables.ml`, the coefficients, region
boundaries and counts of nx's special functions per compute dtype, and
`packages/nx/test/golden/special/<fn>.golden`, the points each function is
held to. With --check nothing is written, and the run fails if a file would
change: the tables and the proofs they carry disagree.

A golden is a table of hexadecimal floats, one row per point and dtype:
the arguments, exactly representable in the dtype, and the value correctly
rounded to it. An inverse's row also holds `kappa`, its condition number
|p / (x F'(x))| at the result; a row whose bound is absolute and scaled by
the function holds that scale.
"""

