"""Generate the exact values Nx.geomspace is held to.

    uv run packages/nx/test/gen/geomspace.py [--check]

Writes `packages/nx/test/golden/special/geomspace.golden`: rows of float64
ends `start` and `stop`, a count `n`, an index `i`, whether `stop` is an
endpoint, and the value `start (stop / start)^(i / div)` correctly rounded
to float64, `div` being `n - 1` with the endpoint and `n` without. The
ratio is exact here, so it may lie past float64's range, where nx takes its
logarithmic path. Every end is a normal float64, so every value is one too.
With --check nothing is written, and the run fails if the golden would
change.
"""

import argparse
import random
import sys
from fractions import Fraction
from pathlib import Path

from mpmath import mpf

from oracle import F64, correctly_rounded, hexf

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden" / "special" / "geomspace.golden"
HEADER = "# generated by packages/nx/test/gen/geomspace.py; do not edit\n"

TINY = 2.0**-1022
HUGE = (2.0 - 2.0**-52) * 2.0**1023

# Ends near each other, across float64's range in one ratio, and past it in
# either direction (the ratio overflows or falls below the least normal).
PAIRS = [
    (1.0, 1000.0),
    (3.0, 10.0),
    (1000.0, 1.0),
    (1.0, 1.0),
    (1e-300, 1e-290),
    (1e-150, 1e150),
    (2.0, 1e300),
    (1e-300, 1e300),
    (1e300, 1e-300),
    (TINY, HUGE),
    (HUGE, TINY),
    (1e-200, 1e200),
]


def drawn(rng, k):
    """`k` pairs of ends with random significands and binary exponents."""
    out = []
    for _ in range(k):
        a = rng.uniform(1, 2) * 2.0 ** rng.randint(-1020, 1020)
        b = rng.uniform(1, 2) * 2.0 ** rng.randint(-1020, 1020)
        out.append((a, b))
    return out


def value(start, stop, n, i, endpoint):
    div = n - 1 if endpoint else n
    e = Fraction(i, div)

    def f(a, b):
        return a * (b / a) ** (mpf(e.numerator) / e.denominator)

    return correctly_rounded(F64, f, start, stop)


def rows():
    rng = random.Random(20261125)
    out = []
    for start, stop in PAIRS + drawn(rng, 24):
        for n, endpoint in [(2, True), (3, True), (5, True), (9, True), (4, False), (7, False)]:
            for i in range(n):
                v = value(start, stop, n, i, endpoint)
                cells = [hexf(start), hexf(stop), hexf(float(n)), hexf(float(i)),
                         hexf(1.0 if endpoint else 0.0), hexf(v)]
                out.append("f64\t" + "\t".join(cells))
    return out


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--check", action="store_true")
    args = p.parse_args()
    text = HEADER + "dtype\tstart\tstop\tn\ti\tendpoint\tf\n" + "\n".join(rows()) + "\n"
    if args.check:
        if GOLDEN.read_text() != text:
            sys.exit(f"{GOLDEN} would change")
        return
    GOLDEN.write_text(text)


if __name__ == "__main__":
    main()
