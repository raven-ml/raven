"""Write the golden of the decimal digits Dtype.Float_text gives floats.

    uv run packages/nx/test/array/gen/float_digits.py [--check]

Each answer is a decimal as its digits, without leading or trailing zeros,
and the exponent of its last digit: 1.5 is "15 -1" and zero "0 0". Two
oracles state each one and must agree, or the run fails:

- shortest: the fewest digits that read back as the float in its format,
  reading to nearest, ties to even, with the exponent unbounded above; of
  those the nearest, and of two as near the one whose last digit is even.
  An exact search in rationals states it, listing the decimals of each
  length inside the interval of reals that read as the float. Python's
  repr agrees on binary64 and numpy's Dragon4 on binary32.
- significant n: |x| rounded to n significant digits, ties to even, by
  decimal.Decimal on the exact value, and by Python's %e.
- decimals n: |x| rounded to a multiple of 10^-n, ties to even, by
  decimal.Decimal, and by Python's %f where n >= 0.

The golden holds, under a line naming each section, one line per float as
its bits in hexadecimal, then n for significant and decimals, then the
digits and the exponent:

- shortest binary64 and binary32: random bit patterns, every power of two
  and the neighbours of some, the subnormal and normal extremes, decimals
  of 1 to 17 digits and their neighbours, and n 2^-r, where two shortest
  candidates are often equally near;
- significant and decimals of binary64 values and of binary32 values held
  in a binary64, the bits being binary64's: random n, exact ties, carries
  into a new leading digit, and long expansions.

The narrow formats, whose every value test_float_text checks with an
exact reader, have no section. Without --check the golden is written; with
it, the run fails if the golden would change.
"""

import decimal
import math
import random
import struct
import sys
from fractions import Fraction
from pathlib import Path

import numpy as np

GOLDEN = Path(__file__).resolve().parent.parent / "golden" / "float_digits.txt"
HEADER = "# generated by packages/nx/test/array/gen/float_digits.py; do not edit\n"
SEED = 21


# Formats


class Format:
    """A binary format: [exp] exponent bits and [mant] stored fraction
    bits."""

    def __init__(self, name, exp, mant):
        self.name = name
        self.precision = mant + 1
        self.emin = 2 - (1 << (exp - 1))


F32 = Format("binary32", 8, 23)
F64 = Format("binary64", 11, 52)


def f64_bits(x):
    return struct.unpack("<Q", struct.pack("<d", x))[0]


def f64_of_bits(b):
    return struct.unpack("<d", struct.pack("<Q", b))[0]


def f32_bits(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]


def f32_of_bits(b):
    return struct.unpack("<f", struct.pack("<I", b))[0]


# Normal form


def normal(digits, exp):
    """[digits 10^exp] without leading or trailing zeros, zero as ("0", 0)."""
    digits = digits.lstrip("0")
    if digits == "":
        return ("0", 0)
    stripped = digits.rstrip("0")
    return (stripped, exp + len(digits) - len(stripped))


def of_fraction(m, unit_exp):
    return normal(str(m), unit_exp)


# Shortest: exact search


def interval(fmt, x):
    """The reals that read as the positive [x] of [fmt]: the ends and whether
    they belong. x = c 2^q with q at least the subnormals' exponent; the ends
    are the midpoints to the neighbours, the one below a quarter step away at
    the bottom of a binade above the subnormals."""
    qmin = fmt.emin - fmt.precision + 1
    q = max(x.numerator.bit_length() - x.denominator.bit_length() - fmt.precision, qmin)
    # The bit lengths put q within one of its value: settle it.
    while x / Fraction(2) ** q >= 2**fmt.precision:
        q += 1
    while q > qmin and x / Fraction(2) ** q < 2 ** (fmt.precision - 1):
        q -= 1
    c = x / Fraction(2) ** q
    assert c.denominator == 1
    c = c.numerator
    step = Fraction(2) ** q
    below = Fraction(1, 4) if c == 1 << (fmt.precision - 1) and q > qmin else Fraction(1, 2)
    return (c - below) * step, (c + Fraction(1, 2)) * step, c % 2 == 0


def decade(x):
    """About the exponent of the leading digit of the positive [x], within
    one; computed on integers, since a float of [x] may underflow."""
    return len(str(x.numerator)) - len(str(x.denominator))


def search(fmt, x):
    """The shortest decimal that reads as [x] in [fmt], by listing the decimals
    of each length in each decade the interval meets."""
    if x == 0:
        return ("0", 0)
    lo, hi, closed = interval(fmt, x)

    def inside(v):
        return lo <= v <= hi if closed else lo < v < hi

    k_lo = decade(lo if lo > 0 else x) - 1
    k_hi = decade(hi) + 1
    for p in range(1, 60):
        found = []
        for k in range(k_lo, k_hi + 1):
            unit = Fraction(10) ** (k - p + 1)
            first = max(math.ceil(lo / unit), 10 ** (p - 1))
            last = min(math.floor(hi / unit), 10**p - 1)
            for m in range(first, last + 1):
                if inside(m * unit):
                    found.append((abs(m * unit - x), m % 2, m, k - p + 1))
        if found:
            _, _, m, e = min(found)
            return of_fraction(m, e)
    raise SystemExit(f"{fmt.name} {x}: no decimal found")


# Shortest: library oracles


def repr_digits(x):
    """Python's repr of a positive double, as digits and exponent."""
    d = decimal.Decimal(repr(x))
    sign, digits, exp = d.as_tuple()
    return normal("".join(map(str, digits)), exp)


def numpy_digits(x, dtype):
    s = np.format_float_scientific(dtype(x), unique=True, trim="-")
    mantissa, exponent = s.split("e")
    whole, _, frac = mantissa.partition(".")
    return normal(whole + frac, int(exponent) - len(frac))


def shortest(fmt, x, check=None):
    d = search(fmt, Fraction(x))
    if check is not None and x != 0 and check(x) != d:
        raise SystemExit(f"{fmt.name} {x!r}: oracles differ, {d} {check(x)}")
    return d


# Rounding


CONTEXT = decimal.Context(
    prec=5000, rounding=decimal.ROUND_HALF_EVEN, Emin=-999999, Emax=999999
)


def of_decimal(d):
    _, digits, exp = d.as_tuple()
    return normal("".join(map(str, digits)), exp)


def significant(n, x):
    x = abs(x)
    ctx = CONTEXT.copy()
    ctx.prec = n
    d = of_decimal(ctx.plus(decimal.Decimal(x)))
    if x != 0:
        mantissa, exponent = ("%.*e" % (n - 1, x)).split("e")
        whole, _, frac = mantissa.partition(".")
        if normal(whole + frac, int(exponent) - len(frac)) != d:
            raise SystemExit(f"significant {n} {x!r}: oracles differ")
    return d


def decimals(n, x):
    x = abs(x)
    d = of_decimal(
        decimal.Decimal(x).quantize(decimal.Decimal(1).scaleb(-n), context=CONTEXT)
    )
    if n >= 0:
        whole, _, frac = ("%.*f" % (n, x)).partition(".")
        if normal(whole + frac, -len(frac)) != d:
            raise SystemExit(f"decimals {n} {x!r}: oracles differ")
    return d


# Inputs


def ulps(x, k):
    return f64_of_bits(f64_bits(x) + k)


def ulps32(x, k):
    return f32_of_bits(f32_bits(x) + k)


def doubles(rng):
    """Positive finite doubles from the classes the golden covers."""
    xs = []
    xs += [f64_of_bits(rng.randrange(1, 0x7FF0000000000000)) for _ in range(2000)]
    xs += [math.ldexp(1.0, e) for e in range(-1074, 1024)]
    for e in rng.sample(range(-1022, 1024), 300):
        xs += [ulps(math.ldexp(1.0, e), k) for k in (-2, -1, 1, 2)]
    xs += [ulps(5e-324, k) for k in range(3)]
    xs += [ulps(2.2250738585072014e-308, k) for k in (-2, -1, 1, 2)]
    xs += [ulps(sys.float_info.max, -k) for k in range(4)]
    for _ in range(1000):
        p = rng.randint(1, 17)
        xs.append(float(f"{rng.randrange(1, 10**p)}e{rng.randint(-30, 30)}"))
    for _ in range(1500):
        d, j, k = rng.randrange(1, 100), rng.randint(-325, 308), rng.randint(-2, 2)
        x = float(f"{d}e{j}")
        if 0 < x < math.inf and 0 < ulps(x, k) < math.inf:
            xs.append(ulps(x, k))
    for _ in range(1000):
        n = rng.randrange(1 << 52, 1 << 53)
        xs.append(math.ldexp(n, -rng.randint(0, 63)))
    xs += [1e23, 2.0**50 + 0.25, 0.1, 0.3]
    return xs


def singles(rng):
    """Positive finite float32s, held in doubles."""
    xs = []
    xs += [f32_of_bits(rng.randrange(1, 0x7F800000)) for _ in range(1000)]
    for e in range(-149, 128):
        xs += [ulps32(math.ldexp(1.0, e), k) for k in (-1, 0, 1) if e > -149 or k >= 0]
    xs += [f32_of_bits(k) for k in (1, 2, 3, 0x7FFFFF, 0x800000, 0x800001)]
    xs += [f32_of_bits(0x7F7FFFFF - k) for k in range(3)]
    for _ in range(500):
        p = rng.randint(1, 9)
        x = float(f"{rng.randrange(1, 10**p)}e{rng.randint(-45, 38)}")
        if x < float(np.finfo(np.float32).max) and np.float32(x) > 0:
            xs.append(float(np.float32(x)))
    for _ in range(500):
        n = rng.randrange(1 << 23, 1 << 24)
        xs.append(math.ldexp(n, -rng.randint(0, 40)))
    xs.append(float(np.float32(0.1)))
    return xs


def roundings(rng, xs32):
    """(n, x) for significant: random digit counts, exact ties a 2^-j at one
    digit fewer than their expansion, and carries next to powers of ten."""
    rows = []
    for _ in range(1500):
        x = f64_of_bits(rng.randrange(0, 0x7FF0000000000000))
        rows.append((rng.randint(1, 39), x))
    for x in rng.sample(xs32, 500):
        rows.append((rng.randint(1, 20), x))
    for _ in range(500):
        x = math.ldexp(rng.randrange(1, 1 << 20), -rng.randint(1, 30))
        rows.append((len(of_decimal(decimal.Decimal(x))[0]) - 1 or 1, x))
    for _ in range(300):
        m, j = rng.randint(-8, 22), rng.randint(0, 79)
        x = float(10**m) + rng.choice((-1, 1)) * math.ldexp(1.0, -j)
        if x > 0:
            rows.append((rng.randint(1, 20), x))
    rows += [(1, 9.5), (2, 9.95), (3, 999.5), (1, 0.95), (17, 5e-324), (800, 5e-324)]
    rows += [(17, sys.float_info.max), (1000, 0.1), (39, 0.1)]
    return rows


def places(rng, xs32):
    """(n, x) for decimals: random places, ties, negative places, and long
    expansions."""
    rows = []
    for _ in range(1200):
        x = abs(rng.choice((f64_of_bits(rng.randrange(0, 0x7FF0000000000000)),
                            rng.uniform(0, 1e6), rng.uniform(0, 1))))
        rows.append((rng.randint(0, 29), x))
    for x in rng.sample(xs32, 300):
        rows.append((rng.randint(0, 29), x))
    for _ in range(300):
        j = rng.randint(1, 30)
        x = math.ldexp(2 * rng.randrange(0, 1 << 20) + 1, -j)
        rows.append((j - 1, x))
    for _ in range(150):
        rows.append((rng.randint(-20, -1), rng.uniform(0, 1e25)))
    for _ in range(30):
        x = f64_of_bits(rng.randrange(0, 0x7FF0000000000000))
        rows.append((rng.randint(30, 1100), x))
    rows += [(0, 0.5), (0, 1.5), (0, 2.5), (2, 0.125), (-2, 1250.0), (1075, 5e-324)]
    rows += [(0, 0.49999999999999994), (-308, sys.float_info.max), (-309, 1e308)]
    return rows


# Golden


def line(bits, width, *fields):
    return f"{bits:0{width}x} " + " ".join(map(str, fields)) + "\n"


def rows():
    rng = random.Random(SEED)
    out = [HEADER]
    xs64 = doubles(rng)
    out.append("shortest binary64\n")
    for x in xs64:
        out.append(line(f64_bits(x), 16, *shortest(F64, x, repr_digits)))
    xs32 = singles(rng)
    out.append("shortest binary32\n")
    for x in xs32:
        d = shortest(F32, x, lambda x: numpy_digits(x, np.float32))
        out.append(line(f32_bits(x), 8, *d))
    out.append("significant\n")
    for n, x in roundings(rng, xs32):
        out.append(line(f64_bits(x), 16, n, *significant(n, x)))
    out.append("decimals\n")
    for n, x in places(rng, xs32):
        out.append(line(f64_bits(x), 16, n, *decimals(n, x)))
    return "".join(out)


def main():
    text = rows()
    if "--check" in sys.argv[1:]:
        if not GOLDEN.exists() or GOLDEN.read_text() != text:
            raise SystemExit(f"{GOLDEN} differs from the oracles")
        return
    GOLDEN.write_text(text)


if __name__ == "__main__":
    main()
