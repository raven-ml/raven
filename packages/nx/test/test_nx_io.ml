(* Whether a file can be replaced or deleted while a tensor loaded from it is
   reachable depends on the platform once loading maps the file. POSIX allows
   both. On Windows the outcome is written to the build log and the test is
   skipped. *)
let test_safetensors_replace_loaded_file () =
  with_temp_dir @@ fun dir ->
  let path = Filename.concat dir "weights.safetensors" in
  let n = 65536 in
  let first = Array.init n float_of_int in
  let second = Array.init n (fun i -> float_of_int (-i)) in
  Nx_io.save_safetensors path
    [ ("w", Nx.P (Nx.create Nx.float32 [| n |] first)) ];
  let load () =
    Hashtbl.find (Nx_io.load_safetensors path) "w" |> Nx.unpack Nx.float32
  in
  let loaded = load () in
  let outcome f =
    match f () with
    | () -> "allowed"
    | exception (Failure message | Sys_error message) -> "refused: " ^ message
  in
  let saved =
    outcome (fun () ->
        Nx_io.save_safetensors path
          [ ("w", Nx.P (Nx.create Nx.float32 [| n |] second)) ])
  in
  let reloaded = if saved = "allowed" then Nx.to_array (load ()) else second in
  let removed = outcome (fun () -> Sys.remove path) in
  equal ~msg:"loaded values after the save and the delete" (array float_exact)
    first (Nx.to_array loaded);
  equal ~msg:"the save replaced the file" (array float_exact) second reloaded;
  if saved <> "allowed" || removed <> "allowed" then
    let report =
      Printf.sprintf "save over a loaded file %s; delete of a loaded file %s"
        saved removed
    in
    if Sys.win32 then begin
      let line = "test_nx_io: on Windows, " ^ report ^ "\n" in
      ignore
        (Unix.write_substring uncaptured_stderr line 0 (String.length line));
      skip ~reason:report ()
    end
    else fail report

(* [raw_safetensors ?pad entries] is a SafeTensors file holding [entries], each
   a name, a dtype tag, a shape and the entry's bytes, in order. The data
   section starts on a multiple of 8, [pad] bytes later. *)
let raw_safetensors ?(pad = 0) entries =
  let offset = ref 0 in
  let fields =
    List.map
      (fun (name, dtype, shape, data) ->
        let start = !offset in
        offset := start + String.length data;
        Printf.sprintf
          {|"%s":{"dtype":"%s","shape":[%s],"data_offsets":[%d,%d]}|} name dtype
          (String.concat "," (List.map string_of_int shape))
          start !offset)
      entries
  in
  let json = "{" ^ String.concat "," fields ^ "}" in
  let aligned = (String.length json + 7) / 8 * 8 in
  let header = json ^ String.make (aligned - String.length json + pad) ' ' in
  let prefix = Bytes.create 8 in
  Bytes.set_int64_le prefix 0 (Int64.of_int (String.length header));
  String.concat ""
    (Bytes.to_string prefix :: header
    :: List.map (fun (_, _, _, data) -> data) entries)

let with_safetensors contents f =
  with_temp_dir @@ fun dir ->
  let path = Filename.concat dir "raw.safetensors" in
  write_file_bytes path contents;
  f path

let stored_bytes (Nx.P t) =
  let buffer = Nx.to_buffer (Nx.reshape [| Nx.numel t |] (Nx.contiguous t)) in
  let size = Nx_buffer.kind_size_in_bytes (Nx_buffer.kind buffer) in
  let bytes = Bytes.create (Nx_buffer.length buffer * size) in
  Nx_buffer.blit_to_bytes buffer bytes;
  Bytes.to_string bytes

let dtype_name (Nx.P t) = Nx_core.Dtype.to_string (Nx.dtype t)
let packed_shape (Nx.P t) = Nx.shape t

let pattern n seed =
  String.init n (fun i -> Char.chr (((i * 37) + seed) land 255))

(* Entries in descending element size, so that with [pad = 0] each sits on a
   multiple of its element size and with [pad = 1] none of the wide ones
   does. *)
let typed_entries =
  [
    ("u64", "U64", [ 2 ], pattern 16 1);
    ("u32", "U32", [ 2; 2 ], pattern 16 2);
    ("bf16", "BF16", [ 3 ], pattern 6 3);
    ("f16", "F16", [ 1 ], pattern 2 4);
    ("f8_e4m3", "F8_E4M3", [ 3 ], pattern 3 5);
    ("f8_e5m2", "F8_E5M2", [ 3 ], pattern 3 6);
    ("bool", "BOOL", [ 4 ], "\000\001\002\255");
    ("empty", "F32", [ 0; 3 ], "");
  ]

let check_typed_entries archive =
  List.iter
    (fun (name, _, shape, data) ->
      let packed = Hashtbl.find archive name in
      equal ~msg:(name ^ " shape") (array int) (Array.of_list shape)
        (packed_shape packed);
      equal ~msg:(name ^ " bytes") string data (stored_bytes packed))
    typed_entries;
  equal ~msg:"entries" int (List.length typed_entries) (Hashtbl.length archive)

let test_safetensors_views_bit_exact () =
  with_safetensors (raw_safetensors typed_entries) @@ fun path ->
  let archive = Nx_io.load_safetensors path in
  check_typed_entries archive;
  equal ~msg:"bfloat16 dtype" string "bfloat16"
    (dtype_name (Hashtbl.find archive "bf16"));
  equal ~msg:"uint64 dtype" string "uint64"
    (dtype_name (Hashtbl.find archive "u64"));
  (* Entries of an aligned file are views of one mapping: they lie as far apart
     in memory as in the file. *)
  let address name =
    let (Nx.P t) = Hashtbl.find archive name in
    Nx_buffer.unsafe_data_ptr (Nx.to_buffer t)
  in
  equal ~msg:"u32 follows u64 in memory" nativeint 16n
    (Nativeint.sub (address "u32") (address "u64"))

let test_safetensors_misaligned_twin () =
  with_safetensors (raw_safetensors ~pad:1 typed_entries) @@ fun path ->
  check_typed_entries (Nx_io.load_safetensors path)

(* An entry that is a view knows where in the file its bytes are; one the load
   copied does not. *)
let test_safetensors_file_range () =
  let range archive name =
    let (Nx.P t) = Hashtbl.find archive name in
    Option.map
      (fun ((file : Nx_buffer.file), offset) -> (file.path, file.size, offset))
      (Nx_buffer.file_range (Nx.to_buffer t))
  in
  let contents = raw_safetensors typed_entries in
  let data_len =
    List.fold_left
      (fun n (_, _, _, data) -> n + String.length data)
      0 typed_entries
  in
  let data_start = String.length contents - data_len in
  with_safetensors contents (fun path ->
      let archive = Nx_io.load_safetensors path in
      let expected offset = Some (path, String.length contents, offset) in
      let ranges = option (triple string int int) in
      equal ~msg:"first entry" ranges (expected data_start)
        (range archive "u64");
      equal ~msg:"an entry further on" ranges
        (expected (data_start + 32))
        (range archive "bf16"));
  with_safetensors (raw_safetensors ~pad:1 typed_entries) (fun path ->
      let archive = Nx_io.load_safetensors path in
      equal ~msg:"a copied entry"
        (option (triple string int int))
        None (range archive "u64"))

let test_safetensors_foreign_dtypes () =
  let entries =
    [
      ("scales", "F8_E8M0", [ 2; 3 ], pattern 6 7);
      ("nibbles", "F4", [ 2; 4 ], pattern 4 8);
      ("sixes", "F6_E2M3", [ 4 ], pattern 3 9);
    ]
  in
  with_safetensors (raw_safetensors entries) @@ fun path ->
  let archive = Nx_io.load_safetensors path in
  List.iter
    (fun (name, shape) ->
      let packed = Hashtbl.find archive name in
      equal ~msg:(name ^ " dtype") string "uint8" (dtype_name packed);
      equal ~msg:(name ^ " shape") (array int) shape (packed_shape packed))
    [ ("scales", [| 2; 3 |]); ("nibbles", [| 4 |]); ("sixes", [| 3 |]) ];
  List.iter
    (fun (name, _, _, data) ->
      equal ~msg:(name ^ " bytes") string data
        (stored_bytes (Hashtbl.find archive name)))
    entries

let expect_load_failure ~msg path =
  match Nx_io.load_safetensors path with
  | _ -> fail ("expected a failure: " ^ msg)
  | exception Failure message -> ignore (find_substring message path)

let test_safetensors_invalid_files () =
  let whole = raw_safetensors typed_entries in
  let with_prefix length =
    let bytes = Bytes.of_string whole in
    Bytes.set_int64_le bytes 0 length;
    Bytes.to_string bytes
  in
  List.iter
    (fun (msg, contents) ->
      with_safetensors contents (expect_load_failure ~msg))
    [
      ("truncated data", String.sub whole 0 (String.length whole - 5));
      ("trailing bytes", whole ^ "\000");
      ("no header", String.sub whole 0 5);
      ("empty", "");
      ("header past the file", with_prefix (Int64.of_int (String.length whole)));
      ("header past the cap", with_prefix 100_000_001L);
      ("header length with the high bit set", with_prefix Int64.min_int);
      ( "repeated name",
        raw_safetensors [ ("w", "U8", [ 1 ], "a"); ("w", "U8", [ 1 ], "b") ] );
    ]

let test_safetensors_not_a_regular_file () =
  with_temp_dir @@ fun dir ->
  expect_load_failure ~msg:"directory" dir;
  expect_load_failure ~msg:"missing file" (Filename.concat dir "missing");
  if not Sys.win32 then begin
    let fifo = Filename.concat dir "fifo" in
    Unix.mkfifo fifo 0o600;
    expect_load_failure ~msg:"fifo" fifo
  end

(* Not inlined, so that once it returns nothing but its result keeps the file
   mapped. *)
let[@inline never] load_one path name =
  Hashtbl.find (Nx_io.load_safetensors path) name

let test_safetensors_view_outlives_archive () =
  let n = 1 lsl 18 in
  let data = pattern (2 * n) 11 in
  with_safetensors (raw_safetensors [ ("w", "BF16", [ n ], data) ])
  @@ fun path ->
  let packed = load_one path "w" in
  Gc.full_major ();
  equal ~msg:"bytes after the archive is collected" bool true
    (String.equal data (stored_bytes packed))

let test_safetensors_bfloat16_bit_exact () =
  (* Fixture generated by Python: BF16 bits [0x0000, 0x0001, 0x3F80, 0x7F80,
     0x7FC1] = [+0, smallest subnormal, 1.0, +inf, NaN] *)
  let fixture = Filename.concat fixture_dir "bf16_bit_exact.safetensors" in
  let archive = Nx_io.load_safetensors fixture in
  let packed = Hashtbl.find archive "bf16_tensor" in
  let values = packed |> Nx.unpack Nx.bfloat16 |> Nx.to_array in
  equal ~msg:"bf16 subnormal preserved" bool true (values.(1) <> 0.0);
  equal ~msg:"bf16 nan preserved" bool true (Float.is_nan values.(4));
  (* Round-trip: save and check raw payload is identical *)
  let path_out = temp_file "test_bf16_rt_" ".safetensors" in
  Fun.protect
    ~finally:(fun () -> Sys.remove path_out)
    (fun () ->
      Nx_io.save_safetensors path_out [ ("bf16_tensor", packed) ];
      let payload_in = safetensors_payload fixture in
      let payload_out = safetensors_payload path_out in
      equal ~msg:"bfloat16 payload round-trip" string payload_in payload_out)

