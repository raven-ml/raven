let with_temp_dir f =
  let dir = Filename.temp_dir "test_nx_io_" "" in
  let remove () =
    Gc.full_major ();
    Array.iter
      (fun name ->
        try Sys.remove (Filename.concat dir name) with Sys_error _ -> ())
      (Sys.readdir dir);
    try Sys.rmdir dir with Sys_error _ -> ()
  in
  Fun.protect ~finally:remove (fun () -> f dir)

