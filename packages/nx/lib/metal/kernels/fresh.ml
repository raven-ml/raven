(* fresh METALLIB SOURCE... checks the source stamp gen.py compiled into the
   metallib, then prints an OCaml module whose value [metallib] is its bytes.
   Hash the files in gen.py's order, as lines of hex MD5 digests. *)

let digest files =
  let line f = Digest.to_hex (Digest.file f) ^ "\n" in
  Digest.to_hex (Digest.string (String.concat "" (List.map line files)))

let rec at s sub i j =
  j = String.length sub || (s.[i + j] = sub.[j] && at s sub i (j + 1))

let rec contains s sub i =
  i + String.length sub <= String.length s
  && (at s sub i 0 || contains s sub (i + 1))

(* [bytes] as an OCaml string literal, 32 bytes a line. *)
let literal bytes =
  let b = Buffer.create (4 * String.length bytes) in
  Buffer.add_char b '"';
  String.iteri
    (fun i c ->
      if i > 0 && i mod 32 = 0 then Buffer.add_string b "\\\n  ";
      Buffer.add_string b (Printf.sprintf "\\x%02x" (Char.code c)))
    bytes;
  Buffer.add_char b '"';
  Buffer.contents b

let () =
  match Array.to_list Sys.argv with
  | _ :: lib :: (_ :: _ as sources) ->
      let bytes = In_channel.with_open_bin lib In_channel.input_all in
      let name = "nx_metal_sources_" ^ digest sources ^ "\000" in
      if not (contains bytes name 0) then begin
        Printf.eprintf
          "%s was built from other sources: rebuild it with uv run \
           packages/nx/lib/metal/kernels/gen.py\n"
          lib;
        exit 1
      end;
      Printf.printf "(* Generated by kernels/fresh.exe from %s. *)\n\n" lib;
      Printf.printf "let metallib =\n  %s\n" (literal bytes)
  | _ ->
      prerr_endline "usage: fresh METALLIB SOURCE...";
      exit 2
