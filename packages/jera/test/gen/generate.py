"""Generate jera's goldens from mpmath and scipy.

    uv run packages/jera/test/gen/generate.py [--check]

Each golden is an OCaml module in test/golden/ of float arrays, written with
17 significant digits so that it reads back as the float64 it was printed
from. Without --check the modules are written; with --check nothing is
written, each module that would change is printed as a diff, and the run fails
if any would.
"""

import argparse
import difflib
import sys
from pathlib import Path

import mpmath as mp
import numpy as np
from scipy import interpolate
from scipy.integrate import _quad_vec

HERE = Path(__file__).resolve().parent
GOLDEN = HERE.parent / "golden"
HEADER = """(*---------------------------------------------------------------------------
  Copyright (c) 2026 The Raven authors. All rights reserved.
  SPDX-License-Identifier: ISC
  ---------------------------------------------------------------------------*)

(* Generated by test/gen/generate.py; do not edit. *)
"""


def lit(x):
    x = float(x)
    if x != x:
        return "nan"
    if x == float("inf"):
        return "infinity"
    if x == float("-inf"):
        return "neg_infinity"
    s = repr(x)
    if "e" not in s and "." not in s:
        s += "."
    return f"({s})" if s.startswith("-") else s


def array(xs):
    return "[| " + "; ".join(lit(x) for x in np.ravel(xs)) + " |]"


class Module:
    def __init__(self, doc):
        self.doc = doc
        self.lines = []

    def floats(self, name, xs):
        self.lines.append(f"let {name} = {array(xs)}")

    def text(self):
        return HEADER + f"\n(* {self.doc} *)\n\n" + "\n\n".join(self.lines) + "\n"


# Quadrature


def gauss_legendre(n):
    """Golub–Welsch at 50 digits: the eigenvalues of the Jacobi matrix are the
    nodes, and twice the squared first components of its eigenvectors the
    weights."""
    mp.mp.dps = 50
    j = mp.zeros(n, n)
    for k in range(1, n):
        b = k / mp.sqrt(4 * k * k - 1)
        j[k - 1, k] = b
        j[k, k - 1] = b
    e, q = mp.eigsy(j)
    pairs = sorted((e[i], 2 * q[0, i] ** 2) for i in range(n))
    x = [p[0] for p in pairs]
    if n % 2 == 1:
        x[n // 2] = mp.mpf(0)  # the center, which the eigensolver leaves near 0
    return x, [p[1] for p in pairs]


GAUSS = [1, 2, 3, 4, 5, 8, 10, 16, 20, 32, 64, 100]


def quad():
    m = Module("Gauss–Legendre rules from mpmath, Gauss–Kronrod rules from scipy.")
    for n in GAUSS:
        x, w = gauss_legendre(n)
        m.floats(f"gauss{n}_x", x)
        m.floats(f"gauss{n}_w", w)
    for name, rule in [("kronrod7", _quad_vec._quadrature_gk15),
                       ("kronrod10", _quad_vec._quadrature_gk21)]:
        # scipy writes each rule's nodes and weights as tuple constants.
        consts = rule.__code__.co_consts
        tuples = [c for c in consts if isinstance(c, tuple) and len(c) > 3]
        x, _, v = tuples
        order = np.argsort(x)
        m.floats(f"{name}_x", np.array(x)[order])
        m.floats(f"{name}_w", np.array(v)[order])
    return m


MODULES = {"golden_quad": quad}


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    stale = False
    for name, make in MODULES.items():
        path = GOLDEN / f"{name}.ml"
        new = make().text()
        old = path.read_text() if path.exists() else ""
        if new == old:
            continue
        if args.check:
            stale = True
            sys.stdout.writelines(difflib.unified_diff(
                old.splitlines(True), new.splitlines(True),
                str(path), str(path) + " (generated)"))
        else:
            path.write_text(new)
            print(f"wrote {path.relative_to(HERE.parent.parent.parent.parent)}")
    sys.exit(1 if stale else 0)


if __name__ == "__main__":
    main()
