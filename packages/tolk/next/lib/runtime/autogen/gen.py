"""Generates the vendor constants tolk.next's queue encoders read, from
tinygrad's autogen modules.

    uv run packages/tolk/next/lib/runtime/autogen/gen.py [--check]

It imports tinygrad from `_tinygrad_next`, which must be at TINYGRAD, and
writes each vendor's module beside this script: `nv_gpu.ml` and `amd_gpu.ml`. With --check it
writes nothing and fails if a committed module differs.

A module holds only the constants its encoder reads, as the inventories below
name them, lowercased: a method or a value as an integer, a field of a method's
word as its bit range `(hi, lo)`. NV's launch descriptors (QMDs) are tables of
the fields the encoder writes, by name, for each descriptor version, as
tinygrad's `QMD` reads them: a field that takes an index is named once for each
of 0 to 7, with the index after an underscore. NV's constants are the same in
the driver releases 570, 580 and 610, which the script checks.
"""

