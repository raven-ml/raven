let tiny_forward () =
  let input name shape =
    let n = List.fold_left ( * ) 1 shape in
    let value i = match name with
      | "attention_norm" | "ffn_norm" | "norm" -> 1.
      | "frequencies" -> if i mod 2 = 0 then 1. else 0.
      | "x" -> float_of_int (i - 7) /. 8.
      | _ -> float_of_int (i mod 13 - 6) /. 16.
    in
    Run.of_float_array ~shape (Array.init n value)
  in
  let output, h, _ = Llama_fixture.build input in
  Run.realize_many [output; h];
  equal ~msg:"residual block output" (array (float 2e-5)) hidden (Run.to_float_array h);
  equal ~msg:"normalized vocabulary projection" (array (float 2e-5)) logits
    (Run.to_float_array output)

let () = exit (run "Llama fixture" [test "tiny forward matches tinygrad CPU" tiny_forward])
