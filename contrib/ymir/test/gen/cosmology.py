# Formats


class Format:
    def __init__(self, name, p, emin, np_type):
        self.name, self.p, self.emin, self.np = name, p, emin, np_type
        self.min_normal = 2.0**emin

    def round(self, x):
        """[x] rounded to nearest even in the format, as a Python float."""
        with mp.workprec(self.p):
            return float(+mpf(x))

    def hex(self, x):
        return float(x).hex()


F32 = Format("float32", 24, -126, np.float32)
