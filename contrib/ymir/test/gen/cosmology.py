BOUND = {"float32": 2.0**-20, "float64": 2.0**-46}
F_BOUND = {"float32": 2.0**-20, "float64": 2.0**-48}


# The neutrino function

K = 120 / (7 * mp.pi**4)


@functools.lru_cache(None)
def f_exact(y):
    """F(y) = (120 / 7 pi^4) int_0^inf x^2 sqrt(x^2 + y^2) / (e^x + 1) dx."""
    y = mpf(y)
    f = lambda x: x * x * mp.sqrt(x * x + y * y) / (mp.exp(x) + 1)
    points = sorted({mpf(0), mpf(1), mpf(4), mpf(16), mpf(48), y})
    return K * mp.quad(f, points + [mp.inf])


# Small y: F = 1 + y^2 (c2 + c4 y^2 + c5 y^3 + c_log y^2 log y) + O(y^6). The
# coefficients come from the Mellin transform of the integrand: c2 from
# int x/(e^x+1) = pi^2/12, c_log from the Fermi function's value 1/2 at 0, c5
# from its slope -1/4, and c4 from the double pole at y^4, here by Richardson
# extrapolation of the remainder.
C2 = K * mp.pi**2 / 24
C_LOG = K / 16
C5 = -K / 30
# The y^6 and y^7 terms, which the extrapolation of c4 removes.
C6 = K * mp.binomial(mpf(1) / 2, 3) * mp.diff(mp.altzeta, -2) / 2
C7 = -K / 630


def series_c4():
    with mp.workdps(60):

        def remainder(y):
            y = mpf(y)
            f = f_exact.__wrapped__(y)
            rest = f - 1 - C2 * y**2 - C_LOG * y**4 * mp.log(y) - C5 * y**5
            rest -= C6 * y**6 + C7 * y**7
            return rest / y**4

        a, b = remainder("1e-3"), remainder("5e-4")
        # The remainder is c4 + O(y^4).
        return (16 * b - a) / 15


C4 = series_c4()


# Large y: F = y Q(1/y^2) with Q(r) = sum_k K binom(1/2, k) Gamma(3+2k)
# eta(3+2k) r^k, the expansion of sqrt(x^2 + y^2) in x^2/y^2 under the
# Fermi-Dirac moments. It is asymptotic: its error falls to a minimum near
# k = y/2 and grows past it.
def asymptotic_coefficient(k):
    return K * mp.binomial(mpf(1) / 2, k) * mp.gamma(3 + 2 * k) * mp.altzeta(3 + 2 * k)


# Chebyshev series in log y over [lo, hi].
def chebyshev_coefficients(lo, hi, n=96):
    a, b = mp.log(lo), mp.log(hi)
    xs = [mp.cos(mp.pi * (k + mpf(1) / 2) / n) for k in range(n)]
    fs = [f_exact(mp.exp((a + b) / 2 + (b - a) / 2 * x)) for x in xs]
    cs = []
    for j in range(n):
        s = mp.fsum(fs[k] * mp.cos(mp.pi * j * (k + mpf(1) / 2) / n) for k in range(n))
        cs.append((2 if j else 1) * s / n)
    return cs


class Neutrino:
    """F's pieces for a format, as the library sums them."""

    def __init__(self, fmt, series_below, asymptotic_from, cheb, asym):
        r = fmt.round
        self.fmt = fmt
        self.series_below = r(series_below)
        self.asymptotic_from = r(asymptotic_from)
        self.log_floor = fmt.min_normal
        self.series = [r(C5), r(C4), 0.0, r(C2)]
        self.series_log = r(C_LOG)
        lo, hi = mp.log(self.series_below), mp.log(self.asymptotic_from)
        self.cheb_mid = r((lo + hi) / 2)
        self.cheb_scale = r(2 / (hi - lo))
        self.cheb = [r(c) for c in cheb]
        self.asymptotic = [r(c) for c in reversed(asym)]

    # The library's operations, in the format's arithmetic.
    def eval(self, y):
        t = self.fmt.np
        y = t(y)
        lit = lambda v: t(v)
        log = lambda v: t(np.log(t(v)))

        def horner(cs, x):
            acc = lit(cs[0])
            for c in cs[1:]:
                acc = t(t(acc * x) + lit(c))
            return acc

        if y <= lit(self.series_below):
            ys = y
            ys2 = t(ys * ys)
            lg = log(max(ys, lit(self.log_floor)))
            inner = t(horner(self.series, ys) + t(t(ys2 * lg) * lit(self.series_log)))
            return t(t(ys2 * inner) + lit(1.0))
        if y >= lit(self.asymptotic_from):
            r = t(lit(1.0) / t(y * y))
            return t(y * horner(self.asymptotic, r))
        x = t(t(log(y) - lit(self.cheb_mid)) * lit(self.cheb_scale))
        cs = self.cheb
        x2 = t(x * lit(2.0))
        b1, b2 = lit(cs[-1]), lit(0.0)
        for c in reversed(cs[1:-1]):
            b1, b2 = t(t(t(x2 * b1) - b2) + lit(c)), b1
        return t(t(t(x * b1) - b2) + lit(cs[0]))


def choose_neutrino(fmt):
    """The cheapest pieces of F that meet the format's bound: the series below
    the largest power of two it reaches, then for each candidate start of the
    asymptotic expansion, its fewest terms and the fewest Chebyshev
    coefficients between, minimising their total."""
    target = F_BOUND[fmt.name] / 8

    def series_error(y):
        y = mpf(y)
        approx = 1 + y**2 * (C2 + C4 * y**2 + C5 * y**3 + C_LOG * y**2 * mp.log(y))
        return abs(approx / f_exact(y) - 1)

    series_below = max(
        2.0**-k for k in range(1, 40) if series_error(2.0**-k) <= target
    )
    asym = [asymptotic_coefficient(k) for k in range(40)]
    best = None
    for start in [16, 20, 24, 32, 40, 48, 64]:
        y = mpf(start)
        ref = f_exact(y)
        terms = None
        for n in range(1, 40):
            s = y * mp.fsum(asym[k] * y ** (-2 * k) for k in range(n))
            if abs(s / ref - 1) <= target:
                terms = n
                break
        if terms is None:
            continue
        cs = chebyshev_coefficients(mpf(series_below), y)
        degree = next(
            d for d in range(len(cs)) if mp.fsum(abs(c) for c in cs[d + 1 :]) <= target
        )
        cost = terms + degree
        if best is None or cost < best[0]:
            best = (cost, start, asym[:terms], cs[: degree + 1])
    _, start, a, cs = best
    return Neutrino(fmt, series_below, start, cs, a)


def check_neutrino(nu):
    """F's error, as the library evaluates it, at points over every region."""
    fmt = nu.fmt
    points = {0.0}
    lo, hi = math.log(1e-6), math.log(1e5)
    for i in range(401):
        points.add(fmt.round(math.exp(lo + (hi - lo) * i / 400)))
    for edge in [nu.series_below, nu.asymptotic_from]:
        x = fmt.np(edge)
        for _ in range(3):
            points.add(float(x))
            x = np.nextafter(x, fmt.np(np.inf))
        x = fmt.np(edge)
        for _ in range(3):
            x = np.nextafter(x, fmt.np(0))
            points.add(float(x))
    worst = (0.0, None)
    for y in sorted(points):
        got = nu.eval(y)
        err = abs(mpf(float(got)) / f_exact(mpf(y)) - 1)
        if err > worst[0]:
            worst = (float(err), y)
    bound = F_BOUND[fmt.name]
    print(
        f"F {fmt.name}: series below {nu.series_below}, Chebyshev degree "
        f"{len(nu.cheb) - 1}, asymptotic from {nu.asymptotic_from} with "
        f"{len(nu.asymptotic)} terms; worst error 2^{math.log2(worst[0]):.1f} "
        f"at y = {worst[1]} (bound 2^{math.log2(bound):.0f})",
        file=sys.stderr,
    )
    if worst[0] > bound:
        sys.exit(f"F {fmt.name}: error {worst[0]} above the bound {bound}")


# Curvature: S(x) = sum_n x^n / (2n+1)! and W(x) = sum_(n>=1) 4^n x^(n-1) /
# (2 (2n+1)!), Taylor polynomials on [-1, 1], each to the degree past which
# every term is below 2^-53 of the function's least value there.
SINC_DEGREE = 9
VOLUME_DEGREE = 10


def sinc_taylor():
    return [1 / mp.factorial(2 * n + 1) for n in range(SINC_DEGREE + 1)]


def volume_taylor():
    return [
        mpf(4) ** n / (2 * mp.factorial(2 * n + 1)) for n in range(1, VOLUME_DEGREE + 2)
    ]


def check_taylor():
    s_min = mp.sin(1)  # S(-1)
    w_min = (mp.sin(2) / 2 - 1) / -2  # W(-1)
    s_next = 1 / mp.factorial(2 * (SINC_DEGREE + 1) + 1)
    n = VOLUME_DEGREE + 2
    w_next = mpf(4) ** n / (2 * mp.factorial(2 * n + 1))
    if s_next / s_min > 2.0**-53 or w_next / w_min > 2.0**-53:
        sys.exit("S or W: the Taylor polynomials stop too early")


# Gauss-Legendre rules on [0, 1], weights summing to 1.


@functools.lru_cache(None)
def gauss_legendre(n):
    with mp.workdps(50):
        xs, ws = [], []
        for i in range(1, n + 1):
            x = mp.cos(mp.pi * (i - mpf(1) / 4) / (n + mpf(1) / 2))
            for _ in range(100):
                p0, p1 = mpf(1), x
                for k in range(2, n + 1):
                    p0, p1 = p1, ((2 * k - 1) * x * p1 - (k - 1) * p0) / k
                dp = n * (x * p1 - p0) / (x * x - 1)
                dx = p1 / dp
                x -= dx
                if abs(dx) < mpf(10) ** -45:
                    break
            xs.append((1 - x) / 2)
            ws.append(1 / ((1 - x * x) * dp * dp))
        order = sorted(range(n), key=lambda i: xs[i])
        return [xs[i] for i in order], [ws[i] for i in order]


# The rules' check


def f_fast(nu, y):
    """F(y) from [nu]'s pieces in mpmath, unrounded coefficients: within
    2^-51 of F, the integrand's F in the rules' check, where both sides of
    each comparison read it."""
    y = abs(mpf(y))
    if y <= nu.series_below_mp:
        if y == 0:
            return mpf(1)
        return 1 + y**2 * (C2 + C4 * y**2 + C5 * y**3 + C_LOG * y**2 * mp.log(y))
    if y >= nu.asymptotic_from_mp:
        r = 1 / (y * y)
        return y * mp.fsum(a * r**k for k, a in enumerate(nu.asym_mp))
    lo, hi = mp.log(nu.series_below_mp), mp.log(nu.asymptotic_from_mp)
    x = (2 * mp.log(y) - lo - hi) / (hi - lo)
    return _cheb(nu.cheb_mp, x)


def _cheb(cs, x):
    b1, b2 = mpf(0), mpf(0)
    for c in reversed(cs[1:]):
        b1, b2 = 2 * x * b1 - b2 + c, b1
    return x * b1 - b2 + cs[0]


# Exact constants: c, k_B, h, e and sigma are the SI's; G is CODATA 2022's
# (2018's is the same value).
C_LIGHT = mpf(299792458)
K_B = mpf("1.380649e-23")
H_PLANCK = mpf("6.62607015e-34")
EV = mpf("1.602176634e-19")
G = mpf("6.67430e-11")
SIGMA = 2 * mp.pi**5 * K_B**4 / (15 * H_PLANCK**3 * C_LIGHT**2)
MPC = 648000 / mp.pi * 149597870700 * 10**6
T_NCDM = mpf("0.71611")
C_UR = mpf(7) / 8 * (mpf(4) / 11) ** (mpf(4) / 3)
C_NU = mpf(7) / 8 * T_NCDM**4


class Model:
    """A cosmology, h in units of 100 km s^-1 Mpc^-1, T in K, masses in eV."""

    def __init__(self, nu, omega_cb, omega_k, w0, wa, h, t_cmb, n_eff, masses):
        self.nu = nu
        self.omega_cb, self.omega_k = mpf(omega_cb), mpf(omega_k)
        self.w0, self.wa = mpf(w0), mpf(wa)
        h0 = mpf(h) * 100 * 1000 / MPC
        self.omega_g = 32 * mp.pi * G * SIGMA * mpf(t_cmb) ** 4 / (3 * C_LIGHT**3 * h0**2)
        self.ur = C_UR * mpf(n_eff)
        t = mpf(t_cmb) if t_cmb > 0 else mpf(1)
        self.y = [mpf(m) * EV / (K_B * T_NCDM * t) for m in masses]
        self.omega_de = 1 - self.omega_cb - self.omega_k - self.radiation(mpf(1))

    def radiation(self, a):
        massive = mp.fsum(f_fast(self.nu, y * a) - 1 for y in self.y)
        return self.omega_g + self.omega_g * (self.ur + C_NU * massive)

    def terms(self, a, ln_a, one_minus_a):
        de = mp.exp(-3 * (1 + self.w0 + self.wa) * ln_a - 3 * self.wa * one_minus_a)
        return [
            self.omega_cb * a,
            self.omega_k * a * a,
            self.omega_de * a**4 * de,
            self.radiation(a),
        ]

    def a4e2(self, a, ln_a, one_minus_a):
        return mp.fsum(self.terms(a, ln_a, one_minus_a))

    def floors(self, lo, hi, n=400):
        """The least E^2 and the least a^4 E^2 over the sum of its terms'
        magnitudes on [lo, hi]."""
        e2, q = mpf("inf"), mpf("inf")
        for i in range(n + 1):
            a = lo + (hi - lo) * mpf(i) / n
            if a <= 0:
                continue
            ts = self.terms(a, mp.log(a), 1 - a)
            total = mp.fsum(ts)
            e2 = min(e2, total / a**4)
            q = min(q, total / mp.fsum(abs(t) for t in ts))
        return e2, q


# The integrals, as the library writes them.


def distance_integrand(m, cube):
    def f(v):
        u = 1 - v
        a = u * u
        e2 = m.a4e2(a, 2 * mp.log1p(-v), v * (2 - v))
        return 2 * (u * a if cube else u) / mp.sqrt(e2)

    return f


def age_integrand(m):
    def f(s):
        a = s**4
        return 4 * s**7 / mp.sqrt(m.a4e2(a, 4 * mp.log(s), 1 - a))

    return f


def rule_sum(f, end, n, fmt):
    xs, ws = gauss_legendre(n)
    return end * mp.fsum(
        mpf(fmt.round(w)) * f(end * mpf(fmt.round(x))) for x, w in zip(xs, ws)
    )


# The validation box.
BOX = {
    "omega_cb": (0.01, 3.0),
    "omega_k": (-4.5, 2.0),
    "w0": (-3.0, 1.0),
    "wa": (-3.0, 2.0),
    "h": (0.4, 1.0),
    "t_cmb": (0.0, 3.0),
    "n_eff": (0.0, 5.0),
    "mass": (0.0, 1.0),
}
Z_DISTANCE = 1100.0
Z_AGE = 1e6


def draw(rnd):
    while True:
        w0, wa = rnd.uniform(*BOX["w0"]), rnd.uniform(*BOX["wa"])
        if w0 + wa < 0:
            break
    lo, hi = BOX["omega_cb"]
    params = dict(
        omega_cb=math.exp(rnd.uniform(math.log(lo), math.log(hi))),
        omega_k=rnd.uniform(*BOX["omega_k"]),
        w0=w0,
        wa=wa,
        h=rnd.uniform(*BOX["h"]),
        t_cmb=rnd.choice([0.0, rnd.uniform(*BOX["t_cmb"])]),
        n_eff=rnd.uniform(*BOX["n_eff"]),
        masses=[rnd.uniform(*BOX["mass"]) for _ in range(rnd.randint(0, 3))],
    )
    z = math.expm1(rnd.uniform(0, math.log1p(Z_DISTANCE)))
    zt = math.expm1(rnd.uniform(0, math.log1p(Z_AGE)))
    return params, rnd.choice([z, Z_DISTANCE]), rnd.choice([zt, Z_AGE])


def corners():
    """The box's corners at the largest redshifts, w0 + wa < 0 kept by moving
    wa to -w0 - 0.01 where the corner breaks it."""
    keys = ["omega_cb", "omega_k", "w0", "wa", "h", "t_cmb", "n_eff", "mass"]
    out = []
    for bits in range(1 << len(keys)):
        p = {k: BOX[k][(bits >> i) & 1] for i, k in enumerate(keys)}
        if p["w0"] + p["wa"] >= 0:
            p["wa"] = -p["w0"] - 0.01
        mass = p.pop("mass")
        p["masses"] = [mass]
        out.append((p, Z_DISTANCE, Z_AGE))
    return out


CANDIDATES = {"distance": [16, 20, 24, 32, 40, 48, 56, 64, 80, 96], "age": [16, 20, 24, 32, 40, 48, 56, 64, 80, 96]}


def measure(args):
    """Each rule's error per node count on one cosmology, with the range's
    floors; None where a^4 E^2 is not positive on the range."""
    nu, counts, (params, z, zt) = args
    m = Model(nu, **params)
    rows = []
    z, zt = mpf(z), mpf(zt)
    az = 1 / (1 + z)
    e2, q = m.floors(az, mpf(1))
    if q > 0:
        vz = 1 - 1 / mp.sqrt(1 + z)
        for kind, cube in [("distance", False), ("lookback", True)]:
            f = distance_integrand(m, cube)
            exact = mp.quad(f, mp.linspace(0, vz, 17))
            errs = {
                (fmt.name, n): float(abs(rule_sum(f, vz, n, fmt) / exact - 1))
                for fmt in FORMATS
                for n in counts[fmt.name]["distance"]
            }
            rows.append((kind, float(e2), float(q), errs, params, float(z)))
    azt = 1 / (1 + zt)
    e2, q = m.floors(mpf(0), azt)
    if q > 0:
        sz = (1 + zt) ** (-mpf(1) / 4)
        f = age_integrand(m)
        exact = mp.quad(f, mp.linspace(0, sz, 17))
        errs = {
            (fmt.name, n): float(abs(rule_sum(f, sz, n, fmt) / exact - 1))
            for fmt in FORMATS
            for n in counts[fmt.name]["age"]
        }
        rows.append(("age", float(e2), float(q), errs, params, float(zt)))
    return rows


