def ml_float(x):
    """[x] as a hexadecimal literal without trailing zeros: 0x1.8p-3."""
    h = float(x).hex()
    mant, exp = h.split("p")
    if "." in mant:
        mant = mant.rstrip("0").rstrip(".")
    return f"{mant}p{exp}"


def ml_array(name, xs):
    """A record field holding an array, laid out as ocamlformat lays it."""
    items = "; ".join(ml_float(x) for x in xs)
    one = f"    {name} = [| {items} |];"
    if len(one) <= 80:
        return [one]
    two = f"      [| {items} |];"
    if len(two) <= 80:
        return [f"    {name} =", two]
    return [f"    {name} =", "      [|"] + [f"        {ml_float(x)};" for x in xs] + ["      |];"]


def ml_scalar(name, x):
    return [f"    {name} = {ml_float(x)};"]


def emit(nus, rules):
    out = [HEADER, FIELDS]
    for fmt in FORMATS:
        nu = nus[fmt.name]
        r = fmt.round
        dn, dw = gauss_legendre(rules[fmt.name]["distance"])
        an, aw = gauss_legendre(rules[fmt.name]["age"])
        out.append(f"let {fmt.name} =")
        out.append("  {")
        body = []
        body += ml_array("distance_nodes", [r(x) for x in dn])
        body += ml_array("distance_weights", [r(x) for x in dw])
        body += ml_array("age_nodes", [r(x) for x in an])
        body += ml_array("age_weights", [r(x) for x in aw])
        body += ml_scalar("f_series_below", nu.series_below)
        body += ml_array("f_series", nu.series)
        body += ml_scalar("f_series_log", nu.series_log)
        body += ml_scalar("f_log_floor", nu.log_floor)
        body += ml_scalar("f_cheb_mid", nu.cheb_mid)
        body += ml_scalar("f_cheb_scale", nu.cheb_scale)
        body += ml_array("f_cheb", nu.cheb)
        body += ml_scalar("f_asymptotic_from", nu.asymptotic_from)
        body += ml_array("f_asymptotic", nu.asymptotic)
        body += ml_array("sinc_taylor", [r(c) for c in reversed(sinc_taylor())])
        body += ml_array("volume_taylor", [r(c) for c in reversed(volume_taylor())])
        out += body
        out.append("  }")
        out.append("")
    return "\n".join(out)


def write(path, text, check):
    old = path.read_text() if path.exists() else ""
    if old == text:
        return
    if check:
        diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path), "generated", lineterm="")
        sys.exit("\n".join(list(diff)[:40]))
    path.write_text(text)


def report(rows, floors, counts):
    """Per rule, format and node count, log2 of the largest relative error
    over the drawn cosmologies whose q is at least each floor."""
    print(
        "q is the least a^4 E^2 over |Omega_cb a| + |Omega_k a^2| + |Omega_de a^4 f_de(a)|"
        " + Omega_r(a) on the range a function integrates; each cell is"
        " nodes:log2(worst relative error)",
        file=sys.stderr,
    )
    for kind in ["distance", "lookback", "age"]:
        rs = [r for r in rows if r[0] == kind]
        print(f"{kind}: {len(rs)} cosmologies", file=sys.stderr)
        for fmt in FORMATS:
            cands = counts[fmt.name]["age" if kind == "age" else "distance"]
            for floor in floors:
                kept = [r for r in rs if r[2] >= floor]
                cells = []
                for n in cands:
                    worst = max((r[3][(fmt.name, n)] for r in kept), default=0.0)
                    cells.append(f"{n}:{math.log2(worst + 2.0**-200):6.1f}")
                print(f"  {fmt.name} q>={floor:<5} ({len(kept):4}) " + " ".join(cells), file=sys.stderr)


# The floor of q, the least a^4 E^2 over the sum of its terms' magnitudes on
# the range a function integrates, that the validation box requires, and the
# node counts the run chooses from: the smallest that meets the bound.
FLOOR = 0.3
COUNTS = {"float32": [16, 20, 24, 32], "float64": [48, 56, 64, 72, 80]}


def prepare_fast(nu):
    nu.series_below_mp = mpf(nu.series_below)
    nu.asymptotic_from_mp = mpf(nu.asymptotic_from)
    nu.cheb_mp = chebyshev_coefficients(nu.series_below_mp, nu.asymptotic_from_mp)[: len(nu.cheb) + 8]
    nu.asym_mp = [asymptotic_coefficient(k) for k in range(len(nu.asymptotic))]


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="write nothing; fail if the file would change")
    parser.add_argument("--draws", type=int, default=1000, help="cosmologies drawn from the box")
    parser.add_argument("--explore", action="store_true", help="print each rule's error per node count and floor")
    parser.add_argument("--no-box", action="store_true", help="skip the rules' check, with the largest counts")
    args = parser.parse_args()
    check_taylor()
    nus = {}
    for fmt in FORMATS:
        nus[fmt.name] = choose_neutrino(fmt)
        check_neutrino(nus[fmt.name])
    if not args.no_box:
        nu = nus["float64"]
        prepare_fast(nu)
        rnd = random.Random(20261007)
        samples = corners() + [draw(rnd) for _ in range(args.draws)]
        with Pool() as pool:
            counts = {
                fmt.name: {"distance": CANDIDATES["distance"], "age": CANDIDATES["age"]}
                if args.explore
                else {"distance": COUNTS[fmt.name], "age": COUNTS[fmt.name]}
                for fmt in FORMATS
            }
            rows = [r for rs in pool.map(measure, [(nu, counts, s) for s in samples]) for r in rs]
            pool.close()
            pool.join()
        report(rows, [0.0, 0.05, 0.1, 0.2, 0.3, 0.5], counts)
        if args.explore:
            return
        rules = {fmt.name: {} for fmt in FORMATS}
        for fmt in FORMATS:
            target = BOUND[fmt.name] / 4
            for rule, kinds in [("distance", ["distance", "lookback"]), ("age", ["age"])]:
                kept = [r for r in rows if r[0] in kinds and r[2] >= FLOOR]
                for n in COUNTS[fmt.name]:
                    worst = max(r[3][(fmt.name, n)] for r in kept)
                    if worst <= target:
                        break
                else:
                    sys.exit(f"{rule} {fmt.name}: no count meets 2^{math.log2(target):.0f}")
                rules[fmt.name][rule] = n
                print(
                    f"{rule} {fmt.name}: {n} nodes, worst 2^{math.log2(worst + 2.0**-200):.1f} "
                    f"over {len(kept)} cosmologies with q >= {FLOOR}",
                    file=sys.stderr,
                )
    else:
        rules = {fmt.name: {"distance": COUNTS[fmt.name][-1], "age": COUNTS[fmt.name][-1]} for fmt in FORMATS}
    write(TABLES, emit(nus, rules), args.check)


if __name__ == "__main__":
    main()
