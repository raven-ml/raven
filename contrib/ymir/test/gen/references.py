spec = importlib.util.spec_from_file_location("tables", HERE / "cosmology.py")
tables = importlib.util.module_from_spec(spec)
spec.loader.exec_module(tables)

mp.dps = 40


# F to 40 digits: the series below 1e-8, Chebyshev pieces in log y, and the
# asymptotic expansion from 256, each checked against quadrature.

F_LO, F_HI, F_PIECES, F_DEGREE = mpf("1e-8"), mpf(256), 32, 72


F_TABLE = []


def f_table():
    """F's Chebyshev pieces, computed once in the main process and handed to
    each worker."""
    if not F_TABLE:
        lo, hi = mp.log(F_LO), mp.log(F_HI)
        w = (hi - lo) / F_PIECES
        with Pool() as pool:
            F_TABLE.extend(
                pool.map(_piece, [(mp.exp(lo + i * w), mp.exp(lo + (i + 1) * w)) for i in range(F_PIECES)])
            )
            pool.close()
            pool.join()
    return F_TABLE


def _set_table(table):
    F_TABLE[:] = table


def _piece(bounds):
    with mp.workdps(45):
        return tables.chebyshev_coefficients(bounds[0], bounds[1], n=F_DEGREE)


ASYM = [tables.asymptotic_coefficient(k) for k in range(40)]


def f_ref(y):
    y = abs(mpf(y))
    if y == 0:
        return mpf(1)
    if y < F_LO:
        c = tables
        return 1 + y**2 * (c.C2 + c.C4 * y**2 + c.C5 * y**3 + c.C_LOG * y**2 * mp.log(y) + c.C6 * y**4 + c.C7 * y**5)
    if y >= F_HI:
        r = 1 / (y * y)
        return y * mp.fsum(a * r**k for k, a in enumerate(ASYM))
    lo, hi = mp.log(F_LO), mp.log(F_HI)
    w = (hi - lo) / F_PIECES
    i = min(int((mp.log(y) - lo) / w), F_PIECES - 1)
    a, b = lo + i * w, lo + (i + 1) * w
    x = (2 * mp.log(y) - a - b) / (b - a)
    return tables._cheb(f_table()[i], x)


def check_f_ref():
    for y in ["1e-9", "3e-7", "0.01", "0.5", "1", "3.7", "40", "200", "300", "5000"]:
        with mp.workdps(45):
            exact = tables.f_exact.__wrapped__(mpf(y))
        if abs(f_ref(y) / exact - 1) > mpf("1e-31"):
            sys.exit(f"F's reference table misses at y = {y}")


# The models


class Spec:
    def __init__(self, name, h0, omega_cb, omega_k=0.0, w0=-1.0, wa=0.0, t_cmb=2.7255, n_eff=3.046, m_nu=(), codata=2022):
        self.name, self.h0, self.omega_cb, self.omega_k = name, h0, omega_cb, omega_k
        self.w0, self.wa, self.t_cmb, self.n_eff = w0, wa, t_cmb, n_eff
        self.m_nu, self.codata = list(m_nu), codata
        self.single = False

    def round(self, x):
        """[x] as the model's dtype holds it."""
        import numpy as np

        return float(np.float32(x)) if self.single else float(x)

    def float32(self):
        """The same model with every parameter rounded to float32, named
        <name>/f32, whose redshifts round to float32 too."""
        import numpy as np

        r = lambda x: float(np.float32(x))
        s = Spec(
            self.name + "/f32", r(self.h0), r(self.omega_cb), r(self.omega_k), r(self.w0), r(self.wa),
            r(self.t_cmb), r(self.n_eff), [r(m) for m in self.m_nu], self.codata,
        )
        s.single = True
        return s

    def line(self):
        m = ",".join(repr(float(x)) for x in self.m_nu) or "-"
        fields = [
            f"codata={self.codata}",
            f"h0={self.h0!r}",
            f"omega_cb={self.omega_cb!r}",
            f"omega_k={self.omega_k!r}",
            f"w0={self.w0!r}",
            f"wa={self.wa!r}",
            f"t_cmb={self.t_cmb!r}",
            f"n_eff={self.n_eff!r}",
            f"m_nu={m}",
        ]
        return f"model {self.name} " + " ".join(fields)


