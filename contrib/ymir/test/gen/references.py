def planck_class():
    s = Spec("planck2018", 67.66, (0.02242 + 0.11933) / 0.6766**2, m_nu=[0.06])
    s.class_params = {"omega_b": 0.02242, "omega_cdm": 0.11933, "N_ur": float(3.046 - (mpf("0.71611") ** 4 / (mpf(4) / 11) ** (mpf(4) / 3)))}
    return s


Z_CLASS = [0.01, 0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 100.0, 1000.0]


def class_values(s):
    import numpy as np
    from classy import Class
    from scipy.interpolate import CubicSpline

    p = {
        "h": s.h0 / 100,
        "T_cmb": s.t_cmb,
        "Omega_k": s.omega_k,
        "output": "",
        "tol_background_integration": 1e-12,
        "background_Nloga": 200000,
        **s.class_params,
    }
    if s.m_nu:
        p["N_ncdm"] = len(s.m_nu)
        p["m_ncdm"] = ",".join(repr(m) for m in s.m_nu)
        p["T_ncdm"] = ",".join(["0.71611"] * len(s.m_nu))
    if s.w0 != -1.0 or s.wa != 0.0:
        p.update({"Omega_Lambda": 0.0, "w0_fld": s.w0, "wa_fld": s.wa, "use_ppf": "yes"})
    c = Class()
    c.set(p)
    c.compute()
    bg = c.get_background()
    z_bg = bg["z"][::-1]
    t_bg = bg["proper time [Gyr]"][::-1]
    age_at = CubicSpline(np.log1p(z_bg), t_bg)
    age0 = float(c.age())
    out = [f"{s.name} age 0.0 {age0!r}"]
    for z in Z_CLASS:
        h = float(c.Hubble(z)) * 299792.458
        chi = float(c.comoving_distance(z))
        da = float(c.angular_distance(z))
        out += [
            f"{s.name} hubble {z!r} {h!r}",
            f"{s.name} comoving_distance {z!r} {chi!r}",
            f"{s.name} transverse {z!r} {da * (1 + z)!r}",
            f"{s.name} angular_diameter_distance {z!r} {da!r}",
            f"{s.name} lookback_time {z!r} {age0 - float(age_at(math.log1p(z)))!r}",
            f"{s.name} age {z!r} {float(age_at(math.log1p(z)))!r}",
        ]
    c.struct_cleanup()
    return out


# astropy


Z_ASTROPY = [0.01, 0.1, 0.5, 1.0, 2.0, 5.0, 10.0, 100.0, 1000.0]
ASTROPY_AGE_BELOW = 100.0


def astropy_models():
    return [_at(s, [0.0] + Z_ASTROPY) for s in _astropy_specs()]


def _at(s, zs):
    s.zs = zs
    return s


def _astropy_specs():
    return [
        Spec("flat_lcdm", 70.0, 0.3, t_cmb=2.725, n_eff=3.04, codata=2018),
        Spec("open_lcdm", 70.0, 0.3, omega_k=0.1, t_cmb=2.725, n_eff=3.04, codata=2018),
        Spec("closed_lcdm", 70.0, 0.3, omega_k=-0.1, t_cmb=2.725, n_eff=3.04, codata=2018),
        Spec("curved_w0wa", 68.0, 0.31, omega_k=0.02, w0=-0.9, wa=-0.3, t_cmb=2.7255, n_eff=3.046, codata=2018),
        Spec("cold_w0wa", 70.0, 0.3, omega_k=0.05, w0=-1.1, wa=0.2, t_cmb=0.0, n_eff=3.046, codata=2018),
    ]


def astropy_values(s):
    import astropy.units as u
    from astropy.cosmology import w0waCDM

    c = w0waCDM(
        H0=s.h0, Om0=s.omega_cb, Ode0=1 - s.omega_cb - s.omega_k, w0=s.w0, wa=s.wa,
        Tcmb0=s.t_cmb, Neff=s.n_eff, m_nu=0.0 * u.eV,
    )
    # astropy's Ode0 leaves radiation to curvature; the library closes the
    # budget with dark energy. Move the radiation from Ok0 to Ode0.
    c = w0waCDM(
        H0=s.h0, Om0=s.omega_cb, Ode0=1 - s.omega_cb - s.omega_k - c.Ogamma0 - c.Onu0,
        w0=s.w0, wa=s.wa, Tcmb0=s.t_cmb, Neff=s.n_eff, m_nu=0.0 * u.eV,
    )
    return _astropy_rows(s.name, c)


def _astropy_rows(name, c):
    v = lambda q, unit: float(q.to_value(unit))
    out = [f"{name} age 0.0 {v(c.age(0), 'Gyr')!r}"]
    for z in Z_ASTROPY:
        out += [
            f"{name} hubble {z!r} {v(c.H(z), 'km s-1 Mpc-1')!r}",
            f"{name} comoving_distance {z!r} {v(c.comoving_distance(z), 'Mpc')!r}",
            f"{name} transverse {z!r} {v(c.comoving_transverse_distance(z), 'Mpc')!r}",
            f"{name} angular_diameter_distance {z!r} {v(c.angular_diameter_distance(z), 'Mpc')!r}",
            f"{name} lookback_time {z!r} {v(c.lookback_time(z), 'Gyr')!r}",
        ]
        # astropy integrates the age from z to infinity, adaptively: at z =
        # 1000 it misses by 5e-7.
        if z <= ASTROPY_AGE_BELOW:
            out.append(f"{name} age {z!r} {v(c.age(z), 'Gyr')!r}")
    return out


def astropy_planck18():
    from astropy.cosmology import Planck18

    rows = []
    for line in _astropy_rows("planck2018", Planck18):
        _, fn, _, _ = line.split()
        if fn in ("comoving_distance", "age"):
            rows.append(line)
    return rows


# Output


def golden(models, rows):
    return HEADER + "".join(m.line() + "\n" for m in models) + "".join(r + "\n" for r in rows)


def write(path, text, check):
    old = path.read_text() if path.exists() else ""
    if old == text:
        return
    if check:
        diff = difflib.unified_diff(old.splitlines(), text.splitlines(), str(path), "generated", lineterm="")
        sys.exit("\n".join(list(diff)[:40]))
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text)


def compare(name, rows, reference, tol):
    """The largest relative difference per function between [rows] and the
    mpmath values of the same models, each of which must stay below [tol]."""
    ref = {}
    for line in reference:
        m, fn, z, v = line.split()
        ref[(m, fn, float(z.split("/")[0]))] = float(v)
    worst = {}
    for line in rows:
        m, fn, z, v = line.split()
        key = (m, fn, float(z))
        if key not in ref:
            sys.exit(f"{name}: no mpmath value for {key}")
        if ref[key] != 0:
            err = abs(float(v) / ref[key] - 1)
            if err > worst.get(fn, (0.0, None))[0]:
                worst[fn] = (err, key)
    for fn, (err, key) in sorted(worst.items()):
        print(f"{name} against mpmath: {fn} worst {err:.2e} at {key}", file=sys.stderr)
    bad = [fn for fn, (err, _) in worst.items() if err > tol]
    if bad:
        sys.exit(f"{name} disagrees with mpmath beyond {tol} in {bad}")


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true", help="write nothing; fail if a golden would change")
    args = parser.parse_args()
    f_table()
    check_f_ref()
    mp_models = MPMATH_MODELS + [m.float32() for m in MPMATH_MODELS]
    cls = ccl_models() + [_at(planck_class(), [0.0] + Z_CLASS)]
    ast = astropy_models()
    # Each golden's models in mpmath, at that golden's redshifts.
    sets = [mp_models, cls, ast]
    with Pool(initializer=_set_table, initargs=(f_table(),)) as pool:
        exact = pool.map(exact_values, [s for models in sets for s in models])
        pool.close()
        pool.join()
    rows_of = []
    for models in sets:
        rows_of.append([r for _ in models for r in exact.pop(0)])
    mp_rows, cls_exact, ast_exact = rows_of
    write(GOLDEN / "mpmath.golden", golden(mp_models, mp_rows), args.check)
    class_rows = [r for s in cls for r in class_values(s)]
    compare("CLASS", class_rows, cls_exact, 1e-6)
    write(GOLDEN / "class.golden", golden(cls, class_rows), args.check)
    ast_rows = [r for s in ast for r in astropy_values(s)]
    compare("astropy", ast_rows, ast_exact, 1e-7)
    p18 = astropy_planck18()
    write(GOLDEN / "astropy.golden", golden(ast + [PLANCK18], ast_rows + p18), args.check)


if __name__ == "__main__":
    main()
