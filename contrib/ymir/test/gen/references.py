# mpmath references: the library's integrals, at 30 digits.

C = tables.C_LIGHT
MPC = tables.MPC
GYR = mpf(31557600) * 10**9
G = {2018: mpf("6.67430e-11"), 2022: mpf("6.67430e-11")}


class Exact(tables.Model):
    def __init__(self, s):
        self.spec = s
        super().__init__(None, s.omega_cb, s.omega_k, s.w0, s.wa, mpf(s.h0) / 100, s.t_cmb, s.n_eff, s.m_nu)
        self.h0 = mpf(s.h0) * 1000 / MPC  # s^-1

    def radiation(self, a):
        massive = mp.fsum(f_ref(y * a) - 1 for y in self.y)
        return self.omega_g + self.omega_g * (self.ur + tables.C_NU * massive)


def quad(f, lo, hi):
    return mp.quad(f, mp.linspace(lo, hi, 9))


def exact_values(s):
    """Every function of [s] at each redshift, as value lines."""
    mp.dps = 30
    m = Exact(s)
    d_h = C / m.h0 / MPC  # Mpc
    t_h = 1 / m.h0 / GYR  # Gyr
    out = []

    def put(fn, z, v):
        out.append(f"{s.name} {fn} {z} {float(v)!r}")

    r = s.round

    def e2_at(z):
        a = 1 / (1 + z)
        return m.a4e2(a, -mp.log1p(z), z / (1 + z)) * (1 + z) ** 4

    def chi_hat(z):
        vz = 1 - 1 / mp.sqrt(1 + z)
        return quad(tables.distance_integrand(m, False), 0, vz) if z > 0 else mpf(0)

    def sinc(x):
        if x > 0:
            return mp.sinh(mp.sqrt(x)) / mp.sqrt(x)
        if x < 0:
            return mp.sin(mp.sqrt(-x)) / mp.sqrt(-x)
        return mpf(1)

    def wvol(x):
        return (sinc(4 * x) - 1) / (2 * x) if x != 0 else mpf(1) / 3

    for zf in map(r, getattr(s, "zs", Z_MPMATH)):
        z = mpf(zf)
        a = 1 / (1 + z)
        e2 = e2_at(z)
        terms = m.terms(a, -mp.log1p(z), z / (1 + z))
        total = mp.fsum(terms)
        names = ["cold_matter", "curvature", "dark_energy"]
        for name, t in zip(names, terms[:3]):
            put(f"density_parameter:{name}", zf, t / total)
        put("density_parameter:photons", zf, m.omega_g / total)
        put("density_parameter:neutrinos", zf, (terms[3] - m.omega_g) / total)
        h = mpf(s.h0) * mp.sqrt(e2)
        put("hubble", zf, h)
        h_si = m.h0 * mp.sqrt(e2)
        put("critical_density", zf, 3 * h_si**2 / (8 * mp.pi * G[s.codata]))
        ch = chi_hat(z)
        dm = ch * sinc(m.omega_k * ch * ch)
        put("comoving_distance", zf, d_h * ch)
        put("transverse", zf, d_h * dm)
        put("angular_diameter_distance", zf, d_h * dm / (1 + z))
        put("luminosity_distance", zf, d_h * dm * (1 + z))
        put("comoving_volume", zf, d_h**3 * ch**3 * wvol(m.omega_k * ch * ch))
        put("comoving_volume_element", zf, d_h**3 * dm**2 / mp.sqrt(e2))
        if z > 0:
            obs = r(zf * 1.001)
            put("luminosity_distance", f"{zf!r}/{obs!r}", d_h * dm * (1 + mpf(obs)))
            put("distance_modulus", zf, 5 * mp.log10(d_h * dm * (1 + z) * 10**5))
            vz = 1 - 1 / mp.sqrt(1 + z)
            put("lookback_time", zf, t_h * quad(tables.distance_integrand(m, True), 0, vz))
        else:
            put("lookback_time", zf, 0)
    for zf in map(r, getattr(s, "zs", Z_MPMATH) + Z_AGE):
        z = mpf(zf)
        sz = (1 + z) ** (-mpf(1) / 4)
        put("age", zf, t_h * quad(tables.age_integrand(m), 0, sz))
    return out


